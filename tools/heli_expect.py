#!/usr/bin/env python3
"""Expected pose/hold sequence for Baraka's heliport lanes, straight from source.

The MAME harness logs the SAG (image-data pointer) of P1's object every frame.
This prints what that log SHOULD collapse to: one (SAG, pose, ticks) row per
lane entry, derived by walking a_sa_windup / a_sa_helitest in src/MKSA.ASM and
resolving each multipart wrapper's FIRST piece through the .TBL records.

The first piece is what matters because the primary object carries it; the rest
of the wrapper hangs off the multipart chain and never lands in oimg.

    python tools/heli_expect.py                 # human-readable
    python tools/heli_expect.py --json out.json # for heli_check.py
"""
import argparse, glob, json, os, re, sys

# The RAM symbols the MAME harness pokes at.  These are BIT addresses out of
# src/mk2.map and they MOVE ON EVERY RELINK - deleting a couple of hundred
# lines of code shifted every one of them by +020h once, and the failure mode
# is silent: gstate reads garbage, every pointer reads null, and the run
# reports "starts=0" exactly as if the ROM had never booted.  So the harness
# does not hardcode them any more; this writes them out for it to read.
LUA_SYMS = ["gstate", "p1_char", "p2_char", "p1_obj", "p2_obj",
            "p1_proc", "p2_proc", "p2_bar", "f_colbox", "pf_ram",
            "objlst", "objlst2"]

LUA_HEADER = ("-- GENERATED by tools/heli_expect.py --lua-addrs.\n"
              "-- Bit addresses from src/mk2.map for THIS link.  Never"
              " hand-edit,\n-- and never copy them into the harness:"
              " they move whenever code size does.\n"
              "return {\n")


def map_symbols(names):
    """symbol -> bit address, from the linker map's two-column listing."""
    want, out = set(names), {}
    pat = re.compile(r"\b([0-9a-f]{8})\s+(\w+)")
    for line in open(os.path.join(ROOT, "src", "mk2.map"), errors="replace"):
        for m in pat.finditer(line):
            if m.group(2) in want:
                out[m.group(2)] = int(m.group(1), 16)
    return out


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def tbl_records():
    """label -> (w, h, anix, aniy, sag).  Later files win, like LOAD2's bind."""
    out = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "src", "*.TBL"))):
        L = open(f, encoding="utf-8", errors="surrogateescape").read().split("\n")
        for i, line in enumerate(L):
            m = re.match(r"^([A-Z0-9_]+):\s*$", line)
            if not m or i + 2 >= len(L):
                continue
            w = re.match(r"\s*\.word\s+(-?\d+),(-?\d+),(-?\d+),(-?\d+)", L[i + 1])
            s = re.match(r"\s*\.long\s+0?([0-9a-fA-F]+)[hH]\s*$", L[i + 2])
            if w and s:
                out[m.group(1)] = (int(w.group(1)), int(w.group(2)),
                                   int(w.group(3)), int(w.group(4)),
                                   int(s.group(1), 16))
    return out


def wrappers():
    """label -> [piece, ...] for `LABEL .long A,B,0' multiparts in the ASM."""
    out = {}
    for f in glob.glob(os.path.join(ROOT, "src", "*.ASM")):
        L = open(f, encoding="utf-8", errors="surrogateescape").read().split("\n")
        for i, line in enumerate(L):
            m = re.match(r"^([A-Z0-9_]+)\s*$", line)
            nxt = L[i + 1] if i + 1 < len(L) else ""
            if m and nxt.strip().startswith(".long"):
                body = nxt.split(".long", 1)[1]
            else:
                m = re.match(r"^([A-Z0-9_]+)\s+\.long\s+(.*)$", line)
                if not m:
                    continue
                body = m.group(2)
            pieces = [p.strip() for p in body.split(";")[0].split(",")]
            pieces = [p for p in pieces if p and p != "0"]
            if pieces and all(re.match(r"^[A-Z0-9_]+$", p) for p in pieces):
                out.setdefault(m.group(1), pieces)
    return out


def walk_lane(label, stop_on_jump):
    """Collapse the lane's rows into (pose, ticks, dx, dy) entries.

    Every row is one tick - both lanes are generated expanded to sleep 1 - so a
    repeated pose label IS the hold.  Command rows (ani_*) and their .word
    operands carry no tick, which is the whole reason a hook can sit mid-lane
    without shifting anything after it.

    dx/dy are the CUMULATIVE ani_adjustxy totals in force while the entry
    draws.  multi_adjust_xy adds them straight onto oxpos/oypos, so the dy
    column is the object's y track through the move and can be checked against
    a live trace tick for tick.  dx cannot be checked so directly - the engine
    negates it under b_fliph - so only its magnitude is comparable.
    """
    # a_sa_helivictim lives in MKST.ASM, beside the Shang wrappers it names
    # (they are file-local there); the two Baraka lanes are in MKSA.ASM.
    for src in ("MKSA.ASM", "MKST.ASM"):
        L = open(os.path.join(ROOT, "src", src),
                 encoding="latin-1").read().split(chr(10))
        if label in L:
            break
    else:
        raise SystemExit("no lane %s in MKSA.ASM or MKST.ASM" % label)
    i = L.index(label) + 1
    seq, pend = [], None
    cdx = cdy = 0
    while i < len(L):
        t = L[i].split(";")[0].strip()
        i += 1
        if not t:
            continue
        if t.startswith(".word"):
            if pend == "ani_adjustxy":
                a, b = t.split(".word", 1)[1].split(",")
                cdx += int(a.strip())
                cdy += int(b.strip())
                pend = None
            continue
        if not t.startswith(".long"):
            continue                      # a bare label (the loop target)
        body = t.split(".long", 1)[1].strip()
        head = body.split(",")[0].strip()
        if head == "0":
            break
        if head.startswith("ani_jump"):
            if stop_on_jump:
                break
            continue
        if head.startswith("ani_"):
            pend = head                   # ani_calla / ani_adjustxy: the next
            continue                      #   row is its operand, not a pose
        if pend == "ani_calla":
            pend = None
            continue                      # this .long is the hook address
        pend = None
        if seq and seq[-1][0] == head and seq[-1][2:] == [cdx, cdy]:
            seq[-1][1] += 1
        else:
            seq.append([head, 1, cdx, cdy])
    return seq


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json")
    ap.add_argument("--lua-addrs", metavar="PATH",
                    help="also write a Lua table of the RAM symbol addresses "
                         "the MAME harness needs, read straight from mk2.map")
    a = ap.parse_args()
    recs, wraps = tbl_records(), wrappers()
    out = {}
    bad = []
    # a_sa_helivictim is gone: the victim plays his OWN tables now and the
    # Shang lane was reference only.  heli_check verifies his HOLDS instead.
    for label in ("a_sa_windup", "a_sa_helitest"):
        rows = []
        for pose, ticks, cdx, cdy in walk_lane(label, stop_on_jump=True):
            piece = wraps.get(pose, [pose])[0]
            r = recs.get(piece)
            if not r:
                bad.append((label, pose, piece))
                continue
            rows.append(dict(pose=pose, piece=piece, ticks=ticks,
                             dx=cdx, dy=cdy, sag=r[4], w=r[0], h=r[1],
                             # every strip, so a caller can work out the
                             # DRAWN box and not just the anchor - which is
                             # what "is he clear of the top of the screen"
                             # actually needs
                             pieces=[list(recs[q]) for q in wraps.get(pose, [pose])
                                     if q in recs]))
        out[label] = rows
        print("%s: %d entries, %d ticks" %
              (label, len(rows), sum(r["ticks"] for r in rows)))
        for n, r in enumerate(rows):
            print("  %2d %-14s %-14s x%-2d dx=%+4d dy=%+4d sag=%08x %dx%d"
                  % (n, r["pose"], r["piece"], r["ticks"], r["dx"], r["dy"],
                     r["sag"], r["w"], r["h"]))
    if bad:
        print("\nUNRESOLVED (no .TBL record):", file=sys.stderr)
        for lab, pose, piece in bad:
            print("  %s %s -> %s" % (lab, pose, piece), file=sys.stderr)
        sys.exit(1)
    if a.json:
        json.dump(out, open(a.json, "w"), indent=1)
        print("\nwrote " + a.json)
    if a.lua_addrs:
        syms = map_symbols(LUA_SYMS)
        missing = [n for n in LUA_SYMS if n not in syms]
        if missing:
            print("mk2.map has no: " + ", ".join(missing), file=sys.stderr)
            sys.exit(1)
        with open(a.lua_addrs, "w") as f:
            f.write(LUA_HEADER)
            for n in LUA_SYMS:
                f.write("  %-9s = 0x%08x,\n" % (n, syms[n]))
            f.write("}\n")
        print("wrote " + a.lua_addrs)


main()
