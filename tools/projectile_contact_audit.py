#!/usr/bin/env python3
"""
projectile_contact_audit.py - who throws the contact height away, and why.

Section 3.4 of doc/TOURNAMENT_READINESS.md said "one aligned, nine to go".
That was a guess, and it is wrong. This counts.

`match_me_with_him` snaps a projectile object onto the VICTIM's anchor. That
is what lines a burst up horizontally, and it also discards the height the
projectile was actually flying at. For a STEERABLE shot that is visible:
Baraka's spark aimed at the shins hit low while the burst still bloomed at
chest height, which is the one this project fixed - by saving `oypos` across
the snap and putting it back.

So the audit is: at every snap site, is the contact height preserved? And for
the ones that discard it, is that a defect or a decision? The second question
is not answerable by pattern-matching, so this reports the SIGNALS that decide
it - a y offset applied after the snap, a velocity written into the burst, a
loop that copies the victim's velocity - and the reading lives in the doc.

  python tools/projectile_contact_audit.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
FILES = ("MKZAP.ASM", "MKPROP.ASM")

SAVE = re.compile(r"move\s+\*a8\(oypos\),(a\d+),w")
REST = re.compile(r"move\s+(a\d+),\*a8\(oypos\),w")
SNAP = re.compile(r"calla\s+match_me_with_him")
ADJ = re.compile(r"movi\s+0?([0-9a-fA-F]+)h,a1\s*$")
YVEL = re.compile(r"move\s+a\d+,\*a8\(oyvel\),l")
RIDE = re.compile(r"move\s+\*a10\(oyvel\),\*a8\(oyvel\),l")


def sites():
    out = []
    for fn in FILES:
        path = os.path.join(SRC, fn)
        if not os.path.exists(path):
            continue
        lines = open(path, encoding="latin-1",
                     errors="replace").read().splitlines()
        labels = []
        for i, ln in enumerate(lines):
            if ln[:1] not in (" ", "\t", "*", ";", ""):
                m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)", ln)
                if m:
                    labels.append((i, m.group(1)))
        for i, ln in enumerate(lines):
            code = ln.split(";")[0]
            if not SNAP.search(code):
                continue
            lbl = ""
            for at, l in reversed(labels):
                if at <= i:
                    lbl = l
                    break
            win_before = lines[max(i - 16, 0):i]
            win_after = lines[i + 1:min(i + 22, len(lines))]
            keeps = (any(SAVE.search(x) for x in win_before)
                     and any(REST.search(x) for x in win_after))
            sig = []
            if any(YVEL.search(x.split(";")[0]) for x in win_after):
                sig.append("writes oyvel")
            if any(RIDE.search(x.split(";")[0]) for x in win_after):
                sig.append("rides victim velocity")
            # A y offset only counts if it is the argument to multi_adjust_xy.
            # Matching any `movi X,a1` picked up 050000h - a 16.16 VELOCITY
            # for the blocked-hat bounce - and reported it as a 327,680 pixel
            # offset, which is the kind of number that should stop a reader
            # rather than get written down.
            for k, x in enumerate(win_after):
                if not re.search(r"calla\s+multi_adjust_xy", x.split(";")[0]):
                    continue
                for j in range(k - 1, max(k - 4, -1), -1):
                    m = ADJ.search(win_after[j].split(";")[0].rstrip())
                    if m:
                        v = int(m.group(1), 16)
                        if v:
                            sig.append("y offset +%d into multi_adjust_xy" % v)
                        break
                break
            out.append((fn, lbl, i + 1, keeps, sig))
    return out


def main():
    rows = sites()
    keep = [r for r in rows if r[3]]
    drop = [r for r in rows if not r[3]]
    print("# Projectile contact height\n")
    print("Generated by `tools/projectile_contact_audit.py`.\n")
    print("`match_me_with_him` snaps the burst onto the victim's anchor and")
    print("discards the height the projectile was flying at. On a level shot")
    print("that changes nothing - the projectile is spawned on the thrower's")
    print("anipoint, so its Y is already the victim's anchor Y. It only")
    print("matters for a STEERABLE shot, or when the two anchors sit at")
    print("different heights.\n")
    print("**%d snap sites: %d preserve the contact height, %d do not.**\n"
          % (len(rows), len(keep), len(drop)))
    print("| site | file | line | contact height | signals |")
    print("|---|---|---|---|---|")
    for fn, lbl, ln, keeps, sig in rows:
        print("| `%s` | %s | %d | %s | %s |"
              % (lbl, fn, ln, "kept" if keeps else "**discarded**",
                 ", ".join(sig) if sig else ""))
    print()
    print("A discarded height is not automatically a defect. The signals")
    print("column is what decides it: a y offset applied after the snap or a")
    print("velocity written into the burst means the site is placing the")
    print("effect deliberately, and restoring the flight height would break")
    print("that rather than fix it.")


if __name__ == "__main__":
    main()
