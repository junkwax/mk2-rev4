#!/usr/bin/env python3
"""
balance_audit.py - find outliers in the strike table.

A raw frame-data dump does not tell you what is WRONG with it.  What does is
comparing the same move across characters: every fighter has a high kick, a
sweep, an uppercut, and they are meant to be broadly comparable.  A record
that is well outside its family is either a deliberate character trait or a
mistake, and either way somebody should have decided it on purpose.

Groups records by FAMILY - the record name with the two-letter character code
stripped, so stk_lkhikick / stk_jxhikick / stk_hhhikick are one family - and
reports members more than a set ratio away from the family median.

This is a screening tool.  It finds things worth LOOKING at; it does not know
which are intentional.  Kintaro and Shao Kahn are bosses and will always show
up as outliers on damage, for instance, which is correct and not a finding.

Usage:
  python tools/balance_audit.py                 report
  python tools/balance_audit.py --ratio 2.0     looser threshold
"""
import csv, os, re, sys, argparse, statistics, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, "doc", "frame_data_records.csv")

# two-letter codes that prefix a record name inside its character's list
CODES = ("hh", "lk", "jc", "sa", "fn", "st", "rd", "nj", "jx", "go", "sk")
BOSSES = {"kintaro", "shao kahn"}


def family(record):
    """stk_lkhikick -> hikick ; stk_swipe -> swipe (no character code)."""
    n = record[4:] if record.startswith("stk_") else record
    n = n.lstrip("_")
    for c in CODES:
        if n.startswith(c) and len(n) > len(c):
            return n[len(c):].lstrip("_")
    return n


def main():
    ap = argparse.ArgumentParser()
    # 1.6 fires on nothing here.  MK2 balances by REACH, not damage:
    # damage is identical across characters for shared moves (hikick
    # 32/8, sweep 20/5, elbow 24/6) and reach spreads only 1.04-1.27x.
    # A threshold has to be calibrated to the data it screens.
    ap.add_argument("--ratio", type=float, default=1.15,
                    help="flag members this many times off the family median")
    ap.add_argument("--min-family", type=int, default=4,
                    help="ignore families smaller than this")
    args = ap.parse_args()

    if not os.path.exists(CSV):
        sys.exit("run tools/frame_data.py --csv doc/frame_data.csv first")

    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    fams = collections.defaultdict(list)
    for r in rows:
        fams[family(r["record"])].append(r)

    METRICS = [("reach", "reach"), ("hit", "damage on hit"),
               ("blk", "chip on block")]

    findings = []
    for fam, members in sorted(fams.items()):
        # de-duplicate: several characters share one record (nj_strikes etc.)
        uniq = {}
        for m in members:
            uniq.setdefault(m["record"], m)
        members = list(uniq.values())
        if len(members) < args.min_family:
            continue
        for key, label in METRICS:
            vals = []
            for m in members:
                try:
                    vals.append((int(m[key]), m))
                except (ValueError, TypeError):
                    pass
            if len(vals) < args.min_family:
                continue
            med = statistics.median(v for v, _ in vals)
            if med == 0:
                continue
            for v, m in vals:
                ratio = v / med
                if ratio >= args.ratio or (v > 0 and ratio <= 1 / args.ratio) or v == 0:
                    findings.append(dict(
                        fam=fam, metric=label, record=m["record"],
                        char=m["char"], value=v, median=med,
                        ratio=ratio, boss=m["char"] in BOSSES))

    print("# Strike-table outliers\n")
    print("Generated by `tools/balance_audit.py` from `doc/frame_data_records.csv`.")
    print("Families are the same move across characters; a member well off the")
    print("family median is either a deliberate trait or a mistake.\n")
    print("**This is a screening tool.** It finds things worth looking at, not")
    print("things that are wrong. Boss rows are marked - Kintaro and Shao Kahn")
    print("being outliers on damage is correct, not a finding.\n")

    real = [f for f in findings if not f["boss"]]
    boss = [f for f in findings if f["boss"]]

    def dump(title, items):
        print("\n## %s (%d)\n" % (title, len(items)))
        if not items:
            print("none")
            return
        print("| family | metric | record | char | value | family median | x |")
        print("|---|---|---|---|---|---|---|")
        for f in sorted(items, key=lambda f: (-abs(f["ratio"] - 1), f["fam"])):
            print("| %s | %s | %s | %s | %s | %g | %.2f |" % (
                f["fam"], f["metric"], f["record"], f["char"],
                f["value"], f["median"], f["ratio"]))

    dump("Non-boss outliers", real)
    dump("Boss outliers (expected)", boss)

    zero = [f for f in real if f["value"] == 0]
    if zero:
        print("\n## Zero values among non-boss records (%d)\n" % len(zero))
        print("A zero here means the move does no damage, or no chip on block.")
        print("Some are correct (grabs, setups). Worth confirming each.\n")
        for f in zero:
            print("- `%s` (%s): %s = 0" % (f["record"], f["char"], f["metric"]))

    uniform = []
    for fam, members in sorted(fams.items()):
        uniq = {}
        for m in members:
            uniq.setdefault(m["record"], m)
        members = list(uniq.values())
        if len(members) < args.min_family:
            continue
        dmg = {m["hit"] for m in members if m["char"] not in BOSSES}
        if len(dmg) == 1:
            uniform.append((fam, dmg.pop(), len(members)))
    if uniform:
        print()
        print("## Families with IDENTICAL damage across characters (%d)"
              % len(uniform))
        print()
        print("Worth knowing before tuning anything: MK2 does not separate")
        print("these moves by damage at all, only by reach and timing.")
        print()
        for fam, d, n in uniform:
            print("- `%s` - every character does %s (%d records)" % (fam, d, n))

    print("\n%d families examined, %d non-boss findings." % (len(fams), len(real)))


if __name__ == "__main__":
    main()
