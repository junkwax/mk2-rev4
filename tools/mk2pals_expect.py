#!/usr/bin/env python3
"""Write tools/mk2pals_expect.lua - what run_mk2pals_test.ps1 expects to see.

Two sets, both READ rather than typed:

    want[ochar]  the Start+HP costume, out of data/MK2PALS.IMG.  The IMG, not
                 src/MK2PALS.ASM, because the IMG is the authoring side: a
                 repaint that was never re-imported has to fail the rig, and
                 it cannot if the rig reads the same generated file the ROM
                 was built from.

    prev[ochar]  what character_palettes_4 held BEFORE this change, out of
                 this tree's src/.  That is the NEGATIVE CONTROL: a rig that
                 also passes against these is not reading the screen.

Run by the wrapper before every MAME launch; there is nothing to check here.
"""
import io
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import img_palette as ip                        # noqa: E402
from make_mk2pals import ROSTER, tree_palettes  # noqa: E402

REPO = HERE.parent
OUT = HERE / "mk2pals_expect.lua"

# character_palettes_4 rows 0-11 as they stood before the retail mirror
# costumes took the slot.  Kept here and nowhere else on purpose: this is the
# control, so it must not come from the table it is controlling.
PREVIOUS = ["TMBLACK_P", "LIUALT2_P", "JCALT1_P", "UGALTHP_P",
            "KITALT2_P", "MILALT2_P", "TMOVIE_P", "RADALT_P",
            "SUB_P", "REP_P", "SCORP_P", "JAXALT3_P"]


def main() -> int:
    img = dict(ip.palettes(REPO / "data" / "MK2PALS.IMG"))
    ours = tree_palettes(REPO)

    rows = []
    for spec, prev in zip(ROSTER, PREVIOUS):
        ochar, _code, who, _lib, _st, _go, pname, _bname = spec
        # The IMG is the authoring side, but records get RENAMED in IMGTOOL
        # (M2KTBLU_P is KTALT1_P there now) - make_mk2pals.py --check matches
        # them BY CONTENT and proves src/MK2PALS.ASM carries the same words, so
        # a renamed record falls back to the linked copy rather than failing.
        want = img.get(pname, ours.get(pname))
        if want is None:
            sys.exit("%s is in neither data/MK2PALS.IMG nor src/ - run make_mk2pals.py --apply" % pname)
        if prev not in ours:
            sys.exit("%s is gone from src/ - the negative control has no words" % prev)
        rows.append((ochar, who, pname, want, prev, ours[prev]))

    with io.open(OUT, "w", newline="\n") as f:
        f.write("-- GENERATED by tools/mk2pals_expect.py - do not edit.\n")
        f.write("-- want = the Start+HP costume as data/MK2PALS.IMG holds it.\n")
        f.write("-- prev = what character_palettes_4 held before, the control.\n")
        f.write("return {\n")
        for ochar, who, pname, pw, prev, vw in rows:
            f.write("  [%d] = { who = %-14s name = %-11s prev_name = %s,\n"
                    % (ochar, '"%s",' % who, '"%s",' % pname, '"%s"' % prev))
            for key, words in (("want", pw), ("prev", vw)):
                f.write("    %s = {\n" % key)
                for i in range(0, len(words), 8):
                    f.write("      " + ", ".join("0x%04X" % x for x in words[i:i + 8]) + ",\n")
                f.write("    },\n")
            f.write("  },\n")
        f.write("}\n")
    print("wrote %s (%d fighters)" % (OUT.relative_to(REPO), len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
