LIB = struct.Struct("<HHIHHHHH 4s HHH")
IMAGE = struct.Struct("<16s HHH HH H II H HHH HHH")
PAL = struct.Struct("<10s BB H I H H B B H")

# A palette is any run of 1..256 colours.  This used to be a whitelist of the
# power-of-two sizes, which rejected JADEBOX_p (244) - the select-box WIPE
# palettes are deliberately odd sizes, because each one is two boxes' colours
# packed together (ERBOX_P 251, BOX15_P 249, JADEBOX_p 244).  The junk this
# guard exists to drop is still dropped: NINJAS3's three trailing garbage
# records claim 32,768 and 17,969 entries.
MAX_PAL_COUNT = 256


def img_palettes(libname):
    """Every VALID palette record in one library, by name, LAST match winning.

    The header's palette count over-reports on these libraries (NINJAS3 claims
    34 and its last three records are garbage), so a record is taken only when
    its name is printable, its entry count is a real palette size and its data
    lies inside the file.  That drops the junk without a magic constant.
    """
    path = ROOT / "data" / libname
    d = path.read_bytes()
    imgcnt, palcnt, oset = LIB.unpack_from(d, 0)[:3]
    base = oset + imgcnt * IMAGE.size
    found, seen = {}, {}
    for i in range(palcnt):
        off = base + i * PAL.size
        if off + PAL.size > len(d):
            break
        r = PAL.unpack_from(d, off)
        raw = r[0].split(b"\0")[0]
        if not raw or not all(32 <= c < 127 for c in raw):
            continue
        cnt, at = r[3], r[4]
        if not (1 <= cnt <= MAX_PAL_COUNT) or at + 2 * cnt > len(d):
            continue
        nm = raw.decode("latin-1")
        words = list(struct.unpack_from("<%dH" % cnt, d, at))
        seen.setdefault(nm, []).append((i, words))
        found[nm] = words                      # LAST match wins, as LOAD2 does
    return found, seen


def gather():
    """symbol -> words, reporting every duplicate we actually rely on."""
    cache, out = {}, {}
    for sym, lib, rec, _note in CARRY:
        if lib not in cache:
            cache[lib] = img_palettes(lib)
        found, seen = cache[lib]
        if rec not in found:
            raise SystemExit("%s: no palette record named %s (wanted for %s)"
                             % (lib, rec, sym))
        got = seen[rec]
        if len(got) > 1:
            same = all(got[0][1] == g[1] for g in got)
            print("  note: %s has %d records named %s (idx %s, %s) - taking "
                  "the LAST, record %d"
                  % (lib, len(got), rec, ", ".join(str(g[0]) for g in got),
                     "identical" if same else "COLOURS DIFFER", got[-1][0]))
        if sym != rec:
            print("  note: %s is carried from %s record %s - the symbol and the "
                  "record name differ ON PURPOSE" % (sym, lib, rec))
        out[sym] = found[rec]
    return out


def region(pals):
    """The whole generated region, BEGIN and END included."""
    out = [BEGIN,
           ";",
           "; Hand-carried alternate COSTUME palettes, copied out of the IMG",
           "; libraries by tools/sync_alt_costume_palettes.py.  Phase D runs it",
           "; with --check.  EDIT THE IMG, THEN RUN THE TOOL - never these words.",
           ";"]
    for sym, lib, rec, note in CARRY:
        words = pals[sym]
        out.append("; %s" % note)
        out.append(";   <- %s record %s" % (lib, rec))
        out.append("%s:" % sym)
        out.append("\t.word\t %d" % len(words))
        for i in range(0, len(words), 8):
            out.append("\t.word\t" + ",".join("0%04XH" % w
                                              for w in words[i:i + 8]))
        out.append("")
    out.append(END)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="Phase D: fail if IMGPAL6.ASM has drifted from the IMGs")
    a = ap.parse_args()

    pals = gather()
    txt = ASM.read_text(encoding="latin-1")

    start = txt.find(BEGIN)
    end = txt.find(END)
    if start < 0 or end < 0 or end < start:
        print("src/IMGPAL6.ASM: the generated region is missing - add these two "
              "lines where the blocks belong and rerun:\n  %s\n  %s"
              % (BEGIN, END))
        return 1
    end += len(END) + 1                        # take the newline after END

    want = region(pals)
    if txt[start:end] == want:
        print("alternate costume palettes OK (%d, matching the IMGs)" % len(CARRY))
        return 0
    if a.check:
        print("src/IMGPAL6.ASM differs from the IMGs - run "
              "tools/sync_alt_costume_palettes.py")
        return 1
    ASM.write_text(txt[:start] + want + txt[end:], encoding="latin-1", newline="")
    print("rewrote %d palettes in src/IMGPAL6.ASM" % len(CARRY))
    return 0


if __name__ == "__main__":
    sys.exit(main())
