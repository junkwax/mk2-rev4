#!/usr/bin/env python
"""Where Sub-Zero's hand attaches, per victim, out of data/SUBSPINE.WAX.

The head rip had ONE separation for every body - `sz_headrip_reach` (05Ch = 92)
- chosen so his fist landed inside all of them. doc/SZ_HEADRIP_FATALITY.md's
"Per-character victims" flagged that as the known compromise and named
`head_lineups` (do_tongue) as the precedent to copy. This is that table, and the
numbers are AUTHORED, not fitted: the WAX lays Sub-Zero's grab frame
(`NJHIPUNCH3`) at the origin and each victim's own STUNNED pose - the pose he is
actually in during Finish Him - at the x where the hand should attach.

    slot 1  NJHIPUNCH3   dx 0      the anchor
    slot n  <XX>STUNNED  dx ...    that body, placed by hand

IMGTOOL's `local_dx` is an ANIPOINT offset, and it mirrors: the anchor sits at
`origin - dx` unmirrored and `origin + dx` mirrored (jade_impale_wax_import's
note). So the anchor the author placed is at

    placed = +dx if frame_mirror else -dx

**BUT THE GAME ALWAYS DRAWS HIM MIRRORED** - facing Sub-Zero, which in the WAX
is `frame_mirror = 1` (Kung Lao and Liu Kang). The other seven slots show the
body UNmirrored, and a body is not symmetric about its anchor: flipping it moves
his head by twice its offset from the anchor - 39px for Raiden, 33 for Kitana,
24 for Cage - so at `reach = placed` the fist that sits on his head in the WAX
ended up 25-30px short of it in the game. What the author lined up is the HEAD
under the hand (75-86px in front of Sub-Zero in all nine slots, fist tip +79),
so for an unmirrored slot the reach is moved until the game's mirrored head lands
where the WAX's unmirrored one is drawn:

    reach = placed + 2 * head      (head = centre of his top 14 opaque rows,
                                    from the anchor, unflipped art)

A mirrored slot already matches the game and is taken as placed. Mirroring a
slot in IMGTOOL and re-placing it gives the same answer either way.

**Y IS DELIBERATELY IGNORED.** The WAX carries a `local_dy` per victim too, but
the game grounds both fighters (`adjust_him_xy` is called with a1 = 0 and the
engine puts both pairs of feet on the floor), so a y offset would lift the
victim off it. Measured, the authored dy is the editor-side floor correction -
each stunned pose has a different anipoint-to-sole distance - plus a few px of
eyeballing; it is not a game instruction. Taking it would be a bug.

**THE OCHAR MAPPING IS READ OUT OF `sz_head_ani_table` (MKNJ.ASM)**, not typed
here, so this table and the head-sprite table can never disagree about which
bodies share a shape. Kintaro and Shao Kahn take `a_sz_head_gen`, have no slot,
and keep the old single constant.

**THE FRAME IS AUTHORED TOO, NOT JUST THE X.** Each slot holds ONE frame of that
body's seven-frame dizzy loop - Jax STUNNED4, Raiden 6, Shang 5, Kung Lao 4,
Baraka 7, the rest 1 - and the x was placed against THAT frame. The game used to
take the victim over on whichever frame the loop happened to be showing (or, off
the super-freeze ice, on frame 1), so the hand was lined up with a pose he was
not in. `sz_headrip_poses` carries the frame as an index into his dizzy lane
(anitab1 028h, seven plain frames in order - asserted below) and `szhr_pose`
(MKDEATH.ASM) stands him on it at the takeover. -1 = no authored pose.
`tools/szhr_pose_expect.lua` is the same numbers for the rig.

    python tools/subspine_wax_import.py           # rewrite the block in MKNJ.ASM
    python tools/subspine_wax_import.py --check   # Phase D
"""

import argparse
import os
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WAX = ROOT / "data" / "SUBSPINE.WAX"
TARGET = ROOT / "src" / "MKNJ.ASM"
BEGIN = "* --- BEGIN GENERATED by tools/subspine_wax_import.py - do not edit ---"
END = "* --- END GENERATED ---"

LIB_HDR = struct.Struct("<HHIHHHHH 4s HHH")
IMAGE = struct.Struct("<16s HHH HH H II H HHH HHH")

# a_sz_head_<suffix> -> the STUNNED stem that body's pose carries
SUFFIX_STEM = {"tm": "TM", "lk": "LK", "jc": "JC", "ug": "UG", "kt": "KT",
               "st": "ST", "rd": "RN", "nj": "NJ", "jx": "JX"}
ANCHOR_REC = "NJHIPUNCH3"          # his grab frame; the slot everything is measured from
MKDEATH = ROOT / "src" / "MKDEATH.ASM"
POSE_LUA = ROOT / "tools" / "szhr_pose_expect.lua"
# STUNNED stem -> the source file whose dizzy lane (anitab1 028h) carries it
STEM_SRC = {"TM": "MKHH.ASM", "LK": "MKLK.ASM", "JC": "MKJC.ASM", "UG": "MKSA.ASM",
            "KT": "MKFN.ASM", "ST": "MKST.ASM", "RN": "MKRD.ASM", "NJ": "MKNJ.ASM",
            "JX": "MKJX.ASM"}


def pose_index(stem, recname):
    """0-based row of `recname` in that body's dizzy lane, proved against the ASM.

    szhr_pose indexes the lane by this number, so "frame N is row N-1" has to be
    true of the lane as it is written, not assumed from the name.
    """
    mo = re.match(r"^[A-Z]{2}STUNNED(\d+)$", recname)
    if not mo:
        sys.exit(f"subspine_wax_import: {recname} has no frame number")
    txt = (ROOT / "src" / STEM_SRC[stem]).read_text(encoding="latin-1")
    lane = re.search(r"^(a_\w*stunned)\s*\n((?:\s+\.long\s+" + stem +
                     r"STUNNED\d+[^\n]*\n)+)\s+\.long\s+ani_jump,\1", txt, re.M)
    if not lane:
        sys.exit(f"subspine_wax_import: {STEM_SRC[stem]}'s dizzy lane is no longer a plain "
                 f"run of {stem}STUNNEDn frames ending in ani_jump - szhr_pose indexes it")
    rows = re.findall(r"\.long\s+(\w+)", lane.group(2))
    if recname not in rows:
        sys.exit(f"subspine_wax_import: {recname} is not in {lane.group(1)}")
    return rows.index(recname)


def default_reach():
    """sz_headrip_reach's VALUE, not its name.

    It is a `.set` in MKDEATH.ASM and a `.set` does not cross objects (the trap
    `fp_floor` / `flipk_floor` documents), so the two boss rows have to carry the
    literal.  Reading it here keeps one source of truth: change it there and
    --check calls this block stale.
    """
    txt = MKDEATH.read_text(encoding="latin-1")
    mo = re.search(r"^sz_headrip_reach\s+\.set\s+([0-9a-fA-F]+)h\b", txt, re.M)
    if mo:
        return int(mo.group(1), 16)
    mo = re.search(r"^sz_headrip_reach\s+\.set\s+(\d+)\s*$", txt, re.M)
    if not mo:
        sys.exit("subspine_wax_import: cannot read sz_headrip_reach out of src/MKDEATH.ASM")
    return int(mo.group(1))


def s16(v):
    return v - 0x10000 if v & 0x8000 else v


def read_img(path):
    b = path.read_bytes()
    imgcnt, _palcnt, oset = LIB_HDR.unpack_from(b, 0)[:3]
    out = []
    for i in range(imgcnt):
        r = IMAGE.unpack_from(b, oset + i * IMAGE.size)
        out.append(dict(name=r[0].split(b"\0", 1)[0].decode("latin-1"),
                        ax=s16(r[2]), ay=s16(r[3]), w=r[4], h=r[5], off=r[7], data=b))
    return out


HEAD_ROWS = 14


def head_offset(rec):
    """x of his head off the anchor in the UNFLIPPED art: the centre of the top
    HEAD_ROWS opaque rows (stored rows are padded to 4 pixels)."""
    w, stride, b = rec["w"], (rec["w"] + 3) & ~3, rec["data"]
    pts = []
    rows = 0
    for y in range(rec["h"]):
        row = b[rec["off"] + y * stride:rec["off"] + y * stride + w]
        xs = [x for x, v in enumerate(row) if v]
        if xs:
            pts += xs
            rows += 1
            if rows == HEAD_ROWS:
                break
    if not pts:
        sys.exit(f"subspine_wax_import: {rec['name']} has no opaque pixels")
    return sum(pts) / len(pts) - rec["ax"]


def parse_wax(path):
    kv = {}
    for line in path.read_text(errors="replace").splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            kv[k] = v
    return kv


def ints(kv, key):
    v = kv.get(key, "")
    return [int(x) for x in v.split(",") if x.strip() != ""] if v else []


def wax_reaches():
    """{stem: (reach, record)} plus the anchor record, straight off the WAX."""
    kv = parse_wax(WAX)
    out, anchor = {}, None
    for n in range(int(kv.get("slot.count", "0"))):
        seq = ints(kv, f"slot.{n}.sequence_frames")
        if not seq or kv.get(f"slot.{n}.visible", "1") != "1":
            continue                      # a hidden slot is the author's scratch
        lib = os.path.basename(kv.get(f"slot.{n}.doc_idx", "")
                               and kv.get(f"doc.{kv[f'slot.{n}.doc_idx']}.path", "")
                               .replace("\\", "/"))
        if not lib:
            continue
        recs = read_img(ROOT / "data" / lib)
        if not 0 <= seq[0] < len(recs):
            sys.exit(f"SUBSPINE.WAX slot {n}: frame {seq[0]} is outside {lib}")
        rec = recs[seq[0]]
        dx = (ints(kv, f"slot.{n}.local_dx") or [0])[0]
        mir = (ints(kv, f"slot.{n}.frame_mirror") or [0])[0] & 1
        reach = dx if mir else -dx
        if not mir and rec["name"] != ANCHOR_REC:
            # the game mirrors him: keep his HEAD where the WAX drew it
            reach = int(round(reach + 2 * head_offset(rec)))
        if rec["name"] == ANCHOR_REC:
            if reach != 0:
                sys.exit(f"SUBSPINE.WAX: the {ANCHOR_REC} slot is at {reach}, not 0 - "
                         "everything is measured from it, so it has to be the origin")
            anchor = rec
            continue
        mo = re.match(r"^([A-Z]{2})STUNNED\d*$", rec["name"])
        if not mo:
            sys.exit(f"SUBSPINE.WAX slot {n}: {rec['name']} is neither {ANCHOR_REC} nor "
                     "a <XX>STUNNED pose; this importer only understands those")
        stem = mo.group(1)
        if stem in out and out[stem][0] != reach:
            sys.exit(f"SUBSPINE.WAX: two slots place the {stem} body, at "
                     f"{out[stem][0]} and {reach}")
        out[stem] = (reach, rec["name"])
    if anchor is None:
        sys.exit(f"SUBSPINE.WAX: no visible {ANCHOR_REC} slot - nothing to measure from")
    return out


def ochar_rows():
    """(ochar, suffix, comment) straight out of MKNJ.ASM's own head table."""
    txt = TARGET.read_text(encoding="latin-1")
    mo = re.search(r"^sz_head_ani_table\b(.*?)(?=^sz_head_pal_table)", txt, re.S | re.M)
    if not mo:
        sys.exit("subspine_wax_import: sz_head_ani_table not found in src/MKNJ.ASM")
    # the Wolf-only fighters' rows are tools/wolf_fighter_rows.py's, not the 20
    body = mo.group(1).split("WOLF FIGHTERS")[0]
    rows = re.findall(r"\.long\s+a_sz_head_(\w+)\s*;\s*(\d+)\s*-\s*([^\n]*)", body)
    if not rows:
        sys.exit("subspine_wax_import: sz_head_ani_table rows did not parse")
    return [(int(oc), suf, who.strip()) for suf, oc, who in rows]


def wolf_rows(name, out):
    """The Wolf-only fighters' rows for the table whose 20 rows end `out`
    (tools/wolf_fighter_rows.py owns the form)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import wolf_fighter_rows
    vals = [ln.split("\t")[2] for ln in out[-20:]]
    return wolf_fighter_rows.block(name, "word", [[v] for v in vals]) or []


def build():
    reaches = wax_reaches()
    rows = ochar_rows()
    fallback = default_reach()
    seen = set()
    out = [BEGIN,
           "*",
           "*  sz_headrip_reaches - where Sub-Zero's hand attaches, per victim.",
           "*",
           "*  Authored in data/SUBSPINE.WAX: his grab frame NJHIPUNCH3 at the origin and",
           "*  each body's own STUNNED pose - what the victim is actually standing in",
           "*  during FINISH HIM - placed at the x the hand should reach.  Generated by",
           "*  tools/subspine_wax_import.py; edit the WAX, re-run the tool, never this",
           "*  block.  Indexed by the VICTIM's ochar and 20 rows wide for the same reason",
           "*  sz_head_ani_table is - anyone can be the victim.",
           "*",
           "*  The ochar -> body mapping is READ OUT OF sz_head_ani_table below, so the",
           "*  two tables cannot disagree about which bodies share a shape.  Kintaro and",
           "*  Shao Kahn have no pose in the WAX and keep sz_headrip_reach's own value,",
           "*  the single constant every victim used before this - carried as a literal",
           "*  because a .set does not cross objects.",
           "*",
           "\t.globl\tsz_headrip_reaches",
           "",
           "sz_headrip_reaches"]
    for oc, suf, who in rows:
        stem = SUFFIX_STEM.get(suf)
        if stem is None and suf != "gen":
            sys.exit(f"subspine_wax_import: head lane a_sz_head_{suf} (ochar {oc}) has no "
                     "STUNNED stem in SUFFIX_STEM - add it, or the victim gets the wrong body")
        hit = reaches.get(stem) if stem else None
        if hit:
            seen.add(stem)
            out.append(f"\t.word\t{hit[0]}\t\t; {oc:>2} - {who[:34]} ({hit[1]})")
        else:
            out.append(f"\t.word\t{fallback}\t\t; {oc:>2} - {who[:34]} (no pose; sz_headrip_reach)")
    out += wolf_rows("sz_headrip_reaches", out)
    missing = sorted(set(reaches) - seen)
    if missing:
        sys.exit("subspine_wax_import: SUBSPINE.WAX places bodies no ochar uses: "
                 + ", ".join(f"{s} ({reaches[s][1]})" for s in missing))
    out += ["",
            "*",
            "*  sz_headrip_poses - WHICH frame of his dizzy loop each body is authored on.",
            "*",
            "*  The x above was placed against one particular STUNNED frame, so the victim",
            "*  has to be standing on that frame when the hand arrives - not on whichever",
            "*  one the loop was showing, and not on frame 1 because he was thawed off the",
            "*  super-freeze ice.  A row is an index into his anitab1 028h lane (seven plain",
            "*  frames in order; the generator proves it), -1 = no authored pose.  Read by",
            "*  szhr_pose (MKDEATH.ASM).",
            "*",
            "\t.globl\tsz_headrip_poses",
            "",
            "sz_headrip_poses"]
    for oc, suf, who in rows:
        stem = SUFFIX_STEM.get(suf)
        hit = reaches.get(stem) if stem else None
        if hit:
            out.append(f"\t.word\t{pose_index(stem, hit[1])}\t\t; {oc:>2} - {who[:34]} ({hit[1]})")
        else:
            out.append(f"\t.word\t-1\t\t; {oc:>2} - {who[:34]} (no pose)")
    out += wolf_rows("sz_headrip_poses", out)
    out += ["", END]
    return "\n".join(out)


def pose_lua():
    """ochar -> 1-based STUNNED frame, for tools/sz_headrip_test.lua."""
    reaches = wax_reaches()
    out = ["-- GENERATED by tools/subspine_wax_import.py from data/SUBSPINE.WAX - do not edit.",
           "-- victim ochar -> the STUNNED frame (1-based) he must be drawn on at the grab.",
           "return {"]
    for oc, suf, who in ochar_rows():
        stem = SUFFIX_STEM.get(suf)
        hit = reaches.get(stem) if stem else None
        if hit:
            out.append(f"    [{oc}] = {pose_index(stem, hit[1]) + 1},   -- {who[:34]} ({hit[1]})")
    out.append("}")
    return "\n".join(out) + "\n"


def splice(text, block):
    if BEGIN in text:
        pre = text.split(BEGIN)[0]
        post = text.split(END, 1)[1]
        return pre + block + post
    anchor = "\nsz_head_ani_table"
    if anchor not in text:
        sys.exit("subspine_wax_import: cannot find sz_head_ani_table to insert before")
    return text.replace(anchor, "\n" + block + "\n" + anchor.lstrip("\n"), 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()

    block = build()
    if a.print:
        print(block)
        return
    txt = TARGET.read_text(encoding="latin-1")
    new = splice(txt, block)
    lua = pose_lua()
    lua_now = POSE_LUA.read_text(encoding="latin-1") if POSE_LUA.exists() else None
    if a.check:
        if new != txt:
            sys.exit("subspine_wax_import: src/MKNJ.ASM is stale against "
                     "data/SUBSPINE.WAX - re-run tools/subspine_wax_import.py")
        if lua != lua_now:
            sys.exit("subspine_wax_import: tools/szhr_pose_expect.lua is stale against "
                     "data/SUBSPINE.WAX - re-run tools/subspine_wax_import.py")
        print("OK: sz_headrip_reaches + sz_headrip_poses match data/SUBSPINE.WAX")
        return
    if lua != lua_now:
        POSE_LUA.write_text(lua, encoding="latin-1", newline="\n")
        print(f"wrote {POSE_LUA.name}")
    if new == txt:
        print("sz_headrip_reaches / sz_headrip_poses already current")
        return
    TARGET.write_text(new, encoding="latin-1")
    print(f"wrote sz_headrip_reaches + sz_headrip_poses into {TARGET.name}")


if __name__ == "__main__":
    main()
