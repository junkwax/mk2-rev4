#!/usr/bin/env python3
"""
behaviour_lock.py - freeze what canonical interactions actually DO.

Section 8.2 of doc/TOURNAMENT_READINESS.md.  The stability sweep catches
crashes and camera scope; it does not catch "this move now whiffs at point
blank".  `balance.lock` guards the numbers a human typed and `hurtbox.lock`
the ones the art decides - but a move's real behaviour is those two combined
with the handler, and nothing was watching the combination.

This is deliberately NOT a list of assertions about what the game *should* do.
Nobody has ruled on that (see the nine open decisions in section 4 and 5).  It
records what the game DOES, measured in the emulator, so a change becomes a
diff instead of a surprise.  Same contract as the other two locks.

The measurement is `tools/sweep_addon_assert.lua`, run against a standing
practice dummy.  It is deterministic: two consecutive runs are byte-identical.

  python tools/behaviour_lock.py            freeze tools/behaviour_run.txt
  python tools/behaviour_lock.py --check    compare a fresh run to the lock

Unlike the other two locks this one cannot go in Phase D - it needs MAME and
about a minute.  `tools/run_behaviour_check.ps1` does the run and the compare
together; that belongs with the stability sweep, not with the build.
"""
import argparse
import difflib
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN = os.path.join(ROOT, "tools", "behaviour_run.txt")
LOCK = os.path.join(ROOT, "doc", "behaviour.lock")

HEADER = """# behaviour.lock - generated by tools/behaviour_lock.py from a
# tools/sweep_addon_assert.lua run.
#
# What canonical interactions actually DO, measured in the emulator against a
# standing dummy. Not what they SHOULD do - that is still nine open rulings.
# A diff here means a move changed behaviour, which balance.lock and
# hurtbox.lock can both miss: they guard the inputs, this guards the result.
#
# dmg           worst damage the dummy took in the window
# attacker_act  the action P1 was actually in - `elbow_check` turns a close HP
#               into an elbow and a far toward+LP is a low punch, not a throw,
#               so damage alone never identifies a move
# victim_act    0000h means the dummy was never seen outside stance in the
#               sampled window. Four cases that plainly connect report it, so
#               it is corroboration when non-zero and NOT evidence of "no
#               reaction" when zero. Unexplained; recorded rather than tidied.
"""


def read_run():
    if not os.path.exists(RUN):
        return None
    keep = []
    for line in open(RUN, encoding="utf-8", errors="replace"):
        line = line.rstrip("\n")
        if re.match(r"^\S+\s+dist=", line) or line.startswith("cases_done"):
            keep.append(line)
    return keep or None


def build(rows):
    body = HEADER + "\n[cases]\n" + "\n".join(rows) + "\n"
    return body + "\n[digest]\nsha256 %s\n" % hashlib.sha256(
        body.encode("utf-8")).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = read_run()
    if rows is None:
        print("no tools/behaviour_run.txt - run "
              "tools/run_behaviour_check.ps1 first")
        sys.exit(1)
    fresh = build(rows)
    have = open(LOCK, encoding="utf-8", newline="").read() \
        if os.path.exists(LOCK) else None

    if args.check:
        if have is None:
            print("behaviour.lock does not exist yet - run: "
                  "python tools/behaviour_lock.py")
            sys.exit(1)
        if have == fresh:
            print("  behaviour.lock OK (%d cases)" % (len(rows) - 1))
            return
        d = list(difflib.unified_diff(
            have.splitlines(), fresh.splitlines(),
            fromfile="behaviour.lock (committed)", tofile="this run",
            lineterm="", n=0))
        print("BEHAVIOUR CHANGED - %d differing lines:" % sum(
            1 for l in d if l[:1] in "+-" and not l.startswith(("---", "+++"))))
        for l in d[:40]:
            print("  " + l)
        print()
        print("A canonical interaction now does something else. If that was")
        print("deliberate, re-freeze it:")
        print("  python tools/behaviour_lock.py")
        sys.exit(1)

    os.makedirs(os.path.dirname(LOCK), exist_ok=True)
    with open(LOCK, "w", encoding="utf-8", newline="") as fh:
        fh.write(fresh)
    print("wrote doc/behaviour.lock (%d cases)" % (len(rows) - 1))
    if have is not None and have != fresh:
        print("NOTE: this OVERWROTE an existing lock - behaviour changed.")


if __name__ == "__main__":
    main()
