#!/usr/bin/env python3
"""
input_model.py - generate doc/INPUT_MODEL.md.

Section 2.2 of doc/TOURNAMENT_READINESS.md: "the input model is undocumented,
and it has sharp edges". Three of those edges will catch a tournament player
inside an hour and none of them was written down anywhere.

Everything structural is read from the source at generation time, so the
document cannot drift from the build. The measured numbers - latency, the
buffering answer, the two-button window - come from rigs and are labelled with
the tool that produced them, because nothing in the source states them.

  python tools/input_model.py > doc/INPUT_MODEL.md
"""
import importlib.util
import os
import re
import collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
TICK_MS = 1000.0 / 54.7068


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


BA = _load("ba", os.path.join(ROOT, "tools", "box_align_audit.py"))


def equate(txt, name):
    m = re.search(r"^%s\s+\.set\s+(\S+)" % re.escape(name), txt, re.M)
    return m.group(1).strip() if m else None


def combo_windows():
    """scom_* -> input window in ticks (the record's first .word)."""
    out = {}
    pat = re.compile(
        r"^(scom_[A-Za-z0-9_]+)\s*\n\s*\.[wW][oO][rR][dD]\s+0?([0-9a-fA-F]+)h",
        re.M)
    for fn in ("MOVES.ASM", "MKBABY.ASM"):
        p = os.path.join(SRC, fn)
        if os.path.exists(p):
            for m in pat.finditer(BA.read(p)):
                out[m.group(1)] = int(m.group(2), 16)
    return out


def main():
    eq = BA.read(os.path.join(SRC, "MAINEQU.ASM"))
    slack = int(equate(eq, "combo_slack") or 0)
    online = int(equate(eq, "combo_slack_online") or 0)
    tbs = int(equate(eq, "twobtn_slack") or 0)
    tbd = int(equate(eq, "twobtn_depth") or 0)
    sqs = int(equate(eq, "sqs") or 0)

    P = print
    P("# The MK2 input model\n")
    P("Generated by `tools/input_model.py`. Structure is read from the source")
    P("at generation time; the measured numbers name the rig that produced")
    P("them, because nothing in the source states them.\n")
    P("One tick is one display refresh at 54.7068 Hz — **%.2f ms**. Every"
      % TICK_MS)
    P("number below is in ticks.\n")

    P("## What it costs to press a button\n")
    P("Measured with `tools/sweep_addon_latency.lua`, eight trials a case,")
    P("zero variance on every row:\n")
    P("| | ticks | ms |")
    P("|---|---|---|")
    P("| button down to the move starting | **3** | %.0f |" % (3 * TICK_MS))
    P("| button down to a hit landing | **9–12** | %.0f–%.0f |"
      % (9 * TICK_MS, 12 * TICK_MS))
    P("")
    P("The uppercut accepts at 5 rather than 3 because the duck has to")
    P("resolve first. Everything else tested accepts at 3.\n")

    P("## There is no input buffer\n")
    P("Measured with `tools/sweep_addon_buffer.lua`. A high punch, then a low")
    P("kick pressed K ticks later:\n")
    P("* **K ≤ 18 — the kick never comes out.** The input is discarded, not")
    P("  queued.")
    P("* **K ≥ 19 — the kick comes out at exactly K+3**, the same acceptance")
    P("  cost as from neutral.\n")
    P("So a punish has to be **timed, not held early**. Pressing during your")
    P("own recovery does nothing at all — there is no queue for the input to")
    P("survive in. Any advice built on buffering is wrong for this game, and")
    P("for netplay it means a dropped input is simply lost.\n")

    P("## The switch queue\n")
    P("Each player has a **%d-entry** queue of `[switch, time]` pairs" % sqs)
    P("(`sqs`, MAINEQU.ASM), written as inputs arrive and walked **backwards**")
    P("when a special is matched.\n")
    P("Three consequences, all of which look like the game ignoring you:\n")
    P("* **The port is read live, not latched.** `joystick_in_a0` (JOY.ASM)")
    P("  does `move *a0,a0,l` straight off `p_joyport` every time it is")
    P("  called, so two processes in the same frame can see different stick")
    P("  states.")
    P("* **Any extra button held kills the match.** `combo_look_lr` opens with")
    P("  `button_mask` and bails — *\"other buttons pressed ---> NO !!!\"*.")
    P("  Hold block, or ride a second button, and the motion silently does not")
    P("  register.")
    P("* **Matching is exact-state, entry by entry.** No partial credit, and a")
    P("  stray diagonal is never cleaned up — it sits in the queue as a")
    P("  mismatched entry.\n")
    P("### What each of those actually costs\n")
    P("`tools/sweep_addon_droprate.lua` introduces one hazard at a time")
    P("against a motion already measured as reliable (Reptile's spit, F,F+HP")
    P("at an 8-tick gap), four tries each. Attributing a failure in the wild")
    P("is impossible from outside — nothing reports which check rejected — so")
    P("each hazard is caused on purpose instead.\n")
    P("| what the player is doing | move comes out |")
    P("|---|---|")
    P("| nothing extra (control) | **4/4** |")
    P("| holding **Block** | **0/4** |")
    P("| riding a second attack button | **0/4** |")
    P("| **tapping** Down between the two forwards | **0/4** |")
    P("| **holding** Down across the whole motion | **4/4** |")
    P("")
    P("Two things worth having in front of you:\n")
    P("* **You cannot hold Block and throw a special.** Not harder — it does")
    P("  not come out at all. Any second button does the same. This is the")
    P("  edge most likely to be blamed on the player.")
    P("* **Holding a direction is free; tapping one is fatal.** Riding Down")
    P("  through the whole motion costs nothing, because a held direction")
    P("  makes no new queue entry. A Down *tapped* mid-motion makes one, and")
    P("  a mismatched entry is never cleaned up. So a sloppy return through")
    P("  down-forward is harmless, but a deliberate extra input is not.\n")

    P("## Special-move windows\n")
    cw = combo_windows()
    if cw:
        dist = collections.Counter(cw.values())
        P("%d special-move records. The window is the record's first word —" % len(cw))
        P("the time the whole motion has to complete:\n")
        P("| window (ticks) | ms | moves |")
        P("|---|---|---|")
        for w, n in sorted(dist.items()):
            P("| %d | %.0f | %d |" % (w, w * TICK_MS, n))
        tight = sorted(cw.items(), key=lambda kv: kv[1])[:6]
        P("")
        P("Tightest: %s." % ", ".join("`%s` (%d)" % (k, v) for k, v in tight))
        P("")
        P("**That spread looks alarming and is not.** The window tracks how")
        P("hard the motion is, not how long:")
        P("")
        P("* every 16-tick record is a **roll** - two different directions,")
        P("  which the hand does in one movement;")
        P("* a **double tap of one direction** (F,F or B,B) never gets less")
        P("  than 24, because the stick has to return to neutral in between.")
        P("")
        P("Measured with `tools/sweep_addon_combogap.lua`, sweeping the gap")
        P("between the two inputs, three tries each:")
        P("")
        P("| motion | window | gap that works |")
        P("|---|---|---|")
        P("| Raiden's lightning, D then F (a roll) | 16 | **1-10 ticks** |")
        P("| Reptile's spit, F then F (a tap) | 24 | **4-16 ticks** |")
        P("")
        P("Neither is demanding: the roll accepts anything up to 183 ms")
        P("between inputs and the tap up to 293 ms. The spit fails at a gap of")
        P("**2** for the opposite reason - the stick has not been released yet,")
        P("so the second tap is not a second entry at all. **Release between")
        P("taps; speed is not the problem.**")
        P("")
        P("So the only input in the game that is genuinely tight on timing is")
        P("the two-button one below.")
    P("")
    if slack:
        P("**`combo_slack` adds %d ticks (%.0f ms) to every one of those**"
          % (slack, slack * TICK_MS))
        P("windows%s." % (", online only (`combo_slack_online`)" if online
                          else ", offline and online alike"))
    else:
        P("`combo_slack` is 0 — windows are retail-exact.")
    P("")

    P("## Two buttons at once\n")
    P("Kitana's fan throw and Reptile's forceball need both punch buttons.")
    P("`two_button_check` (MOVES.ASM) looks back through the queue for the")
    P("partner button and rejects it if too much time separates the two.\n")
    P("Retail wants the partner as the **immediately** previous entry and")
    P("within **2 ticks (37 ms)**. Measured with")
    P("`tools/sweep_addon_twobtn.lua`: the fan came out 3/3 at separations of")
    P("0–2 ticks and **0/3 at 3 or more**.\n")
    if tbs:
        P("This build sets `twobtn_slack %d` and `twobtn_depth %d`:" % (tbs, tbd))
        P("the window is **%d ticks (%.0f ms)** and the partner may sit up to"
          % (2 + tbs, (2 + tbs) * TICK_MS))
        P("%d entries back, so one stray entry between the presses no longer" % tbd)
        P("kills it. Re-measured after the change: **3/3 out to a separation")
        P("of %d, 0/3 at %d**." % (2 + tbs, 3 + tbs))
        P("")
        P("The trade: a wider window makes an LP→HP string thrown while")
        P("holding forward likelier to come out as a fan. `twobtn_slack 0`")
        P("restores retail exactly.")
    else:
        P("This build is retail here (`twobtn_slack 0`).")
    P("")

    P("## Live switch values\n")
    P("| switch | value | what it does |")
    P("|---|---|---|")
    P("| `combo_slack` | %d | ticks added to every special-move window |" % slack)
    P("| `combo_slack_online` | %d | 1 = that slack applies online only |" % online)
    P("| `twobtn_slack` | %d | ticks added to the two-button window |" % tbs)
    P("| `twobtn_depth` | %d | queue entries searched for the partner button |" % tbd)
    P("")
    P("All four are in `doc/balance.lock`, so changing one fails the build")
    P("until it is declared.")


if __name__ == "__main__":
    main()
