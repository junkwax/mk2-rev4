#!/usr/bin/env python3
"""
Pack bank-0 custom sidecars tight so their leftover tails coalesce into ONE
usable run instead of a dozen useless fragments.

Why this exists
---------------
Every custom sidecar was given a slot on a 4KB boundary with a comfortable
tail, one at a time, over months.  Individually that is tidy; collectively it
scatters the free video ROM.  Before the first pass on 2026-08-10 bank 0 held
102,104 free bytes whose largest single run was 26,346 - so a 40KB asset did
not fit anywhere, even though there was room for four of them.

Packing does not create space.  It moves the SAME free bytes to the top of the
packed region, where they are contiguous and therefore spendable.

What it is safe to move
-----------------------
A sidecar's base address reaches the game through exactly two channels:

  * SAG addresses in src/<NAME>.TBL - regenerated by LOAD2 and promoted by
    tools/promote_tbls.py, so these follow the base automatically.
  * `VS_xx .set <addr>` equates for MOVIE frames (VSJDMOV / VSNBMOV) - these
    are in promote_tbls.py's SET_EQUATE_TABLES, but ONLY since 2026-08-10.
    Before that a `.set`-only table silently reported "ok" forever, because
    the record parser matches labels by a trailing colon.  If you ever add a
    movie sidecar here, confirm its ZIP table is in that set: a stale movie
    address does not draw a wrong picture, it hangs gstate 0dh.

Nothing else in src/ hardcodes a video-ROM address (checked: the only raw
addresses are MK8ZIP/MKZIP/VS*ZIP equates and a MK4MIL diagnostics pattern).

Usage
-----
    python tools/pack_bank0_sidecars.py            # report the layout
    python tools/pack_bank0_sidecars.py --apply    # rewrite the LOD ***> lines
    python tools/pack_bank0_sidecars.py --check    # non-zero if LODs disagree

--apply only rewrites data/*.LOD.  It PRINTS the matching CUSTOM_VIDEO_SLOTS
entries for makevrom.py, which stays hand-edited on purpose - that table
carries the reasoning comments and is the thing that catches a mistake here.

After applying: re-run LOAD2 for the moved LODs (or a full `python build.py`),
then promote_tbls, then makevrom.  makevrom's pairwise overlap check and
per-slot bounds check are the real safety net.
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

IRW_HEADER = 68          # makevrom reports payload = filesize - 68
ALIGN = 0x200            # 512 bytes, matching the MK1SKULL precedent
BANK0_BASE = 0x02000000  # LOAD2 bit-address base for bank 0

# Ordered low-to-high.  FLAPJACK (0x7BC000, 205,504 bytes) and JADVIC
# (0x7F0000) are deliberately NOT in this list: moving the stage background
# buys only its own 7,488-byte tail and costs a re-verify of a whole stage,
# and JADVIC sits above it against the 0x800000 chip edge.  Their tails stay
# separate fragments.
# The region starts just above MK5MIL, the stock payload below it, and is
# DERIVED rather than hardcoded: MK5MIL shrank by 166,876 bytes on 2026-08-11
# when the 10 ending movie frames at its tail were retired, and the whole point
# of that was to let the pack slide down into the space. Recomputing from the
# real IRW means the next such change needs no edit here.
MK5MIL_GUARD = 0x1000    # keep a 4KB cushion under the stock payload
REGION_END = 0x7BC000    # FLAPJACK's fixed base - the pack must not reach it

SIDECARS = [
    "SZSPINE",
    "MOVEART2",
    "MOVEART1",
    "SHAOSIT",
    "JXAIRPRO",
    "NOOBFX",
    "VSNBMOV",
    "KITSPIN",
    "MK1SKULL",
    "GOROWALK",
]


def payload_size(name):
    irw = REPO / "data" / f"{name}.IRW"
    if not irw.exists():
        sys.exit(f"error: {irw} missing - run a LOAD2 pass first")
    return irw.stat().st_size - IRW_HEADER


def lod_base(name):
    """Current ***> byte offset declared by data/<name>.LOD.

    Scans for the line rather than assuming line 1 - MK5MIL.LOD opens with a
    two-line comment about a historical nudge, and taking splitlines()[0]
    silently reports "no ***> line" for it.
    """
    lod = REPO / "data" / f"{name}.LOD"
    for line in lod.read_text(errors="replace").splitlines():
        m = re.match(r"\*\*\*>\s*([0-9A-Fa-f]+)", line)
        if m:
            return (int(m.group(1), 16) - BANK0_BASE) // 8
    sys.exit(f"error: {lod} has no ***> line")


def region_start():
    """First 4KB boundary at least MK5MIL_GUARD above MK5MIL's real end."""
    base = lod_base("MK5MIL")
    end = base + payload_size("MK5MIL")
    return (end + MK5MIL_GUARD + 0xFFF) & ~0xFFF


def plan():
    rows = []
    cursor = region_start()
    for name in SIDECARS:
        size = payload_size(name)
        end = cursor + size
        slot_end = (end + ALIGN - 1) & ~(ALIGN - 1)
        rows.append(dict(name=name, base=cursor, size=size, end=end,
                         slot_end=slot_end, cur=lod_base(name)))
        cursor = slot_end
    return rows, cursor


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true",
                    help="rewrite the ***> line in each data/<name>.LOD")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if any LOD is not on its packed base")
    args = ap.parse_args()

    rows, cursor = plan()
    free = REGION_END - cursor
    if free < 0:
        sys.exit(f"error: pack overruns FLAPJACK at {REGION_END:#08x} by {-free} bytes")

    print(f"{'sidecar':10s} {'payload':>8s}  {'base':>9s} {'end':>9s} {'slot_end':>9s} "
          f"{'guard':>5s}  {'LOAD2 addr':>10s}  moved")
    moved = []
    for r in rows:
        addr = r["base"] * 8 + BANK0_BASE
        did = r["base"] != r["cur"]
        if did:
            moved.append(r)
        print(f"{r['name']:10s} {r['size']:8,d}  {r['base']:#09x} {r['end']:#09x} "
              f"{r['slot_end']:#09x} {r['slot_end']-r['end']:5d}  {addr:#010x}  "
              f"{'yes (was ' + format(r['cur'], '#08x') + ')' if did else 'no'}")

    print(f"\nfree run after the pack: {cursor:#08x}..{REGION_END:#08x} = {free:,} bytes contiguous")
    print(f"{len(moved)} of {len(rows)} sidecars move")

    if args.check:
        if moved:
            print("\nSTALE - LOD bases do not match the packed layout")
            return 1
        print("\nok - every LOD is on its packed base")
        return 0

    if args.apply:
        for r in moved:
            lod = REPO / "data" / f"{r['name']}.LOD"
            text = lod.read_text()
            addr = r["base"] * 8 + BANK0_BASE
            text = re.sub(r"^\*\*\*>\s*[0-9A-Fa-f]+", f"***> {addr:X}", text, count=1)
            lod.write_text(text)
            print(f"  patched {lod.name}  ***> {addr:X}")
        print("\nNow: re-run LOAD2 for the moved LODs, promote_tbls, makevrom.")
        print("CUSTOM_VIDEO_SLOTS entries for makevrom.py:")
        for r in rows:
            print(f'    "{r["name"]}.IRW": ({r["base"]:#08x}, {r["slot_end"]:#08x}, "..."),')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
