#!/usr/bin/env python3
r"""THE DISCORD PAGE'S PICTURE - MK3's OBKNEEBREAK2 (SWAT9.IMG), the officer
reeling back from Stryker's knee break, standing at the left of the attract
loop's alt.games.mk page (discord_info, MKAMODE.ASM).

The frame is 59x120 on a 63-entry palette (57 colours used), so it packs at
6bpp to ~3.2 KB with ZON> - and no free run in the T-unit video ROM is that
big (the largest is ~2.7 KB).  So it is cut into a TOP and a BOTTOM half,
each its own record and its own one-record pack, dealt into two bank-1 tails
no IRW had claimed:

    DISCOB1  top half    0xBFF600..0xC00000  (above RAIN, top of bank 1)
    DISCOB2  bottom half 0x9E5A00..0x9E6400  (JDROD's guard, under MK1TRS2)

Bank 1 is safe: the page draws them as bare objects that cast no shadow, so
only the DMA reads the art.  Both records are PON> on DSCOB_P, which is
carried into the program ROM by src/DISCOBP.ASM (included by MKAMODE.ASM) -
nothing promotes an IMG palette.  Pixels and palette are SWAT9's verbatim;
both anipoints are 0,0 because a single-part object's oxpos/oypos ARE its
top-left corner and the page places the halves outright.

    python tools/make_discord_ob.py --apply | --check | --png FILE
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import make_cage_logo as cl        # noqa: E402  (parse_img)
import make_mk1pit as pit          # noqa: E402  (build_img, rgb)

SRC = Path("C:/Users/you/Workplace/deadlythirdcombat-main/deadlythirdcombat-main/SWAT9.IMG")
RECORD = "OBKNEEBREAK2"
PAL = "DSCOB_P"
SPLIT = 60                          # rows in the top half
PACKS = (("DISCOB1", "DISCOBA", 0xBFF600), ("DISCOB2", "DISCOBB", 0x9E5A00))


def lod_base(phys):
    return 0x2000000 + (phys - 0x800000) * 8


def build():
    if not SRC.exists():
        raise SystemExit(f"{SRC} missing - MK3's art library holds the frame")
    recs, pals = cl.parse_img(SRC.read_bytes())
    r = recs[RECORD]
    words = pals[r["palnum"]]["words"]
    rows = r["px"]
    if len(rows) != 120 or len(rows[0]) != 59:
        raise SystemExit(f"{RECORD} is {len(rows[0])}x{len(rows)}, expected 59x120")
    halves = (rows[:SPLIT], rows[SPLIT:])
    entries = [(name, 0, 0, len(h[0]), len(h), bytes(v for row in h for v in row), 0)
               for (_s, name, _b), h in zip(PACKS, halves)]
    files = {"data/DISCOB.IMG": pit.build_img(entries, [(PAL, 6, words)])}
    for stem, name, phys in PACKS:
        lod = [f"***> {lod_base(phys):X},1",
               "IHDR SIZX:W,SIZY:W,ANIX:W,ANIY:W,SAG:L,CTRL:W,PAL:L",
               ";" + "*" * 62, ";",
               ";  THE DISCORD PAGE'S PICTURE - GENERATED by tools/make_discord_ob.py",
               f";  --apply.  Bank-1 physical 0x{phys:X}.  MK3's OBKNEEBREAK2 (SWAT9.IMG),",
               ";  cut in two because no free run holds the whole frame.  PON> on",
               ";  DSCOB_P (src/DISCOBP.ASM).",
               ";", ";" + "*" * 62,
               "PON>", "ZON>", "PPP> 6", f"ASM> {stem}.TBL", "DISCOB.IMG", f"---> {name}"]
        files[f"data/{stem}.LOD"] = ("\r\n".join(lod) + "\r\n").encode()
    o = [";" + "*" * 70,
         ";  DSCOB_P - the Discord page picture's palette (OBKNEEBREAK2's OLTBLU_P,",
         ";  SWAT9.IMG).  GENERATED by tools/make_discord_ob.py - do not hand-edit.",
         ";  Included by MKAMODE.ASM.",
         ";" + "*" * 70,
         "DSCOB_P:", f"\t.word\t{len(words)}"]
    for i in range(0, len(words), 8):
        o.append("\t.word\t" + ",".join("0%04xh" % v for v in words[i:i + 8]))
    files["src/DISCOBP.ASM"] = ("\r\n".join(o) + "\r\n").encode()
    return files, r, words


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--apply", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--png")
    a = ap.parse_args()
    files, r, words = build()
    if a.png:
        from PIL import Image
        im = Image.new("RGB", (59, 120), (90, 90, 90))
        for y, row in enumerate(r["px"]):
            for x, v in enumerate(row):
                if v:
                    im.putpixel((x, y), pit.rgb(words[v]))
        im.save(a.png)
        print("wrote", a.png)
        return 0
    bad = 0
    for rel, data in files.items():
        p = ROOT / rel
        if a.apply:
            if not p.exists() or p.read_bytes() != data:
                p.write_bytes(data)
                print("wrote", rel)
        elif not p.exists() or p.read_bytes() != data:
            print("STALE", rel)
            bad += 1
    if a.check:
        print("discord picture OK" if not bad else f"{bad} file(s) stale - run --apply")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
