# Runtime proof that RAIN's two costumes on screen are the ones authored in
# RNUMK3_P for player 1 (his DEFAULT since 2026-09-24) and RNUMK2_P for player 2
# in a mirror - both authored in data/NINJAS3.IMG.
#
# The expected words are regenerated from the IMG on every run into
# tools/rain_palette_expect.lua, so the rig cannot pass against a stale number
# somebody typed in.  It then boots a forced RAIN vs RAIN match in MAME and
# reads the colour RAM each fighter's object is pointing at.
#
#   powershell -File tools/run_rain_palette_test.ps1
#   powershell -File tools/run_rain_palette_test.ps1 -Keep     # leave MAME up
#
param(
    [string]$Rom    = "mk2",
    [int]$Settle    = 150,
    [switch]$Keep,
    # -Negative crosses the two expectations on purpose.  It must FAIL; a pass
    # means the rig is not reading the colour RAM and the green run meant
    # nothing.  Exit code is inverted so "0 = the control behaved".
    [switch]$Negative
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$mame = "C:\MAME\mame.exe"
$log  = Join-Path $root "tools\rain_palette_test.log"

# --- the ROM the rig is about to read must be the one this build produced ----
$zip = "C:\MAME\roms\mk2.zip"
$out = Join-Path $root "src\mk2.out"
if (-not (Test-Path $zip)) { throw "no $zip - run: python mamerom.py --source-video" }
if ((Get-Item $zip).LastWriteTime -lt (Get-Item $out).LastWriteTime) {
    throw "$zip is older than src\mk2.out - the rig would read every symbol at the wrong address. Repackage first."
}

# --- regenerate the expectation straight out of the IMG ----------------------
Write-Host "Regenerating tools/rain_palette_expect.lua from the IMGs"
Push-Location $root
try {
    python -c @"
import importlib.util, io
def load(tag, path):
    spec = importlib.util.spec_from_file_location(tag, path)
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m
# RAIN's DEFAULT is RNUMK3_P and his MIRROR/Start+LP costume is RNUMK2_P, both
# authored in NINJAS3.IMG; RNUMK1_P (NINJAS10.IMG) is now only his Start+HP.
# Each palette is read from the tool that OWNS it, so the rig can never expect
# a palette the ROM was not built from.  gather() keys by ROM symbol, which is
# not always the IMG record name.
srp = load('srp', 'tools/sync_rain_palette.py')
umk = load('umk', 'tools/sync_alt_costume_palettes.py')
pals = dict(srp.img_palettes())
pals.update(umk.gather())
with io.open('tools/rain_palette_expect.lua', 'w', newline='\n') as f:
    f.write('-- GENERATED by tools/run_rain_palette_test.ps1: RNUMK3_P (default)\n')
    f.write('-- and RNUMK2_P (mirror / Start+LP), both from data/NINJAS3.IMG.\n')
    f.write('-- Do not edit: the point of this file is that no human chose the numbers.\n')
    f.write('return {\n')
    for name in ('RNUMK3_P', 'RNUMK2_P'):
        w = pals[name]
        f.write('  %s = {\n' % name)
        for i in range(0, len(w), 8):
            f.write('    ' + ', '.join('0x%04X' % x for x in w[i:i+8]) + ',\n')
        f.write('  },\n')
    f.write('}\n')
print('wrote tools/rain_palette_expect.lua (%d + %d words)'
      % (len(pals['RNUMK3_P']), len(pals['RNUMK2_P'])))
"@
    if ($LASTEXITCODE -ne 0) { throw "could not read the palettes out of the IMGs" }
} finally { Pop-Location }

if (Test-Path $log) { Remove-Item $log }

$env:MK2_ROOT   = $root
$env:RPT_LOG    = $log
$env:RPT_SETTLE = "$Settle"
$env:RPT_SWAP   = $(if ($Negative) { "1" } else { "0" })

$mameArgs = @($Rom, "-autoboot_script", (Join-Path $root "tools\rain_palette_test.lua"),
          "-window", "-nomaximize", "-skip_gameinfo", "-nothrottle", "-seconds_to_run", "120")
if (-not $Keep) { $mameArgs += "-exit_after_playback" }

if ($Negative) { Write-Host "NEGATIVE CONTROL - expectations crossed; this run must FAIL" }
Write-Host "Running MAME ($Rom) - forced RAIN vs RAIN mirror match"
Push-Location "C:\MAME"
try { & $mame @mameArgs | Out-Null } finally { Pop-Location }

if (-not (Test-Path $log)) { Write-Host "NO VERDICT - the rig never wrote a log"; exit 2 }
Get-Content $log
$verdict = Select-String -Path $log -Pattern '^\[rain-pal\] (PASS|FAIL)' | Select-Object -Last 1
if (-not $verdict) { Write-Host "`nNO VERDICT - the rig never reached a decision"; exit 2 }
if ($Negative) {
    if ($verdict.Line -match 'FAIL') {
        Write-Host "`nCONTROL OK - the rig failed when it should have"; exit 0
    }
    Write-Host "`nCONTROL BROKEN - the rig passed on crossed expectations, so it is not"
    Write-Host "reading the colour RAM and any green run above meant nothing"; exit 1
}
if ($verdict.Line -match 'PASS') { exit 0 } else { exit 1 }
