#!/usr/bin/env python3
"""The alt.games.mk Discord QR code on the attract-mode Discord page.

`discord_info` (src/MKAMODE.ASM) paints a QR code onto the high score stone
with the CPU - no video ROM, no palette - out of `discqr_rows`, one .long per
module row (bit c = column c, 1 = dark).  This tool is the only thing that
writes that table: it encodes INVITE_URL itself (QR version 2, error level L,
byte mode, the mask the spec's penalty rules pick), so the build needs no
third-party library.

  python tools/make_discord_qr.py --apply      rewrite the generated block
  python tools/make_discord_qr.py --check      fail if the block is stale (Phase D)
  python tools/make_discord_qr.py --png out.png  render it, 8px a module

Change the invite: edit INVITE_URL, --apply, `build.py --asm-only`.
Version 2-L holds 32 bytes; a longer URL is refused rather than silently
growing the code (the draw routine packs a row into one .long, so the code
plus its quiet zone must stay within 32 modules).
"""
import argparse
import re
import sys
from pathlib import Path

INVITE_URL = "https://discord.gg/YNXXYenqG5"

ROOT = Path(__file__).resolve().parent.parent
ASM = ROOT / "src" / "MKAMODE.ASM"
BEGIN = "* >>> generated by tools/make_discord_qr.py - do not edit by hand"
END = "* <<< end of generated block"

VERSION = 2
SIZE = 17 + 4 * VERSION          # 25 modules
DATA_CW = 34                     # version 2-L: 44 codewords, 10 of them ECC
ECC_CW = 10
ALIGN = [6, 18]

# --- GF(256) Reed-Solomon, primitive 0x11d -------------------------------
EXP = [0] * 512
LOG = [0] * 256
_x = 1
for _i in range(255):
    EXP[_i] = _x
    LOG[_x] = _i
    _x <<= 1
    if _x & 0x100:
        _x ^= 0x11D
for _i in range(255, 512):
    EXP[_i] = EXP[_i - 255]


def gf_mul(a, b):
    return 0 if a == 0 or b == 0 else EXP[LOG[a] + LOG[b]]


def rs_ecc(data, n):
    gen = [1]
    for i in range(n):
        nxt = [0] * (len(gen) + 1)
        for j, g in enumerate(gen):
            nxt[j] ^= g
            nxt[j + 1] ^= gf_mul(g, EXP[i])
        gen = nxt
    rem = [0] * n
    for d in data:
        f = d ^ rem[0]
        rem = rem[1:] + [0]
        for j in range(n):
            rem[j] ^= gf_mul(gen[j + 1], f)
    return rem


def codewords(text):
    raw = text.encode("ascii")
    if len(raw) > 32:
        sys.exit(f"make_discord_qr: {len(raw)} bytes will not fit version 2-L (32)")
    bits = []

    def put(val, n):
        bits.extend((val >> (n - 1 - i)) & 1 for i in range(n))

    put(0b0100, 4)                 # byte mode
    put(len(raw), 8)
    for b in raw:
        put(b, 8)
    cap = DATA_CW * 8
    put(0, min(4, cap - len(bits)))
    while len(bits) % 8:
        bits.append(0)
    data = [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    pad = 0xEC
    while len(data) < DATA_CW:
        data.append(pad)
        pad ^= 0xEC ^ 0x11
    return data + rs_ecc(data, ECC_CW)


# --- matrix -----------------------------------------------------------------
def function_grid():
    m = [[0] * SIZE for _ in range(SIZE)]
    f = [[False] * SIZE for _ in range(SIZE)]

    def setf(x, y, dark):
        m[y][x] = 1 if dark else 0
        f[y][x] = True

    for i in range(SIZE):                       # timing
        setf(6, i, i % 2 == 0)
        setf(i, 6, i % 2 == 0)
    for cx, cy in ((3, 3), (SIZE - 4, 3), (3, SIZE - 4)):   # finders + separators
        for dy in range(-4, 5):
            for dx in range(-4, 5):
                x, y = cx + dx, cy + dy
                if 0 <= x < SIZE and 0 <= y < SIZE:
                    d = max(abs(dx), abs(dy))
                    setf(x, y, d not in (2, 4))
    for cx in ALIGN:                            # alignment (only 18,18 at v2)
        for cy in ALIGN:
            if f[cy][cx]:
                continue
            for dy in range(-2, 3):
                for dx in range(-2, 3):
                    setf(cx + dx, cy + dy, max(abs(dx), abs(dy)) != 1)
    format_bits(m, f, 0)                         # reserve the format areas
    return m, f


def format_bits(m, f, mask):
    data = (1 << 3) | mask                       # level L = 01
    rem = data
    for _ in range(10):
        rem = (rem << 1) ^ ((rem >> 9) * 0x537)
    bits = ((data << 10) | rem) ^ 0x5412

    def setf(x, y, dark):
        m[y][x] = 1 if dark else 0
        f[y][x] = True

    b = lambda i: (bits >> i) & 1
    for i in range(6):
        setf(8, i, b(i))
    setf(8, 7, b(6))
    setf(8, 8, b(7))
    setf(7, 8, b(8))
    for i in range(9, 15):
        setf(14 - i, 8, b(i))
    for i in range(8):
        setf(SIZE - 1 - i, 8, b(i))
    for i in range(8, 15):
        setf(8, SIZE - 15 + i, b(i))
    setf(8, SIZE - 8, 1)                         # the dark module


MASKS = [
    lambda x, y: (x + y) % 2 == 0,
    lambda x, y: y % 2 == 0,
    lambda x, y: x % 3 == 0,
    lambda x, y: (x + y) % 3 == 0,
    lambda x, y: (x // 3 + y // 2) % 2 == 0,
    lambda x, y: x * y % 2 + x * y % 3 == 0,
    lambda x, y: (x * y % 2 + x * y % 3) % 2 == 0,
    lambda x, y: ((x + y) % 2 + x * y % 3) % 2 == 0,
]


def place(cw, m, f):
    i, total = 0, len(cw) * 8
    right = SIZE - 1
    while right >= 1:
        if right == 6:
            right = 5
        for vert in range(SIZE):
            for j in range(2):
                x = right - j
                upward = ((right + 1) & 2) == 0
                y = SIZE - 1 - vert if upward else vert
                if not f[y][x] and i < total:
                    m[y][x] = (cw[i >> 3] >> (7 - (i & 7))) & 1
                    i += 1
        right -= 2


def penalty(m):
    s = 0
    lines = [row for row in m] + [list(col) for col in zip(*m)]
    for ln in lines:                              # N1 runs, N3 finder-alikes
        run = 1
        for k in range(1, SIZE + 1):
            if k < SIZE and ln[k] == ln[k - 1]:
                run += 1
            else:
                if run >= 5:
                    s += 3 + run - 5
                run = 1
        t = "".join(map(str, ln))
        for pat in ("10111010000", "00001011101"):
            s += 40 * sum(1 for k in range(len(t) - 10) if t[k:k + 11] == pat)
    for y in range(SIZE - 1):                     # N2 2x2 blocks
        for x in range(SIZE - 1):
            if m[y][x] == m[y][x + 1] == m[y + 1][x] == m[y + 1][x + 1]:
                s += 3
    dark = sum(map(sum, m))                       # N4 balance
    s += 10 * (abs(dark * 100 // (SIZE * SIZE) - 50) // 5)
    return s


def encode(text, force_mask=None):
    cw = codewords(text)
    best = None
    for mask in range(8) if force_mask is None else [force_mask]:
        m, f = function_grid()
        place(cw, m, f)
        for y in range(SIZE):
            for x in range(SIZE):
                if not f[y][x] and MASKS[mask](x, y):
                    m[y][x] ^= 1
        format_bits(m, f, mask)
        p = penalty(m)
        if best is None or p < best[0]:
            best = (p, mask, m)
    return best[1], best[2]


# --- the ASM block ----------------------------------------------------------
def block(text):
    mask, m = encode(text)
    out = [BEGIN,
           f"* {text}  (QR version {VERSION}-L, mask {mask})",
           f"discqr_n\t.set\t{SIZE}\t\t; modules per side",
           "discqr_rows\t\t\t\t; bit c = column c, 1 = dark"]
    for y, row in enumerate(m):
        val = sum(bit << x for x, bit in enumerate(row))
        out.append(f"\t.long\t0{val:08X}h\t\t; {''.join('#' if b else '.' for b in row)}")
    out.append(END)
    return "\n".join(out)


def current(src):
    a = src.find(BEGIN)
    b = src.find(END)
    if a < 0 or b < 0:
        sys.exit(f"make_discord_qr: generated block markers not found in {ASM}")
    return a, b + len(END)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--png")
    a = ap.parse_args()
    raw = ASM.read_bytes().decode("latin-1")
    nl = "\r\n" if "\r\n" in raw else "\n"
    src = raw.replace("\r\n", "\n")
    want = block(INVITE_URL)
    s, e = current(src)
    if a.png:
        from PIL import Image
        _, m = encode(INVITE_URL)
        q, px = 4, 8
        im = Image.new("L", ((SIZE + 2 * q) * px,) * 2, 255)
        for y, row in enumerate(m):
            for x, d in enumerate(row):
                if d:
                    im.paste(0, ((x + q) * px, (y + q) * px, (x + q + 1) * px, (y + q + 1) * px))
        im.save(a.png)
        print(f"make_discord_qr: wrote {a.png}")
    if a.check:
        if src[s:e] != want:
            print("make_discord_qr: MKAMODE.ASM's QR block is stale - run --apply")
            return 1
        print("make_discord_qr: QR block matches", INVITE_URL)
    if a.apply:
        src = src[:s] + want + src[e:]
        ASM.write_bytes(src.replace("\n", nl).encode("latin-1"))
        print("make_discord_qr: wrote the QR block for", INVITE_URL)
    return 0


if __name__ == "__main__":
    sys.exit(main())
