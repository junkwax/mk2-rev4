#!/usr/bin/env python3
r"""Write `tools/costume_expect.lua` - every fighter's per-lane costume words,
read out of the LINKED SOURCE, for the costume rigs to compare the screen
against.

The lane -> symbol mapping is parsed from MKGUYS.ASM's own
`character_palettes_N` tables and the words from whichever `src/*.ASM` defines
each symbol, so a pass means "the screen matches what is linked", not "the
screen matches a number somebody typed into a rig". Regenerate before every
run; the wrappers do.

Emits, per ochar:

    lanes = { {idx, press, sym, {words...}}, ... }   in costume_offer order
    distinct = how many DISTINCT palettes he has (what the drone rolls among)

`idx` is the index into `costume_offer` (MKGUYS.ASM), which is the order the
no-duplicate rule walks forward through, so a rig can predict exactly which
lane a shifted player 2 lands on.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_mk2pals import asm_palettes                                # noqa: E402
import make_costume_palettes as mcp                                  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "tools" / "costume_expect.lua"

# costume_offer's order (MKGUYS.ASM), which is what the walk follows
OFFER = [
    ("character_palettes_1", "default"),
    ("character_palettes_4", "START+HP"),
    ("character_palettes_2", "START+LP"),
    ("character_palettes_5", "START+HK"),
    ("character_palettes_6", "START+LK"),
    ("character_palettes_3", "START+BLOCK"),
]


def main() -> int:
    words: dict[str, list] = {}
    for f in sorted((REPO / "src").glob("*.ASM")):
        for k, v in asm_palettes(f).items():
            words.setdefault(k, v)

    lines = mcp.MKGUYS.read_text(encoding="latin-1").split("\n")
    rows = {tab: mcp.row_symbols(lines, tab) for tab, _ in OFFER}

    out = ["-- GENERATED by tools/costume_expect.py - do not edit.",
           "-- Per-lane costume palettes, parsed from MKGUYS.ASM's tables and the",
           "-- linked palette words, in costume_offer order.",
           "return {"]
    missing = []
    for och in range(mcp.ROWS):
        who = mcp.ROSTER.get(och, (None, "ochar %d" % och))[1]
        seen, lanes = [], []
        for idx, (tab, press) in enumerate(OFFER):
            sym = rows[tab][och][0]
            w = words.get(sym)
            if w is None:
                missing.append(sym)
                continue
            if w not in seen:
                seen.append(w)
            lanes.append((idx, press, sym, w))
        if not lanes:
            continue
        out.append("  [%d] = { who = %r, distinct = %d, lanes = {" % (och, who, len(seen)))
        for idx, press, sym, w in lanes:
            out.append("    { idx = %d, press = %r, sym = %r, words = {%s} },"
                       % (idx, press, sym, ",".join("0x%04X" % x for x in w)))
        out.append("  } },")
    out.append("}")

    if missing:
        print("WARNING: no words found for %d symbols: %s"
              % (len(missing), ", ".join(sorted(set(missing))[:8])))
    OUT.write_text("\n".join(out) + "\n", encoding="latin-1")
    print("wrote %s" % OUT.name)

    # a rig can only discriminate where the lanes actually differ, so say so
    print("\nochar fighter      distinct palettes across the six lanes")
    for och in sorted(mcp.ROSTER):
        who = mcp.ROSTER[och][1]
        seen = []
        for tab, _ in OFFER:
            w = words.get(rows[tab][och][0])
            if w is not None and w not in seen:
                seen.append(w)
        print("  %-3d %-12s %d" % (och, who, len(seen)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
