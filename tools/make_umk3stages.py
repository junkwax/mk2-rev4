def part_files(L):
    S, imgs = L["S"], L["imgs"]
    groups, _ = deal(L)
    files = {}
    for (name, s, e, ppp), group in zip(S["packs"], groups):
        if not group:
            continue
        bdd = bytearray(b"%d\n" % len(group))
        for idx in group:
            im = imgs[idx]
            bdd += b"%x %d %d %d\n" % (idx, im["w"], im["h"], im["big"])
            bdd += im["px"]
        for label, words, _p in L["pals"]:
            bdd += b"%s %d\n" % (label.encode(), len(words))
            bdd += struct.pack("<%dH" % len(words), *words)
        x, lines = 0, []
        for idx in group:
            lines.append("4000 %d 0 %X 0" % (x, idx))
            x += imgs[idx]["w"] + 4
        hmax = max(imgs[i]["h"] for i in group)
        bdb = [f"{name} {max(x, 1)} {hmax} 255 1 {len(L['pals'])} {len(group)}",
               f"{name} 0 {max(x - 5, 0)} 0 {hmax - 1}"] + lines
        files[f"{name}.BDD"] = bytes(bdd)
        files[f"{name}.BDB"] = ("\n".join(bdb) + "\n").encode()
        why = ("per-block auto depth, as every BBB> in MK7MIL" if ppp == 0 else
               "LOAD2's auto depth ignores a block's LAST pixel; these need more bits there")
        files[f"{name}.LOD"] = LOD_BBB.format(addr=court.lod_addr(s - RELOC), title=S["title"],
                                              name=name, start=s, end=e, rec=S["rec"], out=S["out"],
                                              ppp=ppp, why=why).encode()
    sp = L["spr"]
    if sp:
        names = spr_order(L)
        entries = [(nm, sp["recs"][nm]["ax"], sp["recs"][nm]["ay"], sp["recs"][nm]["w"],
                    sp["recs"][nm]["h"], sp["recs"][nm]["px"], 0) for nm in names]
        files[S["spr_img"]] = pit.build_img(entries, [(f"{S['lab']}SPR_P", cave._bpp(len(sp["pal"]) - 1),
                                                       sp["pal"])])
        name, s, e = S["spr"]
        files[f"{name}.LOD"] = LOD_SPR.format(addr=court.lod_addr(s - RELOC), title=S["title"],
                                              start=s, end=e, ppp=SPR_PPP, img=S["spr_img"],
                                              tbl=S["spr_tbl"], recs="---> " + ",".join(names)).encode()
    if S["floor"]:
        name, s, e = S["floor"]
        files[f"{name}.LOD"] = LOD_FLOOR.format(addr=court.lod_addr(s - RELOC), title=S["title"],
                                                start=s, end=e, bin=S["floor_bin"], src=S["floor_src"],
                                                name=name, sym=S["floor_sym"]).encode()
        # one guard row after the last - the skew floor reads past a row's end
        # at the right scroll limit (SCORPION'S LAIR's yellow dash, 2026-10-08)
        row = FLOOR_W * 6 // 8
        files[S["floor_bin"]] = L["floor"] + L["floor"][-row:]
    return files


