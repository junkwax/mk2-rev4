def snap_of(name):
    return LOAD2 / f"BGNDTBL.{name[-3:]}"


def read_hdrs(snap):
    """cave.read_hdrs, for a pack name of four characters: LOAD2 names the
    table after the BDB name less its first four, so USC1 / UP31 give a bare
    `HDRS:` (DSRT1 gives `1HDRS:`), which cave's regex (word chars, then HDRS) does not match."""
    tmp = LOAD2 / (snap.name + ".hdrs")
    text = snap.read_text(encoding="latin-1", errors="replace")
    tmp.write_text(re.sub(r"^HDRS:", "XHDRS:", text, count=1, flags=re.M), encoding="latin-1")
    try:
        return cave.read_hdrs(tmp)
    finally:
        tmp.unlink()


