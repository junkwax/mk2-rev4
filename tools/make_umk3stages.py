def read_record(rom, S):
    for at, words in S["code_checks"].items():
        if [rom.w(at + 16 * i) for i in range(len(words))] != words:
            raise SystemExit(f"{S['title']}: UMK3 code at {at:08X} is not what this import was read from")
    rec_at = S["rec"]
    if rom.l(STAGE_TABLE + 32 * S["idx"]) != rec_at:
        raise SystemExit(f"UMK3's stage table no longer points {S['idx']:02X} at {rec_at:08X}")
    rec = dict(erase=rom.w(rec_at), worldy=rom.sw(rec_at + 16), ground=rom.w(rec_at + 32),
               start=rom.w(rec_at + 48), left=rom.w(rec_at + 64), right=rom.w(rec_at + 80),
               calla=rom.l(rec_at + 96), scroll=rom.l(rec_at + 128), dlists=rom.l(rec_at + 160))
    if (rec["calla"], rec["scroll"], rec["dlists"]) != (S["calla"], S["scroll"], S["dlists"]):
        raise SystemExit(f"{S['title']}: the record's pointers moved")
    mods, a, plane = [], rec_at + 224, 1
    while True:
        v = rom.l(a)
        if v == 1:
            plane += 1
            a += 32
            continue
        if v in (0xFFFFFFFE, 0xFFFFFFFF):
            break
        mods.append(dict(addr=v, w=rom.w(v), h=rom.w(v + 16), n=rom.w(v + 32),
                         hdrs=rom.l(v + 80), pals=rom.l(v + 112), blks=lair.blocks(rom, v),
                         x=rom.sw(a + 32), y=rom.sw(a + 48), plane=plane))
        plane += 1
        a += 64
    if [m["plane"] for m in mods] != S["planes"]:
        raise SystemExit(f"{S['title']}: planes {[m['plane'] for m in mods]}, not {S['planes']}")
    centred = []
    if rom.l(a) == 0xFFFFFFFE:
        a += 32
        while (m := rom.l(a)) != 0:
            var = rom.l(a + 32)
            p = {0x0105DAB0: 1, 0x0105DA90: 2, 0x0105DA70: 3, 0x0105DA50: 4,
                 0x0105DA30: 5, 0x0105DA10: 6}.get(var)
            md = next((md for md in mods if md["addr"] == m), None)
            if md is None:
                # a camera centred on a module the record does not DRAW (the
                # Dorfen centres plane 1 on the skipped front walls): nothing
                # is on that plane, so its camera changes no pixel
                if m not in S.get("undrawn_centre", ()):
                    raise SystemExit(f"{S['title']}: plane {p} is centred on {m:08X}, "
                                     "which is in no module of the record")
                centred.append((p, None))
            else:
                centred.append((p, md["plane"]))
            a += 64
        a += 32
    if [p for p, _m in centred] != S["centred"]:
        raise SystemExit(f"{S['title']}: centres cameras {centred}, not {S['centred']}")
    rec["centred"] = centred
    if S["floor"]:
        rec["floor"] = dict(sag=rom.l(a), pal=rom.l(a + 32), height=rom.w(a + 64),
                            scroll=rom.l(a + 80), skew=rom.l(a + 112))
        if rec["floor"]["skew"] != SKEW_7:
            raise SystemExit(f"{S['title']}: the floor is no longer skew_7")
    for md in mods:
        md["rate"] = rom.l(S["scroll"] + 32 * (8 - md["plane"]))
        if len(md["blks"]) != md["n"]:
            raise SystemExit(f"UMK3 module {md['addr']:08X}: block count disagrees")
    return rec, mods


def art(rom, S, mods):
    hd, pl = mods[0]["hdrs"], mods[0]["pals"]
    if any((m["hdrs"], m["pals"]) != (hd, pl) for m in mods):
        raise SystemExit(f"{S['title']}: the modules no longer share one header table")
    order = sorted({b[3] & 0xFFF for m in mods for b in m["blks"]})
    imgs = {}
    for i in order:
        a = hd + 80 * i
        w, h, sag, ctrl = rom.w(a), rom.w(a + 16), rom.l(a + 32), rom.w(a + 64)
        rows, _ = pit.decode_record(rom.g, sag, w, h, ctrl)
        imgs[i] = dict(idx=i, w=w, h=h, big=0, px=bytes(v for r in rows for v in r), mk_sag=sag)
    share, first = {}, {}
    for i in order:
        k = imgs[i]["mk_sag"]
        if k in first:
            share[i] = first[k]
        else:
            first[k] = i
    uniq = [i for i in order if i not in share]
    used = sorted({thr.pal_of(b) for m in mods for b in m["blks"]})
    remap = {p: k for k, p in enumerate(used)}
    pals = [(f"{S['lab']}_P{k:02d}", rom.palette(rom.l(pl + 32 * p)), p) for k, p in enumerate(used)]
    return imgs, order, uniq, pals, remap, share


def sprites(rom, S):
    sp = S["sprite"]
    if not sp:
        return None
    frames = hold_list(rom, sp["lst"])
    if not frames or frames[0] != sp["first"]:
        raise SystemExit(f"{S['title']}: the animator list {sp['lst']:08X} changed")
    pal = rom.palette(rom.l(frames[0] + 112))
    recs = {}
    for k, a in enumerate(frames):
        im = lair.rec_image(rom, a)
        if max(im["px"]) >= len(pal):
            raise SystemExit(f"{sp['name']}{k + 1} indexes {max(im['px'])}, its palette has {len(pal)}")
        recs[f"{sp['name']}{k + 1}"] = im
    return dict(rate=sp["rate"], x=sp["x"], y=sp["y"], recs=recs, pal=pal, n=len(frames),
                umk3_list=sp["umk3_list"], name=sp["name"])


def layout(key):
    S = STAGES[key]
    rom = R()
    rec, mods = read_record(rom, S)
    imgs, order, uniq, pals, remap, share = art(rom, S, mods)
    L = dict(key=key, S=S, rom=rom, rec=rec, mods=mods, imgs=imgs, order=order, uniq=uniq,
             pals=pals, remap=remap, share=share, spr=sprites(rom, S))
    if S["floor"]:
        fl = rec["floor"]
        fb = (fl["sag"] + 0x2000000) >> 3           # MK3's setup_floor_info adds 02000000h
        L["floor"] = bytes(rom.g[fb:fb + FLOOR_W * fl["height"] * 6 // 8])
        L["floorpal"] = rom.palette(fl["pal"])
    return L


def rec_scroll(L, plane):
    """UMK3 plane's rate (0 = the fighters)."""
    return L["rom"].l(L["S"]["scroll"] + 32 * (8 - plane)) if 0 <= plane <= 8 else 0


def mk2_plane(L, p):
    return p + L["S"]["shift"]


def mk2_rates(L):
    sh = L["S"]["shift"]
    return {e: rec_scroll(L, e - sh) for e in range(1, 9)}


