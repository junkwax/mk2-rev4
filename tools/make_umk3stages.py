def plane_x(L, cam):
    """Every UMK3 camera's worldtlx at a fighters' camera of `cam` (centre_x
    for the planes the record centres, each on its own module's width)."""
    s = L["rec"]["start"]
    out = {}
    for e in range(9):
        base = s
        hit = [mp for cp, mp in L["rec"]["centred"] if cp == e and mp is not None]
        if hit:
            md = next(m for m in L["mods"] if m["plane"] == hit[0])
            base = md["w"] // 2 - 399 // 2      # center_x: scrrgt/2
        out[e] = base + (cam - s) * rec_scroll(L, e) // 0x20000
    return out


def render(L, cam):
    from PIL import Image, ImageDraw
    rec = L["rec"]
    px_x = plane_x(L, cam)
    scr = Image.new("RGB", (SCREEN_W, SCREEN_H), court.rgb(rec["erase"]))
    px = scr.load()

    def put(im, ox, oy, pal, flip=False):
        w, h = im["w"], im["h"]
        for y in range(h):
            ty = oy + y
            if not 0 <= ty < SCREEN_H:
                continue
            row = im["px"][y * w:(y + 1) * w]
            for x in range(w):
                tx = ox + x
                if 0 <= tx < SCREEN_W:
                    v = row[w - 1 - x] if flip else row[x]
                    if v:
                        px[tx, ty] = court.rgb(pal[v])

    def plane(p):
        md = next((m for m in L["mods"] if m["plane"] == p), None)
        if md is None:
            return
        for blk in sorted(md["blks"], key=lambda b: b[0] & 0xFFF0):
            f, bx, by, hw = blk
            put(L["imgs"][hw & 0xFFF], md["x"] + bx - px_x[p], md["y"] + by - rec["worldy"],
                L["pals"][L["remap"][thr.pal_of(blk)]][1], bool(f & 0x10))

    sp = L["spr"]
    for p in range(8, 0, -1):
        plane(p)
        if sp and p == sp["umk3_list"]:
            im = sp["recs"][f"{sp['name']}1"]
            put(im, sp["x"] - px_x[p], sp["y"] - rec["worldy"], sp["pal"])
    if L["S"]["floor"]:
        fl, h = L["floor"], rec["floor"]["height"]
        y0 = 254 - h
        bits = int.from_bytes(fl, "little")
        cx = px_x[0] - rec["start"] + (FLOOR_W - SCREEN_W) // 2
        for r in range(h):
            for x in range(SCREEN_W):
                c = (x + cx) % FLOOR_W
                v = (bits >> (6 * (r * FLOOR_W + c))) & 63
                if v and 0 <= y0 + r < SCREEN_H:
                    px[x, y0 + r] = court.rgb(L["floorpal"][v])
    gy = rec["ground"] - GROUND_LIFT - rec["worldy"]
    ImageDraw.Draw(scr).line([(0, gy), (SCREEN_W - 1, gy)], fill=(255, 0, 0))
    return scr


def preview(L, cams):
    from PIL import Image, ImageDraw
    rec = L["rec"]
    cams = cams or [rec["left"], rec["start"], rec["right"]]
    out = ROOT / "tmp" / f"umk3{L['key']}"
    out.mkdir(parents=True, exist_ok=True)
    shots = [(c, render(L, c)) for c in cams]
    sheet = Image.new("RGB", (SCREEN_W, (SCREEN_H + 12) * len(shots)), (16, 16, 20))
    dr = ImageDraw.Draw(sheet)
    for k, (c, im) in enumerate(shots):
        sheet.paste(im, (0, k * (SCREEN_H + 12)))
        dr.text((4, k * (SCREEN_H + 12) + 2), "camera %d" % c, fill=(255, 255, 0))
    sheet.save(out / "preview.png")
    print(f"wrote {out / 'preview.png'}")


def report(L):
    S, rec = L["S"], L["rec"]
    print(f"{S['title']} (UMK3) - record {S['rec']:08X}, curback {S['curback']:02X}h  (Wolf only)")
    print(f"  erase {rec['erase']:04X} ground {rec['ground']} world y {rec['worldy']} start "
          f"{rec['start']} limits {rec['left']}..{rec['right']}  centred {rec['centred']}")
    for md in L["mods"]:
        print(f"    UMK3 plane {md['plane']} -> MK2 baklst{mk2_plane(L, md['plane'])}  "
              f"{md['w']:5d}x{md['h']:<4d} at ({md['x']:4d},{md['y']:4d})  "
              f"rate {md['rate']:06X}  {len(md['blks'])} blocks")
    print(f"  art: {len(L['order'])} headers, {len(L['uniq'])} payloads, {len(L['pals'])} palettes")
    groups, used = deal(L)
    for (name, s, e, ppp), g, u in zip(S["packs"], groups, used):
        print(f"  {name} PPP>{ppp} {s:07X}..{e:07X}: {len(g)} images ~{u // 8:,} B of {e - s:,}")
    if S["floor"]:
        print(f"  floor {rec['floor']['sag']:08X} h {rec['floor']['height']}, {len(L['floor']):,} B")
    sp = L["spr"]
    if sp:
        tot = sum(cave.packed_bits(dict(im, big=0)) for im in sp["recs"].values()) // 8
        print(f"  sprite: {sp['n']} frames at {sp['rate']} ticks, ~{tot:,} B, top-left "
              f"({sp['x']},{sp['y']}) on UMK3 baklst{sp['umk3_list']} -> MK2 "
              f"baklst{sp['umk3_list'] + S['shift']}")


def run(key, a):
    L = layout(key)
    S = L["S"]
    if a.report:
        report(L)
    if a.preview is not None:
        preview(L, a.preview)
    files = {}
    if a.parts or a.check:
        files.update(part_files(L))
    if a.parts:
        for nm, data in files.items():
            (DATA / nm).write_bytes(data)
            print(f"wrote data/{nm}  ({len(data):,} bytes)")
    if a.apply or a.check:
        hdrs = merged_headers(L)
        bad, fs, stbl = verify_rom(L, hdrs)
        if bad:
            raise SystemExit(f"{S['title']}'s art is not UMK3's:\n  " + "\n  ".join(bad))
        asm = build_asm(L, hdrs, fs, stbl)
        out = SRC / S["out"]
        if a.apply:
            out.write_text(asm, encoding="latin-1")
            print(f"wrote src/{S['out']}  ({len(asm.splitlines())} lines)")
        if a.check:
            drift = [f"data/{nm} is not the tool's - rerun --parts" for nm, data in files.items()
                     if not (DATA / nm).exists() or (DATA / nm).read_bytes() != data]
            if not out.exists() or out.read_text(encoding="latin-1") != asm:
                drift.append(f"src/{S['out']} has drifted - rerun --apply")
            if drift:
                raise SystemExit(f"{S['title']} (UMK3) check FAILED:\n  " + "\n  ".join(drift))
            print(f"{S['title']} (UMK3): packs, tables and packed pixels all match umk3.zip")


