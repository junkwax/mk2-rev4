def hold_list(rom, lst):
    """An ani list up to its ani_jump (anything that is not a ROM pointer)."""
    out, k = [], 0
    while (v := rom.l(lst + 32 * k)) >= 0xFF800000:
        out.append(v)
        k += 1
    return out


