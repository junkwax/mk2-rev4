#!/usr/bin/env python3
"""
mobility.py - walk and jump, per character, in px/tick and px.

Section 4.6 of doc/TOURNAMENT_READINESS.md: "walk speed, jump height, jump
distance, jump duration ... none of it is in a table, and per-character speed
tables demonstrably exist." Half the neutral game, and nothing stated it.

WALK is per character. `get_walk_info_f` / `_b` (MKGUYS.ASM) index
`walk_forward_info` / `walk_backward_info`, one `.word rate,vel` per ochar, and
`decode_walk_table` does `sll 4,a1` - so the stored word is the velocity in
16.16 SHIFTED RIGHT FOUR. Real velocity is `word << 4`, i.e. `word / 4096`
pixels per tick.

JUMP IS NOT per character, which is worth saying out loud: `up_vel`, `up_grav`
and the angle-jump x velocity are single equates in MAINEQU.ASM/JOY.ASM shared
by the whole cast. Every fighter jumps exactly the same height, for exactly the
same number of ticks, and covers exactly the same distance. All the mobility
difference in MK2 is on the ground.

One tick is one display refresh at 54.7068 Hz.

  python tools/mobility.py
  python tools/mobility.py --csv doc/mobility.csv
"""
import argparse
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
TICK_HZ = 54.7068

CHARS = ["hathead", "liu kang", "cage", "baraka", "kitana", "mileena", "shang",
         "raiden", "sub-zero", "reptile", "scorpion", "jax", "kintaro",
         "shao kahn", "smoke", "noob", "jade"]


def read(p):
    return open(p, encoding="latin-1", errors="replace").read()


def num(t):
    t = t.strip()
    try:
        return int(t[:-1], 16) if t and t[-1] in "hH" else int(t, 0)
    except ValueError:
        return None


def walk_table(text, label):
    """`.word rate,vel` per ochar. vel is the 16.16 value >> 4."""
    m = re.search(r"^%s\s*$" % re.escape(label), text, re.M)
    if not m:
        return []
    out = []
    for line in text[m.end():].splitlines():
        c = line.split(";")[0].strip()
        if not c:
            continue
        mm = re.match(r"\.[wW][oO][rR][dD]\s+(\d+)\s*,\s*0?([0-9a-fA-F]+)h", c)
        if mm:
            out.append((int(mm.group(1)), int(mm.group(2), 16)))
            continue
        if re.match(r"^[A-Za-z_]", c):
            break
    return out


def equate(text, name):
    m = re.search(r"^%s\s+\.set\s+(\S+)" % re.escape(name), text, re.M)
    return num(m.group(1)) if m else None


def s32(v):
    return v - (1 << 32) if v is not None and v >= (1 << 31) else v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv")
    args = ap.parse_args()

    guys = read(os.path.join(SRC, "MKGUYS.ASM"))
    fwd = walk_table(guys, "walk_forward_info")
    bwd = walk_table(guys, "walk_backward_info")

    eq = read(os.path.join(SRC, "MAINEQU.ASM"))
    up_vel = s32(equate(eq, "up_vel"))
    up_grav = equate(eq, "up_grav")

    joy = read(os.path.join(SRC, "JOY.ASM"))
    m = re.search(r"movi\s+0?([0-9a-fA-F]+)h,a11\s*;\s*x vel", joy)
    ang_x = int(m.group(1), 16) if m else None

    rows = []
    for oc, name in enumerate(CHARS):
        f = fwd[oc] if oc < len(fwd) else None
        b = bwd[oc] if oc < len(bwd) else None
        rows.append(dict(
            char=name,
            fwd_rate=f[0] if f else None,
            fwd_px_tick=round((f[1] << 4) / 65536.0, 3) if f else None,
            bwd_rate=b[0] if b else None,
            bwd_px_tick=round((b[1] << 4) / 65536.0, 3) if b else None))

    print("# Mobility\n")
    print("Generated by `tools/mobility.py`. One tick is one display refresh at")
    print("%.4f Hz, so **%.2f ms**.\n" % (TICK_HZ, 1000.0 / TICK_HZ))

    print("## Walk - this is where the cast differs\n")
    print("`rate` is ticks per animation row (lower = faster legs); the speed")
    print("column is what actually moves the fighter.\n")
    print("| character | fwd px/tick | fwd px/sec | back px/tick | back px/sec "
          "| fwd rate | back rate |")
    print("|---|---|---|---|---|---|---|")
    for r in rows:
        if r["fwd_px_tick"] is None:
            continue
        print("| %s | %.3f | %.0f | %.3f | %.0f | %s | %s |" % (
            r["char"], r["fwd_px_tick"], r["fwd_px_tick"] * TICK_HZ,
            r["bwd_px_tick"], r["bwd_px_tick"] * TICK_HZ,
            r["fwd_rate"], r["bwd_rate"]))

    vals = [r["fwd_px_tick"] for r in rows if r["fwd_px_tick"]]
    if vals:
        lo, hi = min(vals), max(vals)
        fast = [r["char"] for r in rows if r["fwd_px_tick"] == hi]
        slow = [r["char"] for r in rows if r["fwd_px_tick"] == lo]
        print()
        print("Forward walk spans **%.3f to %.3f px/tick, a %.0f%% spread** - "
              "fastest %s, slowest %s." % (lo, hi, 100 * (hi / lo - 1),
                                           ", ".join(fast), ", ".join(slow)))

    print("\n## Jump - identical for everybody\n")
    if None in (up_vel, up_grav):
        print("could not resolve up_vel / up_grav")
    else:
        v = -up_vel / 65536.0
        g = up_grav / 65536.0
        apex = v / g
        print("| | value | |")
        print("|---|---|---|")
        print("| initial y velocity (`up_vel`) | %.1f px/tick | up |" % v)
        print("| gravity (`up_grav`) | %.2f px/tick^2 | |" % g)
        print("| time to apex | **%.0f ticks** | %.0f ms |"
              % (apex, apex * 1000 / TICK_HZ))
        print("| full airtime | **%.0f ticks** | %.0f ms |"
              % (2 * apex, 2 * apex * 1000 / TICK_HZ))
        print("| jump height | **%.0f px** | v^2/2g |" % (v * v / (2 * g)))
        if ang_x:
            x = (ang_x) / 65536.0
            print("| angle-jump x velocity | %.1f px/tick | |" % x)
            print("| angle-jump distance | **%.0f px** | x * airtime |"
                  % (x * 2 * apex))
        print()
        print("`up_vel`, `up_grav` and the angle-jump x velocity are single")
        print("equates shared by the whole cast - **no character jumps higher,")
        print("further or longer than any other.** Every mobility difference in")
        print("MK2 is on the ground, which is worth knowing before anyone")
        print("tunes a matchup on 'he has a better jump'.")

    m = re.search(r"^secretwalk\s+\.set\s+(\S+)", eq, re.M)
    on = m.group(1).strip() if m else "MISSING"
    print("\n## The hidden fighters: boss scaling, and the `secretwalk` gate\n")
    print("The table above is the RAW data, and in it Smoke, Noob and Jade walk")
    print("at 4.5 / 4.0 / 4.5 px per tick against 2.5 for most of the cast.")
    print("They also take 3/4 damage through `ochar_damage_table`. Both are")
    print("boss scaling - they exist to make a SECRET OPPONENT a hard fight -")
    print("and in a two-player match they simply hand one player a mobility and")
    print("a durability edge that nothing in the data pays for: Smoke and Noob")
    print("share `nj_strikes` byte for byte with the ninjas (all 32 records),")
    print("and Jade shares `fn_strikes` with the female ninjas (all 26).\n")
    print("The damage side was already gated by `xlate_secret` (JOY.ASM), which")
    print("applies the 3/4 only when the CPU is playing them. **`secretwalk`**")
    print("(currently **%s**) does the same for walk speed, in" % on)
    print("`decode_walk_table`: a HUMAN Smoke or Noob borrows `ft_subzero`'s")
    print("row and a human Jade borrows `ft_fn1`'s - the walk of the character")
    print("whose move table they are already using - while the CPU keeps the")
    print("boss speed.\n")
    print("So read the walk table above as the CPU's speeds. With the gate on,")
    print("a human plays those three at 2.500 / 2.500 / 3.125 forward.\n")
    print("> Verified statically, not in game: a human Smoke, Noob or Jade")
    print("> cannot be reached by any rig - character-select forcing and")
    print("> `test_mode` both fail to start the fight, and only the select")
    print("> cheat produces one. The gate is instruction-identical in form to")
    print("> the shipped `xlate_secret` and uses `get_char_long`'s exact")
    print("> indexing, and it is covered by `doc/balance.lock`.")

    if args.csv:
        out = args.csv if os.path.isabs(args.csv) else os.path.join(ROOT, args.csv)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", newline="", encoding="utf-8") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        print("\ncsv -> %s" % args.csv, file=sys.stderr)


if __name__ == "__main__":
    main()
