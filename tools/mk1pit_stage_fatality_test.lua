-- mk1pit_stage_fatality_test.lua
--
-- THE PIT (MK1), curback 01Ah: the stage and its uppercut fatality, one trial.
--
-- Liu Kang's Back,Forward,Forward + Low Kick (scom_lk_dtp -> check_dtp) during a
-- forced FINISH HIM, with the victim pinned at MP_VX.  do_down_the_mk1pit
-- (MKDEATH) uppercuts him with act_mk1pit_fall and r_fall_down_mk1pit
-- (MK1PTOP.ASM) rides the camera down MK1's shaft onto the spikes.
--
-- What is checked, separately:
--   trigger  the victim gets act_mk1pit_fall (050Dh)
--   sky      mk1p_sky_lst holds the whole sky at fight start (mk1p_sky_objs)
--   camera   worldtly ends EXACTLY on mk1p_fall_cam - short and the floor is
--            off the bottom of the screen, past and the modules run out
--   landing  he comes to rest on the pit floor (oypos near mk1p_floor_y) and
--            ON the screen (mk1p_hold_on_screen)
--   payoff   f_death = -1
--
-- The layout numbers are read out of src/MK1PTOPB.ASM (generated by
-- tools/make_mk1pit.py) so the rig follows the ROM it is testing.
--
-- Env knobs: MP_VX (default 400), MP_GAP (55), MP_SIDE (left|right, the
-- ATTACKER's side), MP_OBSERVE (frames after the fall, 260), MP_TEST_LOG.

local ROOT = (os.getenv("MK2_ROOT") or "C:/Users/you/Workplace/mk2-main"):gsub("\\", "/")

local function getenv_int(name, default)
    local raw = os.getenv(name)
    if not raw or raw == "" then return default end
    return tonumber(raw) or default
end

local LOG_PATH = os.getenv("MP_TEST_LOG") or (ROOT .. "/tools/mk1pit_stage_fatality_test.log")
local VICTIM_X = getenv_int("MP_VX", 400)
local GAP = getenv_int("MP_GAP", 55)
local SIDE = (os.getenv("MP_SIDE") or "left"):lower()
local OBSERVE_FRAMES = getenv_int("MP_OBSERVE", 260)
local CAMERA_SETTLE = getenv_int("MP_SETTLE", 540)
-- MP_MOVE=combo (default) drives Liu Kang's Back,Forward,Forward+LK through
-- check_dtp; MP_MOVE=uppercut throws a plain Down+High Punch - MK1's rule, any
-- clean uppercut in FINISH HIM goes down the pit (do_uppercut's ucut_mk1pit).
local MOVE = (os.getenv("MP_MOVE") or "combo"):lower()
local BLOODDUMP = (os.getenv("MP_BLOODDUMP") or "") ~= ""
-- MP_FALLTRACE=1: one line per TICK for the whole fall - the victim's screen
-- x, his x velocity and his y velocity.  It is how the SHAPE of the arc gets
-- judged instead of eyeballed: mk1p_hold_on_screen writes oxvel every tick,
-- so a wall, a reversal or a dead stop all show up here as a step in a
-- column of numbers long before a 20-tick snapshot can show it.
local FALLTRACE = (os.getenv("MP_FALLTRACE") or "") ~= ""

local EQ = {}
do
    local fh = io.open(ROOT .. "/src/MK1PTOPB.ASM", "r")
    if fh then
        for line in fh:lines() do
            local name, val = line:match("^(mk1p_[%w_]+)%s+%.set%s+(%-?%w+)")
            if name then
                local hex = val:match("^0?(%x+)[hH]$")
                EQ[name] = hex and tonumber(hex, 16) or tonumber(val)
            end
        end
        fh:close()
    end
end

local logfh = io.open(LOG_PATH, "w")
local frame = 0
local function log(fmt, ...)
    local line = "[mk1pit] " .. (select("#", ...) > 0 and string.format(fmt, ...) or tostring(fmt))
    print(line)
    if logfh then logfh:write(line, "\n"); logfh:flush() end
end
local function s16(v) v = v & 0xffff; if v >= 0x8000 then return v - 0x10000 end return v end
local function s32(v) v = v & 0xffffffff; if v >= 0x80000000 then return v - 0x100000000 end return v end

local symbols = {}
do
    local fh = io.open(ROOT .. "/src/mk2.map", "r")
    if fh then
        for line in fh:lines() do
            for addr, name in line:gmatch("(%x%x%x%x%x%x%x%x)%s+([%w_%.]+)") do
                symbols[name] = tonumber(addr, 16)
            end
        end
        fh:close()
    end
end
local function sym(name)
    local v = symbols[name]
    if v == nil then log("WARN missing symbol %s", name); return 0 end
    return v
end

local A = {
    gstate = sym("gstate"), p1_state = sym("p1_state"), p2_state = sym("p2_state"),
    p1_char = sym("p1_char"), p2_char = sym("p2_char"),
    p1_obj = sym("p1_obj"), p2_obj = sym("p2_obj"),
    p1_proc = sym("p1_proc"), p2_proc = sym("p2_proc"),
    curback = sym("curback"), winner_status = sym("winner_status"),
    f_death = sym("f_death"), worldtlx = sym("worldtlx"), worldtly = sym("worldtly"),
    dizzy_dude = sym("dizzy_dude"), dizzy = sym("dizzy"), sky = sym("mk1p_sky_lst"),
    objlst = sym("objlst"),
}
local O = { next = 0x000, oxvel = 0x040, oyvel = 0x060, oxval = 0x080, oxpos = 0x090,
            oyval = 0x0a0, oypos = 0x0b0, ozpos = 0x0d0, ochar = 0x1f0 }
local P = { wake = 0x0e0, action = 0x1f0, flags = 0x210 }

local GS_PSEL, GS_FIGHTING = 4, 2
local PS_ACTIVE = 1
local FT_KANG, FT_JAX = 1, 11
local STAGE = 0x1a
local ACT_FALL, ACT_STUNNED = 0x050d, 0x0400
local PM_REACTING, PM_SITDUCK, PM_SPECIAL = 0x0004, 0x0008, 0x0010

local space, fields = nil, {}
local last_gstate = -1
local charsel_frame, fighting_frame, p1_confirm_start = 0, 0, 0
local finish_forced_frame, victim_dizzy_forced = 0, false
local attempt_start, attempt_n = 0, 0
local fall_start_frame = 0
local cam_y_max = -32768
local sky_count, sky_moved = nil, nil
local sky_first_x = {}
local land_frame, land_x, land_y, land_scr = 0, nil, nil, nil
-- The horizontal shape of the fall.  mk1p_hold_on_screen may turn him round
-- ONCE - the uppercut throws him out, the lean brings him back - and a second
-- reversal means something is fighting it: repell shoving the pair apart as
-- the body falls past the winner, rep8 halving the request, or a rule that
-- assigns a velocity outright instead of accelerating towards one.  All three
-- of those were live at once before 2026-09-22 and the fall changed direction
-- seven times.  Counted on the SIGN only, so a lean easing off is not a turn.
local xv_sign, xv_turns = 0, 0
local finished, snap_index, last_status = false, 0, 0

local function r16(a) return space:read_u16(a) end
local function r32(a) return space:read_u32(a) end
local function w16(a, v) space:write_u16(a, v & 0xffff) end
local function w32(a, v) space:write_u32(a, v & 0xffffffff) end

local function snap(label)
    local ok, s = pcall(function() return manager.machine.screens[":screen"] end)
    if ok and s then pcall(function() s:snapshot() end) end
    log("SNAP idx=%04d frame=%d label=%s", snap_index, frame, label)
    snap_index = snap_index + 1
end

local function sky_objects()
    local out, obj, guard = {}, r32(A.sky), 0
    while obj ~= 0 and guard < 200 do
        out[#out + 1] = obj
        obj = r32(obj + O.next)
        guard = guard + 1
    end
    return out
end

local function victim() return r32(A.p2_obj) end
local function attacker() return r32(A.p1_obj) end
local function p2_action()
    local p = r32(A.p2_proc); if p == 0 then return 0xffff end
    return r16(p + P.action)
end

local function state_line(tag)
    local a, v = attacker(), victim()
    return string.format("%s gs=%d ws=%d fdeath=%d p2act=0x%04x atk_x=%d vic_x=%d vic_y=%d "
        .. "vic_yvel=%d wtlx=%d wtly=%d sky=%d",
        tag, r16(A.gstate), r16(A.winner_status), s16(r16(A.f_death)), p2_action(),
        a ~= 0 and r16(a + O.oxpos) or -1, v ~= 0 and s16(r16(v + O.oxpos)) or -1,
        v ~= 0 and s16(r16(v + O.oypos)) or -1, v ~= 0 and s32(r32(v + O.oyvel)) // 65536 or 0,
        s16(r16(A.worldtlx + 16)), s16(r16(A.worldtly + 16)), #sky_objects())
end

local function finish(ok, reason)
    if finished then return end
    finished = true
    snap(ok and "final_pass" or "final_fail")
    log("RESULT %s reason=%s vx=%d side=%s cam_y_max=%d cam_target=%s land=%s,%s scr=%s floor=%s "
        .. "sky=%s/%s sky_drift=%s fdeath=%d xturns=%d",
        ok and "PASS" or "FAIL", reason, VICTIM_X, SIDE, cam_y_max, tostring(EQ.mk1p_fall_cam),
        tostring(land_x), tostring(land_y), tostring(land_scr), tostring(EQ.mk1p_floor_y),
        tostring(sky_count), tostring(EQ.mk1p_sky_objs), tostring(sky_moved), s16(r16(A.f_death)),
        xv_turns)
    log("%s", state_line("end"))
    if logfh then logfh:flush() end
    manager.machine:exit()
end

local function force_select()
    w16(A.p1_char, FT_KANG)
    w16(A.p2_char, FT_JAX)
    w16(A.curback, STAGE)
    w16(A.p1_state, PS_ACTIVE)
    w16(A.p2_state, PS_ACTIVE)
end

local function fighters_ok()
    local a, v = attacker(), victim()
    return a ~= 0 and v ~= 0 and r16(a + O.ochar) == FT_KANG and r16(v + O.ochar) == FT_JAX
end

local function force_finish_him()
    if fall_start_frame ~= 0 or not fighters_ok() then return end
    local rel = frame - fighting_frame
    if rel < 400 or rel > 2400 then return end
    w16(A.winner_status, 3)
    w16(A.f_death, 0)
    local p1p = r32(A.p1_proc)
    if p1p ~= 0 then w16(p1p + P.flags, r16(p1p + P.flags) & ~(PM_REACTING | PM_SITDUCK | PM_SPECIAL)) end
    local p2p = r32(A.p2_proc)
    if p2p ~= 0 and not victim_dizzy_forced then
        w32(p2p + P.wake, A.dizzy_dude)
        victim_dizzy_forced = true
    end
    if finish_forced_frame == 0 then
        finish_forced_frame = frame
        log("finish_him frame=%d | %s", frame, state_line("ff"))
    end
end

local function victim_ready()
    local p = r32(A.p2_proc)
    if p == 0 then return false end
    local wake = r32(p + P.wake)
    return wake >= A.dizzy and wake < (A.dizzy + 0x120) and r16(p + P.action) == ACT_STUNNED
end

local function pin()
    local a, v = attacker(), victim()
    if a == 0 or v == 0 then return end
    local ax = SIDE == "left" and (VICTIM_X - GAP) or (VICTIM_X + GAP)
    w16(v + O.oxpos, VICTIM_X); w32(v + O.oxval, (VICTIM_X << 16) & 0xffffffff)
    w16(a + O.oxpos, ax);       w32(a + O.oxval, (ax << 16) & 0xffffffff)
end

local ATTEMPT_LEN = 80
local BACK = SIDE == "left" and "P1 Left" or "P1 Right"
local FWD = SIDE == "left" and "P1 Right" or "P1 Left"
local function press_for(name, rel)
    if MOVE == "uppercut" then
        if name == "P1 Down" then return rel >= 0 and rel < 24 end
        if name == "P1 High Punch" then return rel >= 8 and rel < 12 end
        return false
    end
    if name == BACK then return rel >= 0 and rel < 5 end
    if name == FWD then return (rel >= 9 and rel < 14) or (rel >= 18 and rel < 23) end
    if name == "P1 Low Kick" then return rel >= 26 and rel < 32 end
    return false
end

local function pressed(name)
    if charsel_frame == 0 then
        if name == "Coin 1" or name == "Coin 2" then
            return frame >= 220 and frame < 6000 and (frame % 80) < 20
        end
        if name == "2 Players Start" then
            return frame >= 260 and frame < 6000 and (frame % 80) >= 30 and (frame % 80) < 55
        end
    end
    if charsel_frame > 0 and fighting_frame == 0 and p1_confirm_start > 0 then
        if name == "P1 High Punch" then return frame >= p1_confirm_start and frame < p1_confirm_start + 40 end
        if name == "P2 High Punch" then return frame >= p1_confirm_start + 80 and frame < p1_confirm_start + 120 end
    end
    if attempt_start > 0 and fall_start_frame == 0 and fighting_frame > 0 then
        return press_for(name, (frame - attempt_start) % ATTEMPT_LEN)
    end
    return false
end

emu.register_frame(function()
    frame = frame + 1
    if frame == 1 then
        space = manager.machine.devices[":maincpu"].spaces["program"]
        local wanted = { "Coin 1", "Coin 2", "2 Players Start", "P1 High Punch", "P2 High Punch",
                         "P1 Low Kick", "P1 Left", "P1 Right", "P1 Down" }
        for _, port in pairs(manager.machine.ioport.ports) do
            for _, f in pairs(port.fields) do fields[f.name] = fields[f.name] or f end
        end
        for _, n in ipairs(wanted) do if not fields[n] then finish(false, "input_missing_" .. n); return end end
        local keep = {}
        for _, n in ipairs(wanted) do keep[n] = fields[n] end
        fields = keep
        log("trial move=%s vx=%d side=%s gap=%d floor=%s cam=%s sky_objs=%s", MOVE, VICTIM_X, SIDE, GAP,
            tostring(EQ.mk1p_floor_y), tostring(EQ.mk1p_fall_cam), tostring(EQ.mk1p_sky_objs))
    end
    if not space then return end

    local gs = r16(A.gstate)
    if gs ~= last_gstate then
        if gs == GS_PSEL and charsel_frame == 0 then charsel_frame = frame end
        if gs == GS_FIGHTING and last_gstate ~= GS_FIGHTING and fighting_frame == 0 then
            fighting_frame = frame
            log("fight_start frame=%d | %s", frame, state_line("fs"))
        end
        log("gstate frame=%d %d->%d", frame, last_gstate, gs)
        last_gstate = gs
    end

    if fighting_frame == 0 then force_select() end
    if charsel_frame > 0 and fighting_frame == 0 and p1_confirm_start == 0 and frame > charsel_frame + 90 then
        p1_confirm_start = frame + 25
    end

    if fighting_frame > 0 and fall_start_frame == 0 then
        if r16(A.curback) ~= STAGE then finish(false, "wrong_stage"); return end
        local rel = frame - fighting_frame
        -- the stage as it plays: the sky, and whether it drifts
        if rel == 60 then
            local objs = sky_objects()
            sky_count = #objs
            for i, o in ipairs(objs) do sky_first_x[i] = s16(r16(o + O.oxpos)) end
            log("SKY at rel 60: %d objects | %s", sky_count, state_line("sky"))
            snap("stage_start")
        end
        if rel == 360 then
            local moved = 0
            for i, o in ipairs(sky_objects()) do
                if sky_first_x[i] and s16(r16(o + O.oxpos)) ~= sky_first_x[i] then moved = moved + 1 end
            end
            sky_moved = moved
            log("SKY at rel 360: %d of them moved (clouds + the silhouette)", moved)
            snap("stage_later")
        end
        force_finish_him()
        if finish_forced_frame > 0 then pin() end
        if attempt_start == 0 and finish_forced_frame > 0 and victim_ready()
            and frame >= finish_forced_frame + CAMERA_SETTLE then
            attempt_start = frame + 10
            log("victim_ready frame=%d | %s", frame, state_line("vr"))
            snap("before_fatality")
        end
        if attempt_start > 0 and frame >= attempt_start and (frame - attempt_start) % ATTEMPT_LEN == 0 then
            attempt_n = attempt_n + 1
            log("attempt=%d frame=%d | %s", attempt_n, frame, state_line("try"))
            if attempt_n > 8 then finish(false, "fatality_never_fired"); return end
        end
        if p2_action() == ACT_FALL then
            fall_start_frame = frame
            log("MK1PIT_FALL frame=%d | %s", frame, state_line("fall"))
            snap("fall_start")
        end
    end

    if fall_start_frame > 0 then
        local rel = frame - fall_start_frame
        local wtly = s16(r16(A.worldtly + 16))
        if wtly > cam_y_max then cam_y_max = wtly end
        local v = victim()
        if v ~= 0 and land_frame == 0 and rel > 20 then
            local vy = s16(r16(v + O.oypos))
            if s32(r32(v + O.oyvel)) == 0 and vy > (EQ.mk1p_ground or 264) + 200 then
                land_frame = frame
                land_x = s16(r16(v + O.oxpos))
                land_y = vy
                land_scr = land_x - s16(r16(A.worldtlx + 16))
                log("LANDED frame=%d rel=%d | %s", frame, rel, state_line("land"))
                snap("landed")
            end
        end
        if v ~= 0 and land_frame == 0 then
            local xv = s32(r32(v + O.oxvel))
            local sgn = (xv > 0 and 1) or (xv < 0 and -1) or 0
            if sgn ~= 0 then
                if xv_sign ~= 0 and sgn ~= xv_sign then xv_turns = xv_turns + 1 end
                xv_sign = sgn
            end
        end
        if FALLTRACE and v ~= 0 and rel <= 160 then
            log("FTRACE rel=%03d scrx=%d oxpos=%d oxvel=%.3f oypos=%d oyvel=%.3f",
                rel, s16(r16(v + O.oxpos)) - s16(r16(A.worldtlx + 16)),
                s16(r16(v + O.oxpos)), s32(r32(v + O.oxvel)) / 65536.0,
                s16(r16(v + O.oypos)), s32(r32(v + O.oyvel)) / 65536.0)
        end
        if rel % 10 == 0 then
            log("obs rel=%03d | %s", rel, state_line("obs"))
            if rel % 20 == 0 then snap(string.format("obs_%03d", rel)) end
        end
        -- MP_BLOODDUMP=1: walk objlst and print every object's drawn band, so
        -- the pit fountain can be measured instead of eyeballed off a PNG.
        -- Geometry is read out of the object and its own image header, so it
        -- needs no table of record names: anipoint = oypos + ianioffy, and a
        -- single-part object draws from oypos down osizey rows.
        if BLOODDUMP and land_frame > 0 and frame >= land_frame then
            local t = frame - land_frame
            if t % 5 == 0 and t <= 140 then
                local cam = s16(r16(A.worldtly + 16))
                local o = r32(A.objlst)
                local n, parts = 0, {}
                while o ~= 0 and o ~= 0xffffffff and n < 96 do
                    local img = r32(o + 0x1a0)
                    if img ~= 0 and img >= 0xff800000 then
                        local h = s16(r16(img + 0x10))
                        local aniy = s16(r16(img + 0x30))
                        local y = s16(r16(o + 0x0b0))
                        local z = s16(r16(o + 0x0d0))
                        local yv = s32(r32(o + 0x060))
                        parts[#parts + 1] = string.format(
                            "y=%d(scr %d) ani=%d h=%d z=%d yv=%d",
                            y, y - cam, y + aniy, h, z, yv // 65536)
                    end
                    o = r32(o + 0x000)
                    n = n + 1
                end
                log("BLOOD t=%+04d cam=%d objs=%d | %s", t, cam, #parts,
                    table.concat(parts, " ; "))
            end
        end
        if rel >= OBSERVE_FRAMES then
            local bad = {}
            if EQ.mk1p_fall_cam and cam_y_max ~= EQ.mk1p_fall_cam then
                bad[#bad + 1] = string.format("camera_%d_not_%d", cam_y_max, EQ.mk1p_fall_cam)
            end
            if land_frame == 0 then bad[#bad + 1] = "never_landed" end
            if xv_turns > 1 then
                bad[#bad + 1] = string.format("fall_reversed_%dx", xv_turns)
            end
            if land_scr and (land_scr < 60 or land_scr > 340) then   -- lying flat he is ~80px each side
                bad[#bad + 1] = string.format("landed_off_screen_%d", land_scr)
            end
            if s16(r16(A.f_death)) ~= -1 then bad[#bad + 1] = "f_death_not_minus1" end
            if EQ.mk1p_sky_objs and sky_count and sky_count < EQ.mk1p_sky_objs then
                bad[#bad + 1] = string.format("sky_%d_of_%d", sky_count, EQ.mk1p_sky_objs)
            end
            if sky_moved == 0 then bad[#bad + 1] = "sky_never_drifted" end
            if #bad == 0 then finish(true, "down_the_pit") else finish(false, table.concat(bad, "+")) end
            return
        end
    end

    if frame - last_status >= 180 then
        last_status = frame
        log("status | %s", state_line("status"))
    end

    for name, field in pairs(fields) do field:set_value(pressed(name) and 1 or 0) end

    if fighting_frame == 0 and frame > 9000 then finish(false, "never_reached_fight")
    elseif frame > 20000 then finish(false, "global_timeout") end
end)

emu.register_stop(function()
    if logfh then logfh:flush(); logfh:close(); logfh = nil end
end)
