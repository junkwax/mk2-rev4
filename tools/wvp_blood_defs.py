"""Turn World View blood rows into a sahb_defs table and its ani_calla hooks.

THE POINT: a blood row is a TAG, not an animation.  The animation and its rate
already live in the ROM - the frames in MKBLOOD.ASM, the sleep in sahb_defs -
so only three fields of a blood row ever reach the game:

    sequence_frames[0]  WHICH blood      -> the a_* lane label
    local_dx/dy[0]      WHERE            -> the packed [dy:dx] offset
    visible_from[0]     WHEN             -> the master tick it fires on

Everything else a blood row carries - the rest of its frames, every per-frame
hold, the Show@/Hide@ run after the first - is preview scaffolding.  It is not
merely unused: it is a second copy of timing the ROM already owns, free to
drift.  imgtool imports blood at 1 tick/frame on purpose
(kWorldBloodTicksPerFrame) so a spray can be walked onto the exact tick of the
hit, which is why those rows all read 1 and why that is nothing to fix.

WHAT THIS EXISTS TO STOP: the hooks are placed by ENTRY INDEX, not by tick, and
those only coincide when every entry holds one tick.  BARAKADOWNSMALL holds 3
and 4, so ticks 6/7/10/14 are entries 2/2/3/4 - putting the hooks on entries
6/7/10/14 would fire the blood at ticks 18/21/30/42, long after the impact.
Two beats landing in one entry get merged, because ani_calla is one per entry.

    python tools/wvp_blood_defs.py data/sliceblood.WAX \
           --attacker data/BARAKADOWNSMALL.WAX --attacker-slot 0
"""
import argparse, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# First frame of a blood run -> the lane already in MKBLOOD.ASM, and the `seed'
# column (0 = get_tg_blood, 1 = get_jt_blood) each one is wired with.
BLOOD = {
    "MK1SPLAT1":   ("a_sahb_splat",  1),
    "BIGBLD1":     ("a_sahb_bigbld", 1),
    "BIGGERBLUD1": ("a_bigger",      1),
    "GUTS1":       ("a_guts",        1),
    "STAB1":       ("a_sahb_stab",   0),
    "SMGUSH1":     ("a_sahb_smgush", 1),
    "SPRAY1":      ("a_decap_spray", 1),
    "SPLAT1":      ("a_face_blood",  1),
    "UPSPLAT1":    ("a_upsplat",     1),   # lane added 2026-08-24; art was
                                           # already in MKBLOOD.TBL, unused
    "LILBLD1":     ("a_lilbld",      1),   # lane AND art added 2026-08-24
}


def kv(path):
    out = {}
    for line in open(path, encoding="utf-8", errors="surrogateescape"):
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def ints(d, key):
    raw = d.get(key, "")
    return [int(x) for x in raw.split(",") if x.strip().lstrip("-").isdigit()]


def dump_rows(wax, slot):
    """(index, record, hold, mirror) per entry, via the shared dumper."""
    out = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "wvp_dump.py"),
                          wax, str(slot)], capture_output=True, text=True).stdout
    rows = []
    for l in out.split("\n"):
        m = re.match(r"^\s*(\d+)\s+\d+\s+\d+\s+(\S+)\s+\S+\s+(\d+)\s+", l)
        if m:
            rows.append((int(m.group(1)), m.group(2), int(m.group(3))))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("wax", help="project holding the blood rows")
    ap.add_argument("--attacker", help="project holding the lane the hooks go in")
    ap.add_argument("--attacker-slot", type=int, default=0)
    ap.add_argument("--sleep", type=int, default=4,
                    help="ticks per frame for every record (default 4 = 13.7fps, "
                         "the rate the shipped game runs blood at). This is the "
                         "ROM's number, NOT the project's - see the header.")
    a = ap.parse_args()

    d = kv(a.wax)
    found = []
    for slot in range(int(d.get("state.slot_count", "16") or 16)):
        p = "slot.%d." % slot
        seq = ints(d, p + "sequence_frames")
        if not seq:
            continue
        rows = dump_rows(a.wax, slot)
        if not rows:
            continue
        first = rows[0][1]
        if first not in BLOOD:
            continue
        lane, seed = BLOOD[first]
        dx = (ints(d, p + "local_dx") or [0])[0]
        dy = (ints(d, p + "local_dy") or [0])[0]
        tick = (ints(d, p + "visible_from") or [0])[0]
        found.append((slot, first, lane, seed, dx, dy, tick, len(rows)))

    if not found:
        print("; no blood rows found - a row is recognised by its FIRST record")
        print("; being one of: " + ", ".join(sorted(BLOOD)))
        return

    found.sort(key=lambda r: (r[6], r[0]))          # by spawn tick

    print("* GENERATED by tools/wvp_blood_defs.py from %s" % os.path.basename(a.wax))
    print("* One record per blood row: animation, packed [dy:dx], sleep, seed.")
    print("* The sleep is the ROM's (%d = %.1ffps), not the project's - blood rows"
          % (a.sleep, 54.7068 / a.sleep))
    print("* import at 1 tick/frame so they can be placed on the exact tick.")
    print("sahb_defs")
    for i, (slot, rec, lane, seed, dx, dy, tick, n) in enumerate(found):
        packed = ((dy & 0xFFFF) << 16) | (dx & 0xFFFF)
        print("\t.long\t%s,%09xh,%d,%d\t; %d - tick %-3d (%d,%d)  [row %d, %s x%d]"
              % (lane, packed, a.sleep, seed, i, tick, dx, dy, slot, rec, n))

    if not a.attacker:
        print("\n; pass --attacker to map these ticks onto ani_calla entries")
        return

    rows = dump_rows(a.attacker, a.attacker_slot)
    starts, t = [], 0
    for _, _, hold in rows:
        starts.append(t)
        t += hold
    print("\n; tick -> entry, for the --call-entry hooks (%d ticks over %d entries)"
          % (t, len(rows)))
    by_entry = {}
    for i, (slot, rec, lane, seed, dx, dy, tick, n) in enumerate(found):
        ent = 0
        for e in range(len(rows)):
            if starts[e] <= tick < starts[e] + rows[e][2]:
                ent = e
                break
        else:
            ent = len(rows) - 1
            print(";   WARNING slot %d fires at tick %d, past the lane's %d"
                  % (slot, tick, t))
        by_entry.setdefault(ent, []).append((i, tick, lane))
    for ent in sorted(by_entry):
        hits = by_entry[ent]
        note = "" if len(hits) == 1 else \
               "   <-- %d beats share this entry; they need ONE hook" % len(hits)
        print(";   entry %-3d <- %s%s"
              % (ent, ", ".join("slot %d (tick %d)" % (h[0], h[1]) for h in hits), note))
    print(";\n; " + " ".join("--call-entry %d=<hook>" % e for e in sorted(by_entry)))


if __name__ == "__main__":
    main()
