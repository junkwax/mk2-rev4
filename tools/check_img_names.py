#!/usr/bin/env python3
"""Duplicate record / palette NAMES inside the IMG libraries the build reads.

LOAD2 resolves a LOD's `---> NAME` list against the record NAMES in the
current library and takes the LAST match.  So a second record with the same
name silently repacks the first, and nothing downstream notices:

  * the promoted TBL gets the NEW record's SAG and control word, because
    `promote_tbls.py` patches both...
  * ...but KEEPS the existing `.long <palette>` line, so `src/*.TBL` can end
    up naming one palette while the packed pixels are indices into another.
  * `PPP> 0` picks the depth off the pixels actually used, so the control word
    can come out identical and hide the swap.
  * if every index still lands inside the wrongly-named palette, nothing draws
    out of bounds either.

The result is a complete, plausible-looking sprite in the WRONG COLOURS, with
a green build.  That has happened five times in `data/MKBOXES.IMG` alone:
SZBOX (2026-09-22), SCBOX twice, a 55x70 `smerbox` winning the ladder mug
lookup, and the palette-level twin of the same bug (`BOX16_P` meaning one
thing in the IMG and another in `src/IMGPAL6.ASM`).  The last one was found by
a player noticing Scorpion's select photo, not by the build.

This does not judge whether a duplicate is wrong - the tree carries plenty of
them in Midway's own art (FBFONT7's two alphabets, MKSCORE's two VERSUS).  It
BASELINES what is there into doc/img_names.lock and fails on drift, so a new
duplicate has to be looked at and accepted on purpose.

    python tools/check_img_names.py               # report every finding
    python tools/check_img_names.py --check       # nonzero on drift (Phase A0b)
    python tools/check_img_names.py --write       # re-baseline the lock
    python tools/check_img_names.py --img MKBOXES # one library
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import img_subframe_audit as audit  # noqa: E402  (the IMG/LOD parsers live there)

DATA = ROOT / "data"
LOCK = ROOT / "doc" / "img_names.lock"
PALETTE = struct.Struct("<10s BB H I H H B B H")

HEADER = """\
# img_names.lock - generated by tools/check_img_names.py --write
#
# Duplicate record / palette NAMES inside the IMG libraries a live LOD reads.
# LOAD2 resolves a LOD's name list by NAME and takes the LAST match, so a
# duplicate silently repacks the first record - a correct-looking sprite in
# the wrong colours, with a clean build.  See the tool's docstring.
#
# Everything listed here is ACCEPTED - mostly Midway's own art.  A line that
# is not here fails the build.  If a new duplicate is deliberate, re-run with
# --write and say in the commit why the collision is safe.
#
# DUP-RECORD   one library, one name, several records.  REQUESTED means a live
#              LOD asks for that name, so one of them IS being packed and the
#              choice is silent.  DIFFERS/IDENTICAL compares the stored
#              pixels; SIZE-ONLY/SIZE-SAME is all that can be said for the
#              version-0 libraries, whose records carry no pixel offset.
# DUP-PALETTE  one library, one palette name, several palettes.  A promoted
#              TBL can only name it once, so one set of colours wins.
# NAME-CLASH   a record and a palette in one library share a name.  The
#              promoted TBL would define that label twice.
"""


def read_library(path: Path):
    """-> (records, palettes, data, stride) or None.

    Records are dicts with name/w/h/pal/off; palettes are names in file order.
    Table placement is detected the way img_subframe_audit does it, because
    the record stride is not constant across this tree.
    """
    data = path.read_bytes()
    if len(data) < audit.LIB_HDR.size:
        return None
    imgcnt, palcnt, oset = audit.LIB_HDR.unpack_from(data, 0)[:3]
    if imgcnt == 0:
        return None

    best = (-1, None, None)
    for start in (oset, oset + palcnt * PALETTE.size):
        for stride in audit.STRIDES:
            score = audit._score(data, start, stride, imgcnt)
            if score > best[0]:
                best = (score, start, stride)
    score, img_start, stride = best
    if score <= 0:
        return None

    # Image-first libraries put the palette table after the image table;
    # palette-first ones put the image table after the palettes.
    pal_start = img_start + imgcnt * stride if img_start == oset else oset

    records = []
    for i in range(imgcnt):
        off = img_start + i * stride
        if off + stride > len(data):
            break
        w, h = struct.unpack_from("<HH", data, off + 22)
        # palnum and the pixel offset only exist in the 50-byte v6 record
        pal = struct.unpack_from("<H", data, off + 26)[0] if stride >= 50 else -1
        pix = struct.unpack_from("<I", data, off + 28)[0] if stride >= 50 else None
        records.append({"idx": i, "name": audit.cstr(data[off:off + 16]),
                        "w": w, "h": h, "pal": pal, "off": pix})

    palettes = []
    for i in range(palcnt):
        off = pal_start + i * PALETTE.size
        if off + PALETTE.size > len(data):
            break  # palcnt routinely overruns the real record count
        palettes.append(audit.cstr(data[off:off + 10]))

    return records, palettes, data, stride


def stored_pixels(data: bytes, rec: dict):
    """The record's stored pixel rows, or None if they cannot be read."""
    if rec["off"] is None or rec["w"] == 0 or rec["h"] == 0:
        return None
    stride = (rec["w"] + 1) // 2 * 2
    if rec["off"] + stride * rec["h"] > len(data):
        return None
    return b"".join(data[rec["off"] + y * stride:rec["off"] + y * stride + rec["w"]]
                    for y in range(rec["h"]))


def group(names):
    """name (upper) -> [index, ...], skipping blanks."""
    out = {}
    for i, nm in enumerate(names):
        if nm:
            out.setdefault(nm.upper(), []).append(i)
    return out


def findings(only_img=None):
    """Every collision, as sorted report lines."""
    lods = audit.live_lods()
    used, origin, _ = audit.collect(lods)
    lines = []

    for img in sorted(used):
        if only_img and img != only_img.upper():
            continue
        path = DATA / (img + ".IMG")
        if not path.exists():
            alt = DATA / (img + ".img")
            if not alt.exists():
                continue  # a missing library is img_subframe_audit's finding
            path = alt

        lib = read_library(path)
        if lib is None:
            continue
        records, palettes, data, _ = lib
        requested = {n.upper() for n in used[img]}
        rec_names = group([r["name"] for r in records])
        pal_names = group(palettes)

        for name, idxs in sorted(rec_names.items()):
            if len(idxs) < 2:
                continue
            rs = [records[i] for i in idxs]
            sigs = []
            for r in rs:
                px = stored_pixels(data, r)
                sigs.append((r["w"], r["h"], r["pal"],
                             None if px is None else hash(px)))
            if any(s[3] is None for s in sigs):
                kind = "SIZE-ONLY" if len({s[:2] for s in sigs}) > 1 else "SIZE-SAME"
            else:
                kind = "IDENTICAL" if len(set(sigs)) == 1 else "DIFFERS"
            # Differing spellings would only collide if LOAD2 folds case -
            # flag them rather than assume either way.
            note = "  CASE" if len({records[i]["name"] for i in idxs}) > 1 else ""
            who = ("REQUESTED by " + ",".join(sorted(origin[img]))
                   if name in requested else "unused")
            lines.append("DUP-RECORD   %-14s %-20s x%d %-10s %s%s"
                         % (img, name, len(idxs), kind, who, note))

        for name, idxs in sorted(pal_names.items()):
            if len(idxs) >= 2:
                lines.append("DUP-PALETTE  %-14s %-20s x%d"
                             % (img, name, len(idxs)))

        for name in sorted(rec_names):
            if name in pal_names:
                lines.append("NAME-CLASH   %-14s %-20s %s"
                             % (img, name,
                                "REQUESTED" if name in requested else "unused"))

    return sorted(lines)


def read_lock():
    if not LOCK.exists():
        return None
    return sorted(line.rstrip() for line in LOCK.read_text().splitlines()
                  if line.strip() and not line.lstrip().startswith("#"))


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="nonzero if the findings drift from doc/img_names.lock")
    ap.add_argument("--write", action="store_true", help="re-baseline the lock")
    ap.add_argument("--img", help="restrict to one library (stem, no .IMG)")
    a = ap.parse_args()

    lines = findings(a.img)

    if a.write:
        if a.img:
            print("--write re-baselines the whole tree; drop --img")
            return 2
        LOCK.parent.mkdir(parents=True, exist_ok=True)
        LOCK.write_text(HEADER + "\n" + "\n".join(lines) + "\n")
        print("wrote %s (%d finding(s))"
              % (LOCK.relative_to(ROOT).as_posix(), len(lines)))
        return 0

    if not a.check:
        for line in lines:
            print(line)
        print("\n%d finding(s) across the live IMG libraries." % len(lines))
        locked = read_lock()
        if locked is not None:
            print("doc/img_names.lock carries %d." % len(locked))
        return 0

    locked = read_lock()
    if locked is None:
        print("Error: doc/img_names.lock is missing - run "
              "'python tools/check_img_names.py --write'")
        return 1

    new = [line for line in lines if line not in locked]
    gone = [line for line in locked if line not in lines]
    if not new and not gone:
        return 0

    if new:
        print("NEW name collision(s) in the IMG libraries the build reads.")
        print("A duplicate record name means LOAD2 packs the LAST one - the")
        print("sprite can come out in another palette's colours with no other")
        print("sign.  Rename the duplicate in the IMG, or accept it on purpose")
        print("with 'python tools/check_img_names.py --write'.")
        print()
        for line in new:
            print("  + " + line)
    if gone:
        if new:
            print()
        print("Collision(s) in the lock that are GONE (fixed, or the library")
        print("stopped being read).  Re-baseline with --write:")
        print()
        for line in gone:
            print("  - " + line)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
