#!/usr/bin/env python3
"""Generate src/SKSOULP.ASM - the GREEN palettes Shao Kahn's soul rip draws
the escaping soul in, one per fighter family.

The soul is not new art.  It is the victim's own `SUCK_*` strips - the lane
Mileena's inhale fatality already draws (a_??_sucked_in, MKDIE.ASM) - drawn
in a green ramp instead of his colours, which is exactly what the user
authored in data/MKSUCK.IMG: CAGE1-7 re-pointed at a new palette record,
CAGE1_P, that is CAGE_P turned green.

CAGE1_P IS COPIED VERBATIM for Johnny Cage: it is the authored article and
the thing every other family is matched against.  The other eight are
generated from their own family's suck palette by the recipe fitted to it:

    Y = 8-bit luma of the source colour  (0.299 R + 0.587 G + 0.114 B)
    G = round(Y * 27 / 255)   R = 0   B = G // 4

which reproduces CAGE1_P's green in 55 of its 64 entries exactly and is
never more than one index off in the rest, all of them near black.

Nothing promotes an IMG palette into the ROM (see the IMGPAL note in
doc/), so this file is the promoter for these nine: rerun it after any
repaint of MKSUCK.IMG's palettes.

    python tools/make_soulrip_pals.py            # write src/SKSOULP.ASM
    python tools/make_soulrip_pals.py --check    # exit 1 if it is stale
"""
import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMG = ROOT / "data" / "MKSUCK.IMG"
OUT = ROOT / "src" / "SKSOULP.ASM"

LIB = struct.Struct("<HHIHHHHH 4s HHH")               # 28
IMAGE = struct.Struct("<16s HHH HH H II H HHH HHH")   # 50
PALETTE = struct.Struct("<10s BB H I H H B B H")      # 26

# family -> (ASM symbol, palnum in MKSUCK.IMG that its SUCK_* strips use,
#            the record's name, what it is)
FAMILIES = [
    ("TM", 28, "TMBLUE_P",  "kung lao"),
    ("LK", 31, "LKBLUE_P",  "liu kang"),
    ("JC", 24, "CAGE_P",    "johnny cage"),
    ("UG", 17, "UGBLUE_P",  "baraka"),
    ("KT", 22, "KATBLU_P",  "kitana / mileena / jade / khameleon"),
    ("ST",  9, "TYELO_P",   "shang tsung"),
    ("RN", 11, "RADBLU_P",  "raiden"),
    ("NJ", 15, "SUB_P",     "the ninjas - sub-zero, reptile, scorpion, smoke, noob, ermac, rain"),
    ("JX",  7, "JAXBLU_P",  "jax"),
]

# Cage's is authored, not generated: MKSUCK.IMG palnum 33.
AUTHORED = {"JC": 33}

# ochar -> family.  20 rows, 0-19, the length every char-indexed table in the
# build is held to (tools/audit_char_tables.py).  12/13 are the bosses: they
# are never the victim, and the row is filler so an over-read cannot happen.
OCHARS = ["TM", "LK", "JC", "UG", "KT", "KT", "ST", "RN", "NJ", "NJ", "NJ",
          "JX", "TM", "TM", "NJ", "NJ", "KT", "NJ", "KT", "NJ"]
OCHAR_NAMES = ["kung lao", "liu kang", "johnny cage", "baraka", "kitana",
               "mileena", "shang tsung", "raiden", "sub-zero", "reptile",
               "scorpion", "jax", "kintaro (filler)", "shao kahn (filler)",
               "smoke", "noob", "jade", "ermac", "khameleon", "rain"]


def palettes(path: Path):
    data = path.read_bytes()
    imgcnt, palcnt, oset = LIB.unpack_from(data, 0)[:3]
    p0 = oset + imgcnt * IMAGE.size
    out = {}
    for i in range(palcnt - 3):
        name, _pad, _bpp, cnt, fo, *_ = PALETTE.unpack_from(data, p0 + i * PALETTE.size)
        out[i + 3] = (name.split(b"\0", 1)[0].decode("latin-1"),
                      [struct.unpack_from("<H", data, fo + 2 * k)[0] for k in range(cnt)])
    return out


def greenify(word):
    r, g, b = (word >> 10) & 31, (word >> 5) & 31, word & 31
    y = 0.299 * (r * 255 / 31) + 0.587 * (g * 255 / 31) + 0.114 * (b * 255 / 31)
    gg = min(31, int(round(y * 27 / 255)))
    return (gg << 5) | (gg // 4)


def as_asm(sym, words):
    lines = [sym, "\t.word\t%d" % len(words)]
    for i in range(0, len(words), 8):
        lines.append("\t.word\t" + ",".join("0%04XH" % w if w >= 0x0A00 else "0%XH" % w
                                            for w in words[i:i + 8]))
    return "\n".join(lines)


def build():
    pals = palettes(IMG)
    out = ["""**************************************************************************
*                                                                        *
*  sksoulp.asm - the GREEN palettes Shao Kahn's soul rip draws the        *
*                escaping soul in (MKSOULRP.ASM).                         *
*                                                                        *
*  GENERATED by tools/make_soulrip_pals.py - do not hand-edit.  The soul  *
*  is the victim's own SUCK_* strips (a_??_sucked_in, MKDIE.ASM) drawn    *
*  in a green ramp, so there is one palette per art family and nothing    *
*  new in the video ROM.                                                  *
*                                                                        *
*  SOULGRN_JC is data/MKSUCK.IMG's CAGE1_P verbatim - the authored one.   *
*  The other eight are that recipe applied to their own family palette.   *
*                                                                        *
**************************************************************************
\t.file\t"sksoulp.asm"
\t.width\t132
\t.option\tb,d,l,t
\t.mnolist

\t.include\tmainequ.asm

\t.data
"""]
    for fam, palnum, recname, who in FAMILIES:
        if fam in AUTHORED:
            src = pals[AUTHORED[fam]]
            words = src[1]
            note = "%s - %s, AUTHORED (MKSUCK.IMG %s)" % (fam, who, src[0])
        else:
            name, words = pals[palnum]
            if name != recname:
                raise SystemExit("MKSUCK.IMG palnum %d is %s, expected %s"
                                 % (palnum, name, recname))
            words = [greenify(w) for w in words]
            note = "%s - %s, from %s" % (fam, who, recname)
        out.append(";\n; " + note + "\n;")
        out.append(as_asm("SOULGRN_" + fam, words))
        out.append("")

    out.append(""";
; ksr_soul_pals - ochar -> the green palette his soul wears.  20 rows.
;""")
    out.append("\t.globl\tksr_soul_pals")
    out.append("ksr_soul_pals")
    for i, fam in enumerate(OCHARS):
        out.append("\t.long\tSOULGRN_%s\t; %2d - %s" % (fam, i, OCHAR_NAMES[i]))
    # the Wolf-only fighters' rows (tools/wolf_fighter_rows.py owns the form)
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import wolf_fighter_rows
    out += wolf_fighter_rows.block("ksr_soul_pals", "long",
                                   [["SOULGRN_" + fam] for fam in OCHARS]) or []
    out.append("")
    out.append("\t.end")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        have = OUT.read_text() if OUT.exists() else ""
        if have.replace("\r\n", "\n") != text:
            print("STALE %s - rerun tools/make_soulrip_pals.py" % OUT.name)
            return 1
        print("ok %s" % OUT.name)
        return 0
    OUT.write_text(text, newline="\n")
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
