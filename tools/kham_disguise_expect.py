#!/usr/bin/env python3
r"""Write tools/kham_disguise_expect.lua - what KHAMELEON's colour map should
hold at each step of her disguise cycle.

Regenerated on EVERY run of tools/run_kham_disguise_test.ps1, so the rig can
never pass against a number that was true last week.  The words come from
`data/MK2PALS.IMG`, read with the reader of the tool that OWNS these four
palettes - tools/sync_alt_costume_palettes.py, whose Phase D --check is what
proves src/IMGPAL6.ASM still equals the IMG.  Reading the IMG here and the
colour RAM in the rig therefore tests the whole chain: repaint -> carried into
the ASM -> linked -> loaded into a live colour map.

WHY INDEX 40 AND INDEX 5.  All four palettes agree on indices 0-30 and 59-63 -
skin, hair, eyes, the gore markers - and differ only across the costume ramp at
31-55.  Index 5 is therefore the sentinel: it says "this map is one of hers" and
cannot tell them apart.  Index 40 is inside the ramp and is DISTINCT in all
four, which is what lets one word name which disguise is loaded.  Both facts are
asserted here rather than assumed, so a repaint that flattens the ramp fails the
generator instead of producing a rig that cannot discriminate.

    python tools/kham_disguise_expect.py           # write the .lua
    python tools/kham_disguise_expect.py --print   # ... and show it
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sync_alt_costume_palettes import img_palettes                  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tools" / "kham_disguise_expect.lua"

LIB = "MK2PALS.IMG"
ANCHOR = "KHMAIN_P"
# The cycle, in the order kham_disguise_pals (MKGUYS.ASM) lists them.
CYCLE = [("KHALTJ_P", "JADE"), ("KHALTK_P", "KITANA"), ("KHALTM_P", "MILEENA")]

SENTINEL = 5        # identical in all four - "is this even her map"
WITNESS = 40        # distinct in all four - which disguise is loaded


def rgb(w: int) -> str:
    return "%02X%02X%02X" % (((w >> 10) & 31) * 255 // 31,
                             ((w >> 5) & 31) * 255 // 31,
                             (w & 31) * 255 // 31)


def collect() -> dict:
    found, _seen = img_palettes(LIB)
    names = [ANCHOR] + [n for n, _ in CYCLE]
    pals = {}
    for n in names:
        if n not in found:
            raise SystemExit("%s: no palette record named %s" % (LIB, n))
        w = found[n]
        if len(w) != 64:
            raise SystemExit("%s: %s has %d entries, expected 64" % (LIB, n, len(w)))
        pals[n] = w

    # The two assumptions the rig rests on, checked instead of assumed.
    sent = {pals[n][SENTINEL] for n in names}
    if len(sent) != 1:
        raise SystemExit("index %d is not identical across all four palettes "
                         "(%s) - the rig has no sentinel" % (SENTINEL,
                         ", ".join("%s=%04X" % (n, pals[n][SENTINEL]) for n in names)))
    wit = [pals[n][WITNESS] for n in names]
    if len(set(wit)) != len(wit):
        raise SystemExit("index %d is not distinct across all four palettes "
                         "(%s) - the rig cannot tell the disguises apart"
                         % (WITNESS, ", ".join("%s=%04X" % (n, pals[n][WITNESS])
                                               for n in names)))
    return pals


def as_lua(pals: dict) -> str:
    out = [
        "-- GENERATED by tools/kham_disguise_expect.py - do not edit.",
        "-- KHAMELEON's disguise cycle, read out of data/%s." % LIB,
        "-- SENTINEL = a colour identical in all four (is this her map at all).",
        "-- WITNESS   = a colour distinct in all four (which disguise is loaded).",
        "return {",
        "    SENTINEL_IDX = %d," % SENTINEL,
        "    SENTINEL     = 0x%04X," % pals[ANCHOR][SENTINEL],
        "    WITNESS_IDX  = %d," % WITNESS,
        "    ANCHOR       = { name = \"%s\", who = \"KHAMELEON\", witness = 0x%04X, rgb = \"%s\" },"
        % (ANCHOR, pals[ANCHOR][WITNESS], rgb(pals[ANCHOR][WITNESS])),
        "    CYCLE = {",
    ]
    for name, who in CYCLE:
        out.append("        { name = \"%s\", who = \"%s\", witness = 0x%04X, rgb = \"%s\" },"
                   % (name, who, pals[name][WITNESS], rgb(pals[name][WITNESS])))
    out += ["    },", "}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--print", dest="show", action="store_true")
    a = ap.parse_args()
    pals = collect()
    txt = as_lua(pals)
    OUT.write_text(txt, encoding="ascii")
    names = [ANCHOR] + [n for n, _ in CYCLE]
    print("kham_disguise_expect.lua: sentinel[%d]=%04X, witness[%d] %s"
          % (SENTINEL, pals[ANCHOR][SENTINEL], WITNESS,
             " ".join("%s=%04X" % (n, pals[n][WITNESS]) for n in names)))
    if a.show:
        print()
        print(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
