#!/usr/bin/env python3
"""
victim_pose_audit.py - who poses the OTHER fighter by a hardcoded ani index.

Generalises a fix made by hand in `kahn_bigp_pose_victim` (MKBOSS.ASM): a move
that poses its victim with `movi <slot>,a9 / calla get_his_char_ani` is reading
the VICTIM's anitab1, and the two boss tables are short - `go_anitab1` has 24
entries and `sk_anitab1` 26, against 67 for everyone else. Any slot at or above
24 is off the end of a boss's table. That is the char-table overflow class that
has bitten this codebase before.

**This is a screening tool, not a bug list.** Most sites are gated by context
and the gates are real:

  * throws refuse bosses outright - `toss_check` (JOY.ASM) has
    "goro cant be flipped" and "shao kahn can't be flipped", so every
    MKSLAM site is unreachable with a boss victim;
  * fatalities test `ft_goro` / `ft_final_boss` before running;
  * some sites already use `boss_pick_ani` (MKUTIL.ASM), which takes
    a9 = [boss slot : normal slot] and picks on the ATTACKER's ochar. Note
    that is a8, not the victim - for "is HE a boss" the helper is
    `is_he_a_boss` right below it.

So a flagged row means "check whether a boss can be the victim here", and for
most of them the answer is no.

  python tools/victim_pose_audit.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
BOSS_MIN = 24                     # go_anitab1 is the shortest at 24 entries

CALL = re.compile(r"\bcalla\s+get_his_char_ani\b")
IDX = re.compile(r"\bmov[ki]\s+0?([0-9a-fA-F]{1,4})h?,a9\b\s*$")
GUARDED = ("boss_pick_ani", "goro_pick_ani", "is_he_a_boss", "am_i_a_boss")


def main():
    rows = []
    for path in sorted(glob.glob(os.path.join(SRC, "*.ASM"))):
        lines = open(path, encoding="latin-1",
                     errors="replace").read().splitlines()
        labels = []
        for i, ln in enumerate(lines):
            if ln[:1] not in (" ", "\t", "*", ";", ""):
                m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)", ln)
                if m:
                    labels.append((i, m.group(1)))
        for i, ln in enumerate(lines):
            if not CALL.search(ln.split(";")[0]):
                continue
            near = "\n".join(lines[max(i - 8, 0):i + 4])
            guard = next((g for g in GUARDED if g in near), None)
            idx = None
            for j in range(i - 1, max(i - 6, -1), -1):
                m = IDX.search(lines[j].split(";")[0].rstrip())
                if m:
                    v = int(m.group(1), 16)
                    # a packed [sleep|index] longword is not a slot number
                    idx = v if v < 0x100 else None
                    break
            lbl = ""
            for at, l in reversed(labels):
                if at <= i:
                    lbl = l
                    break
            rows.append((os.path.basename(path), i + 1, lbl, idx, guard))

    print("# Victim-pose audit\n")
    print("Generated by `tools/victim_pose_audit.py`. A move that poses its")
    print("victim by a hardcoded slot reads the VICTIM's anitab1. The boss")
    print("tables are short - Kintaro 24 entries, Shao Kahn 26, everyone else")
    print("67 - so any slot >= %d is off the end for a boss victim.\n" % BOSS_MIN)
    print("**Screening only.** Throws refuse bosses (`toss_check`), fatalities")
    print("test for them, and some sites use `boss_pick_ani`. A flagged row")
    print("means *check whether a boss can be the victim here*.\n")
    print("| file | line | routine | slot | note |")
    print("|---|---|---|---|---|")
    flagged = 0
    for f, ln, lbl, idx, guard in rows:
        if guard:
            note = "guarded by `%s`" % guard
        elif idx is None:
            note = "slot not a literal - read it"
        elif idx >= BOSS_MIN:
            note = "**past the boss tables**"
            flagged += 1
        else:
            note = "fits every table"
        print("| %s | %d | `%s` | %s | %s |"
              % (f, ln, lbl, ("%02xh" % idx) if idx is not None else "?", note))
    print()
    print("**%d site(s) use a slot past the boss tables.** Each needs the same"
          % flagged)
    print("question asked: can a boss be the victim of this move? For the")
    print("fatalities and throws the answer is no, and the gate is in the")
    print("code. `goro_slam` (MKBOSS.ASM) is the one that most resembles the")
    print("case already fixed - a boss move posing its opponent, reachable")
    print("with a boss victim only in a `test_mode` build.")


if __name__ == "__main__":
    main()
