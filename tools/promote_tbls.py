#!/usr/bin/env python3
"""
Promote LOAD2-regenerated TBL files from tmp/load2/ into src/.

LOAD2 owns the SAG/control fields in chunk-bearing TBLs. Anytime a .LOD changes
(new sprite, reordered IMG, etc.), LOAD2 repacks the IRW and emits a fresh
TBL with shifted addresses. If src/ keeps the old TBL, the assembled program
ROM points the GSP DMA at stale offsets and the affected sprites render
garbled.

This script patches SAG addresses and LOAD2 control words in src/*.TBL in-place
using the matching labels in tmp/load2/*.TBL. It deliberately does NOT do a
wholesale file replace: hand-added content (palette pointers on POF> entries,
extra labels that come from a separate LOD, custom modules wired into a TBL by
an ASM include) survives the patch.

Rules:
- Labels present in both src/ and regen: SAG and CTRL values are copied from regen.
- Labels in src/ but not regen: preserved (probably from another LOD).
- Labels in regen but not src/: appended at the bottom (probably new
  content the LOD just added).
- Hand-maintained TBLs in HAND_MAINTAINED: skipped entirely.
- Pure `.set` equate TBLs in SET_EQUATE_TABLES: copied label-by-label.
- Trailing palette pointers and hand-added lines on src/ entries: preserved.

Usage:
    python tools/promote_tbls.py                 # patch, print summary
    python tools/promote_tbls.py --check         # exit 1 if anything stale
    python tools/promote_tbls.py --verbose       # list every touched file
"""
