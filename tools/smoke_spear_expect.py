#!/usr/bin/env python3
"""Regenerate tools/smoke_spear_expect.lua from the LINKED sprite tables.

The rope records live in two generated/promoted tables - src/SMROPE.TBL
(COMEHERE1/2/3, Smoke's, from data/SMROPE.LOD) and src/MKNJ.TBL (BIGRP1,
BIGRP2, SPEARHIT, Scorpion's) - and every SAG in a pack moves when anything
ahead of it is re-cut.  A rig carrying hard-coded SAGs would therefore keep
passing against whatever art happened to land at the old address, which is the
exact failure tools/art_identity_snapshot.py exists to catch elsewhere.

So the numbers are READ OUT OF THE BUILD on every run, and this refuses rather
than guesses: a missing record, a duplicate label or a width that disagrees
with data/NEWROPE.IMG is an error, not a default.

    python tools/smoke_spear_expect.py [--out tools/smoke_spear_expect.lua]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# record -> (table file, the fighter it belongs to)
RECORDS = {
    "COMEHERE1": "src/SMROPE.TBL",
    "COMEHERE2": "src/SMROPE.TBL",
    "COMEHERE3": "src/SMROPE.TBL",
    "BIGRP1":    "src/MKNJ.TBL",
    "BIGRP2":    "src/MKNJ.TBL",
    "SPEARHIT":  "src/MKNJ.TBL",
}

# ft_* from MAINEQU.ASM.  The flight pair and the taut frame are the two parts
# of each fighter's rope lane (a_rope_ani / a_sm_rope_ani, MKNJ.ASM).
FIGHTERS = {
    "smoke":    dict(ft=14, flight=["COMEHERE1", "COMEHERE2"], taut="COMEHERE3"),
    "scorpion": dict(ft=10, flight=["BIGRP1", "BIGRP2"],       taut="SPEARHIT"),
}

REC_RE = re.compile(
    r"^(?P<name>\w+):\s*$\s*"
    r"\.word\s+(?P<w>-?\d+),(?P<h>-?\d+),(?P<ax>-?\d+),(?P<ay>-?\d+)\s*$\s*"
    r"\.long\s+0(?P<sag>[0-9a-fA-F]+)H",
    re.MULTILINE,
)


def parse(path: Path) -> dict[str, dict]:
    text = path.read_text(errors="replace")
    out: dict[str, dict] = {}
    for m in REC_RE.finditer(text):
        name = m.group("name")
        rec = dict(w=int(m.group("w")), h=int(m.group("h")),
                   ax=int(m.group("ax")), ay=int(m.group("ay")),
                   sag=int(m.group("sag"), 16))
        if name in out and out[name] != rec:
            raise SystemExit(f"{path}: {name} defined twice with different geometry")
        out[name] = rec
    return out


def img_geometry() -> dict[str, tuple[int, int]]:
    """{record: (w, h)} straight out of data/NEWROPE.IMG, to cross-check."""
    sys.path.insert(0, str(ROOT / "tools"))
    from make_cage_logo import parse_img          # noqa: E402
    recs, _pals = parse_img((ROOT / "data" / "NEWROPE.IMG").read_bytes())
    return {n: (r["w"], r["h"]) for n, r in recs.items()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="tools/smoke_spear_expect.lua")
    args = ap.parse_args()

    tables: dict[str, dict[str, dict]] = {}
    for rel in sorted(set(RECORDS.values())):
        p = ROOT / rel
        if not p.exists():
            raise SystemExit(f"missing {rel} - run python build.py first")
        tables[rel] = parse(p)

    img = img_geometry()
    found: dict[str, dict] = {}
    for name, rel in RECORDS.items():
        rec = tables[rel].get(name)
        if rec is None:
            raise SystemExit(f"{rel} does not define {name} - is data/{Path(rel).stem}.LOD packed?")
        if name in img and (rec["w"], rec["h"]) != img[name]:
            raise SystemExit(
                f"{name}: table says {rec['w']}x{rec['h']}, data/NEWROPE.IMG says "
                f"{img[name][0]}x{img[name][1]} - the art was re-cut without a rebuild")
        found[name] = rec

    lines = [
        "-- GENERATED by tools/smoke_spear_expect.py - do not edit.",
        "-- SAGs and widths read out of src/SMROPE.TBL and src/MKNJ.TBL, so this",
        "-- cannot go stale against a rebuild that moved the art.",
        "return {",
        "  all = {",
    ]
    for name in sorted(found):
        lines.append(f"    {name} = 0x{found[name]['sag']:08x},")
    lines.append("  },")
    for who, spec in FIGHTERS.items():
        flight = spec["flight"]
        taut = spec["taut"]
        lines.append(f"  {who} = {{")
        lines.append(f"    ft = {spec['ft']},")
        lines.append("    flight = { " + " ".join(
            f"[0x{found[n]['sag']:08x}] = true," for n in flight) + " },")
        lines.append(f"    taut = 0x{found[taut]['sag']:08x},")
        lines.append(f"    taut_w = {found[taut]['w']},")
        lines.append(f'    flight_names = "{"/".join(flight)}",')
        lines.append(f'    taut_name = "{taut}",')
        lines.append("  },")
    lines.append("}")

    out = ROOT / args.out
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    for who, spec in FIGHTERS.items():
        taut = found[spec["taut"]]
        print(f"  {who:9s} flight {'/'.join(spec['flight'])} "
              f"taut {spec['taut']} {taut['w']}px sag {taut['sag']:#010x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
