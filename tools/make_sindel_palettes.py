#!/usr/bin/env python3
r"""SINDEL'S COSTUMES (Wolf only, ochar 21) - authored in data/MK2PALS.IMG.

She had ONE palette on all seven costume lanes (LPRP_P), so a Sindel mirror
match had nothing to hand player 2: costnodup walks the lanes for a costume
the other player is not wearing and every lane answered the same one.  UMK3
gives her a second costume - `character_palettes_2[lia]` is LBLU_P - and that
is what a mirror wears there.

Four records, in the library's own naming so they sit beside everybody else's
and are repainted the same way (IMGTOOL, then this tool, then a build):

    SDMAIN_P   her default                      seeded from UMK3's LPRP_P
    SDALT1_P   Start + High Punch / the mirror  seeded from UMK3's LBLU_P
    SDBLD_P    cut-up art in the default        seeded as a copy of SDMAIN_P
    SDBLD1_P   cut-up art in the alternate      seeded as a copy of SDALT1_P

UMK3 has no bloodied palettes (MK3 dropped them), so the two BLD records
start as copies: authored places to paint, not data.

    --seed    add whichever of the four data/MK2PALS.IMG lacks (never
              overwrites one that is there - it may have been repainted)
    --apply   carry the four into src/SDPALS.ASM (SDP_* - included by
              UMK3SDM.ASM, named by tools/wolf_fighter_rows.py's rows)
    --check   Phase D: src/SDPALS.ASM is what the library holds
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import backup_code_palettes as lib      # noqa: E402

IMG = ROOT / "data" / "MK2PALS.IMG"
OUT = ROOT / "src" / "SDPALS.ASM"
MK3 = Path("C:/Users/you/Workplace/mk3-rebuild-main/mk3-rebuild-main/REV21")
NAMES = ("SDMAIN_P", "SDALT1_P", "SDBLD_P", "SDBLD1_P")
SEED = {"SDMAIN_P": ("IMGPAL3.ASM", "LPRP_P"), "SDALT1_P": ("MKGUYS.ASM", "LBLU_P"),
        "SDBLD_P": ("IMGPAL3.ASM", "LPRP_P"), "SDBLD1_P": ("MKGUYS.ASM", "LBLU_P")}


def mk3_palette(fname, label):
    txt = (MK3 / fname).read_text(errors="replace").splitlines()
    i = next(k for k, ln in enumerate(txt) if ln.strip().startswith(label + ":"))
    n = int(re.search(r"\.word\s+(\d+)", txt[i + 1]).group(1))
    words = []
    for ln in txt[i + 2:]:
        if ".word" not in ln:
            break
        for t in ln.split(".word", 1)[1].split(";")[0].split(","):
            t = t.strip().lower().rstrip("h")
            if t:
                words.append(int(t, 16))
    if len(words) != n:
        raise SystemExit(f"{label}: {len(words)} words, header says {n}")
    return words


def name_of(rec):
    return rec[0].split(b"\0")[0].decode("latin-1")


def library():
    _hdr, _images, pals, _first = lib.read_lib(IMG)
    return {name_of(rec): words for rec, words in pals}


def seed():
    hdr, images, pals, first = lib.read_lib(IMG)
    have = {name_of(rec) for rec, _w in pals}
    added = []
    for nm in NAMES:
        if nm not in have:
            pals.append((lib.pal_record(nm, mk3_palette(*SEED[nm])), mk3_palette(*SEED[nm])))
            added.append(nm)
    if added:
        IMG.write_bytes(lib.write_lib(hdr, images, pals, first))
    print("seeded " + (", ".join(added) if added else "nothing - all four are there"))


def asm():
    L = library()
    miss = [n for n in NAMES if n not in L]
    if miss:
        raise SystemExit("data/MK2PALS.IMG lacks " + ", ".join(miss) + " - run --seed")
    o = [";" + "*" * 70,
         ";  SINDEL'S COSTUMES (Wolf only) - GENERATED by tools/make_sindel_palettes.py",
         ";  out of data/MK2PALS.IMG.  Do not hand-edit: repaint the library.",
         ";  SDP_ + the record's name; included by UMK3SDM.ASM.",
         ";" + "*" * 70, "", "\t.data",
         "\t.globl\t" + ",".join("SDP_" + n for n in NAMES), ""]
    for n in NAMES:
        w = L[n]
        o.append(f"SDP_{n}:")
        o.append(f"\t.word\t{len(w)}")
        for i in range(0, len(w), 8):
            o.append("\t.word\t" + ",".join("0%04xh" % v for v in w[i:i + 8]))
        o.append("")
    o.append("\t.text")
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.seed:
        seed()
    if a.apply:
        OUT.write_text(asm(), newline="\r\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
    if a.check:
        if not OUT.exists() or OUT.read_text() != asm():
            print("make_sindel_palettes: STALE src/SDPALS.ASM (--apply)")
            return 1
        print("make_sindel_palettes: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
