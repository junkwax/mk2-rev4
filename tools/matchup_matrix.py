#!/usr/bin/env python3
"""
matchup_matrix.py - every move against every character: what reaches, what does not.

MOVE_MATRIX.md gives each attacker's move a connect band against a GENERIC
opponent. hurtbox.lock gives each character's real size. Neither joins to the
other, so nobody could ask the question a player actually asks: does this move
reach THAT character.

This joins them. The model is the one the collision code uses:

    a hit needs the strike box to overlap the victim's hittable column
    sq_punch insets 3W/8 from each side, leaving a column of W/4 centred on him
    so the column reaches W/8 either side of his anipoint

        max range = box front edge + W/8
        min range = box near edge  - W/8

**Validated against the machine.** Baraka's high kick has a box of +23..+83
against a 62 px opponent, so the model says it connects out to 83 + 62/8 = 91.
Swept in the emulator, it connects at 88 and whiffs at 90
(tools/sweep_addon_hikick.lua). Within about 2 px, which is the width of the
rounding in the sprite tables.

The victim-dependent term is W/8, and the answer that falls out is worth
having: across the non-boss cast it spans just 1.9 px. Character size barely
decides anything. Only Kintaro, at 127 px against Kitana's 56, is meaningfully
different - everything reaches him 8.9 px earlier.

  python tools/matchup_matrix.py
"""
import glob
import importlib.util
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


BA = _load("ba", os.path.join(ROOT, "tools", "box_align_audit.py"))
MM = _load("mm", os.path.join(ROOT, "tools", "move_matrix.py"))
FD = _load("fd", os.path.join(ROOT, "tools", "frame_data.py"))



def posture_widths():
    """character -> {posture: width} from doc/hurtbox.lock.

    Only postures whose lane is SHORT enough that the union across it is
    honest. Stance is 8-10 near-identical frames, duck 3, jump-up 2 - those
    describe a shape. The walk lanes are 9 frames of a full stride and their
    union is the whole step, not the fighter, so a hit model must not use
    them: Kung Lao reads 81 px walking against 71 standing purely because his
    leading foot and trailing foot are in the same union.
    """
    import os as _os
    path = _os.path.join(ROOT, "doc", "hurtbox.lock")
    if not _os.path.exists(path):
        return {}
    want = {"00h": "stance", "05h": "duck", "06h": "jump"}
    out = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^(\S[\S ]*?)\s+([0-9a-f]{2}h)\s+(\S+)\s+(\d+)\s+"
                     r"([+-]\d+)\.\.\s*([+-]\d+)", line)
        if not m:
            continue
        ch, slot, _lane, _n, lo, hi = m.groups()
        if slot in want:
            out.setdefault(ch.strip(), {})[want[slot]] = int(hi) - int(lo)
    return out


def main():
    strips = BA.parse_strips()
    frames_by_file, frames = BA.parse_frames()
    lanes = {}
    for path in glob.glob(os.path.join(SRC, "*.ASM")):
        for k, v in BA.lane_lines(BA.read(path)).items():
            lanes.setdefault(k, v)
    text_all = "\n".join(BA.read(p)
                         for p in glob.glob(os.path.join(SRC, "*.ASM")))
    tabs = BA.parse_anitabs(text_all)
    widths = MM.stance_widths(tabs, lanes, frames, strips)

    stk = BA.read(os.path.join(SRC, "MKSTK.ASM"))
    recs = FD.parse_records(stk)
    lists = BA.parse_lists(stk)

    print("# Matchup matrix - what reaches whom\n")
    print("Generated by `tools/matchup_matrix.py`. Computed from the strike")
    print("boxes and each character's real silhouette, using the model the")
    print("collision code actually uses, and **validated against the**")
    print("**emulator** to within ~2 px on Baraka's high kick.\n")
    print("A hit needs the strike box to overlap the victim's hittable")
    print("column. `sq_punch` insets 3W/8 from each side, leaving W/4 centred")
    print("on him - so the column reaches **W/8 either side** of his anipoint,")
    print("and the reach of every move depends on who is standing there:\n")
    print("    max range = box front + W/8")
    print("    min range = box near  - W/8\n")

    print("## How big everyone is\n")
    print("| character | stance width | column half-width (W/8) |")
    print("|---|---|---|")
    for oc, name in enumerate(BA.CHARS):
        w = widths.get(oc)
        if w:
            print("| %s | %d px | %+.1f |" % (name, w, w / 8.0))
    live = {o: w for o, w in widths.items() if w}
    lo_oc = min(live, key=lambda o: live[o])
    hi_oc = max(live, key=lambda o: live[o])
    non_boss = {o: w for o, w in live.items() if o not in (12, 13)}
    nlo = min(non_boss, key=lambda o: non_boss[o])
    nhi = max(non_boss, key=lambda o: non_boss[o])
    print()
    print("**%s is the smallest target at %d px and %s the largest at %d.**"
          % (BA.CHARS[nlo], non_boss[nlo], BA.CHARS[nhi], non_boss[nhi]))
    print("That is a **%.1f px** swing in how far every move in the game"
          % ((non_boss[nhi] - non_boss[nlo]) / 8.0))
    print("reaches, before anyone moves. Including the bosses it is %.1f px."
          % ((live[hi_oc] - live[lo_oc]) / 8.0))
    print()

    print("## So how much does the matchup actually change?\n")
    print("**Almost nothing, across the normal cast - and that is the**")
    print("**finding.** The only victim-dependent term is W/8, so every move")
    print("in the game reaches %.1f px further against %s than against %s."
          % ((non_boss[nhi] - non_boss[nlo]) / 8.0, BA.CHARS[nhi],
             BA.CHARS[nlo]))
    print("Under two pixels. Spacing learned in one matchup transfers to")
    print("every other one, which is a good property for a tournament game")
    print("and is not something anyone had checked.\n")
    print("The bosses are the exception:\n")
    print("| victim | width | every move reaches | vs %s |"
          % BA.CHARS[nlo])
    print("|---|---|---|---|")
    for oc in sorted(live, key=lambda o: live[o]):
        w = live[oc]
        print("| %s | %d px | %+.1f px | %+.1f |"
              % (BA.CHARS[oc], w, w / 8.0, (w - non_boss[nlo]) / 8.0))
    print()
    print("**Kintaro is hit by everything %.1f px earlier than Kitana is.**"
          % ((live[hi_oc] - non_boss[nlo]) / 8.0))
    print("That is the whole matchup effect in this game, and it applies to")
    print("one character.\n")
    print("## What this does NOT cover\n")
    print("Projectile records. Their box rides the projectile object rather")
    print("than the fighter, so the front edge is not a reach - `stk_jczap1`")
    print("reads as 10 px and means nothing here. The same caveat")
    print("MOVE_MATRIX.md carries.\n")
    print("\n## Does crouching or jumping change what reaches you?\n")
    pw = posture_widths()
    if pw:
        print("Also barely. The column is W/8 either side, so a posture only")
        print("matters if it changes the silhouette's WIDTH - and crouching in")
        print("this game lowers you without narrowing you much.\n")
        print("| character | standing | ducking | jumping | duck vs stand |")
        print("|---|---|---|---|---|")
        deltas = []
        for oc, name in enumerate(BA.CHARS):
            d = pw.get(name)
            if not d or "stance" not in d:
                continue
            st = d["stance"]
            dk = d.get("duck")
            jp = d.get("jump")
            if dk:
                deltas.append((dk - st) / 8.0)
            print("| %s | %d | %s | %s | %s |"
                  % (name, st, dk if dk else "-", jp if jp else "-",
                     ("%+.1f px" % ((dk - st) / 8.0)) if dk else "-"))
        if deltas:
            print()
            print("Ducking changes incoming reach by between %+.1f and %+.1f px."
                  % (min(deltas), max(deltas)))
            print("Crouching in MK2 is a way to go UNDER a high attack - which")
            print("3.1 measured working, 5/5 against 0/5 - not a way to make")
            print("yourself a narrower target.")
        print()
        print("Walk lanes are excluded on purpose: their extents are a union")
        print("across a nine-frame stride, so they describe the step rather")
        print("than the fighter, and would overstate every number here.")


if __name__ == "__main__":
    main()
