#!/usr/bin/env python3
"""THE TOWER's pillar reflection: Midway's own PILREF, faded out (twrpilref).

CASTLE.IMG carries the reflection vocabulary for a castle stage that was never
built: the statue-base strips the guards already use (STATREF, data/STATREF.LOD)
and PILREF, a 47x46 HAND-PAINTED reflection of the CASTLE column - base at the
top, the spiral redrawn upside down and foreshortened - on its own REFLX
palette.  It was never packed.  THE TOWER's pillar is that column, so its
reflection comes home the way the statues' did.

PILREF ends on its own bottom edge, so this bakes a FADE into it the way the
guards' strips fake translucency: the DMA has no alpha, so the reflection is
thinned against index 0 with an ordered (4x4 Bayer) dither - solid for the top
SOLID of its rows, then thinning to nothing at the bottom.  The marble shows
through the gaps.

Writes data/PILREFD.IMG (packed by data/PILREFD.LOD) and src/PILREFP.ASM (the
REFLX words as PILRFX_P - nothing promotes an IMG palette into the ROM).
--check is in Phase D: CASTLE.IMG is hand-edited in IMGTOOL, so a repaint of
PILREF or REFLX must be carried here or it ships stale.

    python tools/make_pilref_img.py --apply
    python tools/make_pilref_img.py --check
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import fl_cave_img as F  # noqa: E402  (the IMG layout IMGTOOL/LOAD2 read)

SRC = ROOT / "data" / "CASTLE.IMG"
OUT_IMG = ROOT / "data" / "PILREFD.IMG"
OUT_ASM = ROOT / "src" / "PILREFP.ASM"
SOLID = 0.30            # fraction of the rows drawn solid before the fade
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def castle():
    d = SRC.read_bytes()
    imgcnt, _palcnt, oset, *_ = F.LIB_HDR.unpack_from(d, 0)
    recs = {}
    for i in range(imgcnt):
        f = F.IMAGE.unpack_from(d, oset + i * F.IMAGE.size)
        recs[f[0].split(b"\0")[0].decode("latin1")] = f
    f = recs["PILREF"]
    w, h, pn, do = f[4], f[5], f[6], f[7]
    st = (w + 3) & ~3
    px = [[d[do + y * st + x] for x in range(w)] for y in range(h)]
    p = F.PALETTE.unpack_from(d, oset + imgcnt * F.IMAGE.size + (pn - F.NUMDEFPAL) * F.PALETTE.size)
    name = p[0].split(b"\0")[0].decode("latin1")
    if name != "REFLX":
        raise SystemExit(f"PILREF is on palette {name}, expected REFLX - re-check the art")
    pal = list(struct.unpack_from(f"<{p[3]}H", d, p[4]))
    return w, h, px, pal


def faded(w, h, px):
    out = []
    for y in range(h):
        keep = 1.0 if y < SOLID * h else max(0.0, 1 - (y - SOLID * h) / ((1 - SOLID) * h))
        out.append([v if v and BAYER[y % 4][x % 4] / 16.0 < keep else 0
                    for x, v in enumerate(px[y])])
    return out


def generate():
    w, h, px, pal = castle()
    fd = faded(w, h, px)
    F.W, F.H, F.BPP = w, h, 6
    F.IMG_NAME, F.PAL_NAME = "PILREFD", "PILREFD_P"
    img = F.build_img([v for r in fd for v in r], pal)
    asm = ["; GENERATED by tools/make_pilref_img.py - do not edit.",
           "; CASTLE.IMG's REFLX, the palette PILREF (data/PILREFD.IMG) is painted in.",
           "PILRFX_P:", f"\t.word\t{len(pal)}"]
    for i in range(0, len(pal), 8):
        asm.append("\t.word\t" + ",".join(f"0{c:04x}h" for c in pal[i:i + 8]))
    return img, "\n".join(asm) + "\n", w, h, fd


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    img, asm, w, h, fd = generate()
    kept = sum(1 for r in fd for v in r if v)
    print(f"PILREFD {w}x{h}: {kept} pixels drawn, solid for the top {SOLID:.0%}")
    if a.apply:
        OUT_IMG.write_bytes(img)
        OUT_ASM.write_text(asm)
        print("wrote", OUT_IMG.relative_to(ROOT), "and", OUT_ASM.relative_to(ROOT))
        return 0
    stale = []
    if not OUT_IMG.exists() or OUT_IMG.read_bytes() != img:
        stale.append(str(OUT_IMG.relative_to(ROOT)))
    if not OUT_ASM.exists() or OUT_ASM.read_text() != asm:
        stale.append(str(OUT_ASM.relative_to(ROOT)))
    for s in stale:
        print("FAIL: stale -", s, "(run --apply)")
    if not stale:
        print("OK")
    return 1 if (stale and a.check) else 0


if __name__ == "__main__":
    sys.exit(main())
