#!/usr/bin/env python3
"""SHAO KAHN STANDING IN THE PIT III - how far left he reaches, row by row.

Writes tmp/pit3kahn/profile.lua: for each frame up3k_proc can show (seated
SHATAUNT/SHACKNE/SHAFISTS + the shin, the rise SHAGETUP1-4, the point
BGTALK1-5 + BGTALKLEG1), keyed by its record's "WxH", the LEFTMOST opaque
world x of every world row - drawn flipped at the anchor, exactly as
tools/make_pit3kahn.py places it.  tools/wolf_pit3_touch_check.lua reads it
and measures fighters against it.  Not part of the build."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_pit3kahn as k  # noqa: E402

imgs, pal = k.read_newshao()
imgs.update(k.read_talk(pal))
out = ["-- GENERATED by tools/pit3_kahn_profile.py", "return {"]
names = k.FRAMES + k.TALK_FRAMES
for n in names:
    im = imgs[n]
    w = im["w"]
    dx, dy = (k.LEG_DX, k.LEG_DY) if n == k.LEG else         (k.RISE_DX, k.RISE_DY) if n in k.GETUP + k.TALK_FRAMES else (0, 0)
    left = k.KAHN_X - (w - 1 - im["ax"]) + dx
    top = k.KAHN_Y - im["ay"] + dy
    rows = {}
    for y in range(im["h"]):
        xs = [left + (w - 1 - x) for x in range(w) if im["px"][y * w + x]]
        if xs:
            rows[top + y] = min(xs)
    out.append(f'  ["{w}x{im["h"]}"] = {{name="{n}", rows={{' +
               ",".join(f"[{y}]={x}" for y, x in sorted(rows.items())) + "}},")
out.append("}")
dst = k.ROOT / "tmp" / "pit3kahn" / "profile.lua"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(out) + "\n")
print(f"wrote {dst}")
