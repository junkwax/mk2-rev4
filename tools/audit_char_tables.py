# Rows FOUR units wide: `.word x,y,ani,offset` read with sll 6.  Counting these
# as pairs would report 8 rows as 16 and call a short table healthy.
QUAD_TABLES = set("""head_lineups""".split())

DATA = re.compile(r'^\s*\.(long|word)\s+(.*?)(?:;.*)?$')
LABEL = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*)\b')

def load(path):
    with open(path, encoding="latin-1") as f:
        return f.readlines()

# index: label -> (file, lineno)
defs = {}
files = {p: load(p) for p in glob.glob(os.path.join(SRC, "*.ASM"))}
for p, lines in files.items():
    for i, ln in enumerate(lines):
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)\b', ln)
        if m and (ln[0] not in ' \t'):
            defs.setdefault(m.group(1), (p, i))

def count_entries(name):
    if name not in defs:
        return None, None
    p, i = defs[name]
    lines = files[p]
    longs = words = 0
    j = i + 1
    while j < len(lines):
        ln = lines[j]
        s = ln.strip()
        if not s or s.startswith(';') or s.startswith('*'):
            j += 1; continue
        m = DATA.match(ln)
        if m:
            vals = [v for v in m.group(2).split(',') if v.strip() != '']
            if m.group(1) == 'long': longs += len(vals)
            else: words += len(vals)
            j += 1; continue
        # a new label or instruction ends the table
        if re.match(r'^[A-Za-z_][A-Za-z0-9_]*\b', ln) and ln[0] not in ' \t':
            break
        if re.match(r'^\s+(movi|move|calla|callr|jauc|jruc|jrc|rets|retp)\b', ln):
            break
        j += 1
    return longs, words

# Known-safe short tables: dispatch is gated (cmpi 12,ochar / jrhs skip) so
# ochar>=12 never reads them, or it's a duplicate label of a full table.
# ochar_baby_combos LEFT THIS LIST 2026-09-08.  It was exempt because
# bb_check refused ochar>=12 before ever indexing it; Ermac's babality
# relaxed that guard, so the table is now the thing that decides and it has
# to be full length like every other one.  A zero row is the refusal.
GATED_SAFE = {
    "char_joyleft": "2nd label on char_joyright (same 20-row table)",
    "db1_table": "gated: ochar 0-11 button handlers + drone_finish_him",
    "db2_table": "gated: ochar 0-11 button handlers + drone_finish_him",
}

print(f"{'table':28} {'longs':>6} {'words':>6}  chars  status")
print("-" * 70)
short = 0
for name in TABLES + WORD_TABLES:
    longs, words = count_entries(name)
    if longs is None:
        print(f"{name:28} {'?':>6} {'?':>6}  (label not found - maybe local/renamed)")
        continue
    # entries per char: prefer .long (1/char); word tables are usually 2/char,
    # except the get_char_word tables, which are exactly 1 word per char.
    if name in QUAD_TABLES:
        n = longs if longs >= words else words
        chars = n // 4; unit = ("long" if longs >= words else "word") + "-quad"
    elif name in PAIR_TABLES:
        n = longs if longs >= words else words
        chars = n // 2; unit = ("long" if longs >= words else "word") + "-pair"
    elif name in WORD_TABLES:
        chars = words; unit = "word"
    elif longs >= words:
        chars = longs; unit = "long"
    else:
        chars = words // 2 if words % 2 == 0 else words; unit = "word/2" if words % 2 == 0 else "word"
    if chars >= 20:
        flag = "OK"
    elif name in GATED_SAFE:
        flag = "SHORT-but-SAFE (" + GATED_SAFE[name] + ")"
    else:
        flag = ">>> SHORT (<20) - JADE/SMOKE/NOOB/ERMAC/KHAMELEON/RAIN OVERFLOW <<<"
        short += 1
    print(f"{name:28} {longs:>6} {words:>6}  {chars:>3}({unit})  {flag}")

print("-" * 70)
print(f"{short} short table(s)")
raise SystemExit(1 if short else 0)
