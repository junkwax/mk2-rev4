#!/usr/bin/env python3
"""
juggle_ceiling.py - the most damage a character could take out of one opening.

Section 4.3 of doc/TOURNAMENT_READINESS.md wants "max damage from one opening,
per character". It also warns, in the same breath, that driving inputs to find
it "would measure the rig's cadence, which has cost this project several
afternoons" - so this deliberately does NOT try to play the game.

It computes a CEILING instead, from two things already measured:

  * every strike record's hit damage, per character (MKSTK.ASM);
  * the observed string lengths - average 2.1-3.4 hits, longest 5 in 20 of 22
    battles - from tools/sweep_addon_phit.lua.

The ceiling is the sum of that character's N highest-damage records. It is an
UPPER BOUND and says so: nothing here checks that those particular moves can
follow one another in the air, and several cannot. What it is good for is the
comparison - if one character's 3-hit ceiling is half a bar and another's is a
third, that gap is real whatever the routes turn out to be.

Every contributing move is NAMED for exactly that reason. A ceiling built from
three uppercuts is not a juggle, and listing them is what lets a reader see it
rather than take the number on trust.

  python tools/juggle_ceiling.py
  python tools/juggle_ceiling.py --csv doc/juggle_ceiling.csv
"""
import argparse
import csv
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
MAX_HP = 0xA1                       # 161, not 100


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


BA = _load("ba", os.path.join(ROOT, "tools", "box_align_audit.py"))
FD = _load("fd", os.path.join(ROOT, "tools", "frame_data.py"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv")
    args = ap.parse_args()

    stk = BA.read(os.path.join(SRC, "MKSTK.ASM"))
    recs = FD.parse_records(stk)
    lists = BA.parse_lists(stk)

    rows = []
    for oc, cname in enumerate(BA.CHARS):
        moves = []
        seen = set()
        for lab in lists.get(BA.CHAR_LIST[oc], []):
            r = recs.get(lab)
            if not r or not r.get("hit"):
                continue
            if lab in seen:
                continue
            seen.add(lab)
            moves.append((r["hit"], lab))
        if not moves:
            continue
        moves.sort(reverse=True)
        top5 = moves[:5]
        rows.append(dict(
            char=cname,
            best=top5[0][0],
            best_move=top5[0][1],
            sum3=sum(d for d, _ in top5[:3]),
            sum5=sum(d for d, _ in top5),
            moves3=", ".join("`%s` %d" % (l, d) for d, l in top5[:3]),
            moves5=", ".join("`%s` %d" % (l, d) for d, l in top5)))

    print("# Juggle damage ceiling\n")
    print("Generated by `tools/juggle_ceiling.py`. **These are upper bounds,")
    print("not combos.** Nothing here checks that the listed moves can follow")
    print("one another in the air, and several cannot - the number bounds the")
    print("balance question rather than answering it. Section 4.3 warns that")
    print("finding the real routes by driving inputs measures the rig's")
    print("cadence rather than the game, so this does not try.\n")
    print("Health is **%d**, not 100. Observed strings run 2.1-3.4 hits with"
          % MAX_HP)
    print("a longest of 5, so the 3-hit column is the realistic shape and the")
    print("5-hit column is the hard cap `p_hit > 3` allows.\n")
    print("| character | best single | 3-hit ceiling | % of bar | "
          "5-hit ceiling | % of bar |")
    print("|---|---|---|---|---|---|")
    for r in sorted(rows, key=lambda r: -r["sum3"]):
        print("| %s | %d (`%s`) | **%d** | %.0f%% | %d | %.0f%% |"
              % (r["char"], r["best"], r["best_move"], r["sum3"],
                 100.0 * r["sum3"] / MAX_HP, r["sum5"],
                 100.0 * r["sum5"] / MAX_HP))

    vals = [r["sum3"] for r in rows]
    if vals:
        hi = max(rows, key=lambda r: r["sum3"])
        lo = min(rows, key=lambda r: r["sum3"])
        print()
        print("**Spread: %d to %d damage on the 3-hit ceiling, %.0f%% to "
              "%.0f%% of a bar** — %s highest, %s lowest."
              % (lo["sum3"], hi["sum3"], 100.0 * lo["sum3"] / MAX_HP,
                 100.0 * hi["sum3"] / MAX_HP, hi["char"], lo["char"]))

    print("\n## What each ceiling is made of\n")
    print("Named so the number can be checked rather than trusted. A ceiling")
    print("built from three copies of the same uppercut is not a juggle, and")
    print("this is where that shows.\n")
    print("| character | the three moves |")
    print("|---|---|")
    for r in sorted(rows, key=lambda r: -r["sum3"]):
        print("| %s | %s |" % (r["char"], r["moves3"]))

    if args.csv:
        out = args.csv if os.path.isabs(args.csv) else os.path.join(ROOT, args.csv)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", newline="", encoding="utf-8") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        print("\ncsv -> %s" % args.csv, file=sys.stderr)


if __name__ == "__main__":
    main()
