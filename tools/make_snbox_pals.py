#!/usr/bin/env python3
"""SINDEL's select-screen palettes (Wolf only) -> src/SNBOXPAL.ASM: the Mileena
-> Sindel box wipe and her 1-player ladder mug (smsnbox, MOUNTAIN.IMG).

FN2BOX2-9 (data/MKBOXES.IMG, packed by data/SNBOX.LOD) sit on the library
palette named SNBOX1 - 245 colours, Mileena's box colours and Sindel's together
(the name is the IMG's, and is a PALETTE: the old SNBOX1 record is no longer
packed, so the label is free) - and a PON> record names its palette, so the ROM
needs that palette under that name.
Nothing promotes an IMG palette into the ROM, so a repaint in IMGTOOL would
otherwise ship the old colours silently: this carries it, plus SNBOX1D,
its dimmed "picked" twin by the same rule as every BOXnD_P set in MKSEL.ASM
(R-12, G-11, B kept, each clamped at 0), for box_dim_table.

    python tools/make_snbox_pals.py --apply    # write src/SNBOXPAL.ASM
    python tools/make_snbox_pals.py --check    # it is current (Phase D)
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
import check_img_names as cin           # noqa: E402
import img_subframe_audit as audit      # noqa: E402
from imgdump import PALETTE              # noqa: E402

IMG = ROOT / "data" / "MKBOXES.IMG"
MOUNTAIN = ROOT / "data" / "MOUNTAIN.IMG"
MUG_PAL = "SNBOX65_p"      # smsnbox, her LADDER mug (the 1-player mountain)
OUT = ROOT / "src" / "SNBOXPAL.ASM"
PAL = "SNBOX1"
DIM = "SNBOX1D"            # its dimmed twin (box_dim_table, MKSEL.ASM)


def palette_words(name, img=IMG):
    recs, pals, data, stride = cin.read_library(img)
    imgcnt, palcnt, oset = struct.unpack_from("<HHI", data, 0)
    best = None
    for start in (oset, oset + palcnt * PALETTE.size):
        for st in audit.STRIDES:
            s = audit._score(data, start, st, imgcnt)
            if best is None or s > best[0]:
                best = (s, start, st)
    img_start = best[1]
    pal_start = img_start + imgcnt * stride if img_start == oset else oset
    hits = [i for i, p in enumerate(pals) if p == name]
    if len(hits) != 1:
        raise SystemExit(f"{img.name}: {len(hits)} palettes named {name}")
    f = PALETTE.unpack_from(data, pal_start + hits[0] * PALETTE.size)
    return list(struct.unpack_from(f"<{f[3]}H", data, f[4]))


def dim(w):
    r, g, b = (w >> 10) & 31, (w >> 5) & 31, w & 31
    return (max(r - 12, 0) << 10) | (max(g - 11, 0) << 5) | b


def block(name, words, note):
    out = [f"; {note}", f"{name}:", f"\t.word\t{len(words)}"]
    for i in range(0, len(words), 8):
        out.append("\t.word\t" + ",".join(f"0{w:04x}h" for w in words[i:i + 8]))
    return out


def build():
    w = palette_words(PAL)
    out = [";" + "*" * 70,
           ";  Mileena -> SINDEL select-box wipe palettes (Wolf only) -",
           ";  GENERATED by tools/make_snbox_pals.py from data/MKBOXES.IMG;",
           ";  edit the library, then rerun the tool.  Included by MKSEL.ASM",
           ";  under .if wunit.",
           ";" + "*" * 70,
           "\t.data", ""]
    out += block(PAL, w, f"MKBOXES.IMG {PAL} - FN2BOX2-9 (data/SNBOX.LOD), {len(w)} colours")
    out += [""]
    out += block(DIM, [dim(x) for x in w],
                 f"dimmed {PAL} - R-12, G-11, B kept (box_dim_table)")
    out += [""]
    m = palette_words(MUG_PAL, MOUNTAIN)
    out += block(MUG_PAL, m, f"MOUNTAIN.IMG {MUG_PAL} - smsnbox, her ladder mug (data/SNBOX.LOD), "
                             f"{len(m)} colours")
    out += ["", "\t.text", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.apply:
        OUT.write_text(text, encoding="latin-1", newline="\r\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="latin-1") != text:
            raise SystemExit(f"{OUT.relative_to(ROOT)} has drifted from {IMG.name} - rerun --apply")
        print("SNBOXPAL.ASM matches MKBOXES.IMG")
    if not (a.apply or a.check):
        print(text[:600])
    return 0


if __name__ == "__main__":
    sys.exit(main())
