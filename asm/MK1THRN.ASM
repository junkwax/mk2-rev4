**************************************************************************
*											     *
*  video game project:	Mortal Kombat 2							*
*											     *
*  module: mk1thrn.asm  --- THE THRONE ROOM (MK1), curback 01Ch		     *
*											     *
*  MK1's court of Shang Tsung: red lacquer walls hung with landscape	     *
*  scrolls, blue jade medallions, gilt dragons either side of the throne   *
*  alcove, spiral gold columns, a grey stone ledge and the red-and-gold    *
*  runner the fighters stand on.						     *
*											     *
*  Where it all comes from - read, not remembered - is in the header of    *
*  tools/make_mk1throne.py.  In short:					     *
*    art       C:\MAME\roms\mk.zip, MK1 rev 5.0.  THERE IS NO .BDB/.BDD    *
*              FOR THIS STAGE IN THE LEAK (THE PIT has KUNGFU5 and THE     *
*              WARRIOR SHRINE KUNGFU1; nothing in data/ holds one pixel    *
*              of this one), so the tool decodes all 45 images straight    *
*              out of MK1's video ROM and proves the packed bytes against  *
*              them on every build				     *
*    layout    MK1's stage record FFCB8080: erase colour, ground, camera,  *
*              limits, module placements and scroll rates all read off it  *
*											     *
*  THE PLANE LIST HAS A SKIP IN IT.  init_bakmods (BGND.ASM, ibak3) walks  *
*  `.long bmod / .word x,y' at 64 bits an entry but advances only 32 for   *
*  a `.long skip_bakmod' - and THE THRONE ROOM is the one MK1 stage that   *
*  uses one.  Read as a uniform list it looks like a three-module stage    *
*  that ends early, which builds and renders perfectly well and is not     *
*  this room.  Back to front:						     *
*    baklst8   the throne - rate 0, it never scrolls sideways		     *
*    baklst7   the back wall, the gilt dragons and the throne alcove	     *
*    baklst6   the ledge behind the scroll paintings			     *
*    baklst5   the scroll paintings and the jade medallions		     *
*    baklst4   SKIPPED, as MK1 skips it					     *
*    baklst3   the near columns, their capitals and the ledge		     *
*    baklst2   the runner the fighters stand on			     *
*    baklst1   the skirt below it						     *
*											     *
*  MK1 creates ONE process here and it is SHANG TSUNG SEATED ON THE	     *
*  THRONE (calla FFCB8600 -> FFD6E660), a four-frame five-piece object.    *
*  He is not a background module; mk1t_shang builds him - see		     *
*  doc/MK1_THRONE_ROOM.md.  When either player (human or CPU) IS Shang     *
*  Tsung, he is left out and mk1t_chair draws the throne EMPTY instead.    *
*											     *
*  Its own object for MK3CAVE.ASM's reason: BGND.ASM is near GSPA's	     *
*  out-of-memory point, and only lists mk1thrn_mod in table_o_mods.	     *
*											     *
**************************************************************************
