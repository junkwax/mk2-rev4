mk1thrn_calla
	clr	a0
	move	a0,@mk1p_sky_lst,l	; the object pool is rebuilt between
					; stages - never inherit a list head, and
					; not even for the one tick before the
					; process first runs
	move	@p1_char,a0,w
	move	@p2_char,a1,w
	movi	ft_st,a2
	calla	double_compare		; Shang Tsung fighting - human or CPU ?
	jreq	mk1t_calla_empty	; yes: he cannot also be on the throne
	create	pid_bani,mk1t_shang	; pid_bani, not pid_fx: killfx sweeps
					; every pid_fx process on a fatality
	jruc	mk1t_calla_shad
mk1t_calla_empty
	create	pid_bani,mk1t_chair	; the throne, empty - sitting_kahn's rule
mk1t_calla_shad
	movi	mk1t_shad_fast,a0	; fast compressed shadows, as every
	move	a0,@shad_fast,w		;   fightable stage - STAGE_SHADOW_SWEEP.md
*
* NO SHADOW CLIP.  init_bakmods (BGND.ASM) hands every stage shad_hi/shad_lo
* 255, which is wider than the screen is tall, so nothing is clipped; a stage
* only narrows them if it stands on something the shadow must not spill off,
* the way THE PIT's deck and THE WARRIOR SHRINE's walkway do.
*
* This one has no such edge - the runner reaches the bottom of the screen and
* the wall behind it is a flat backdrop, not a ledge - so the full shadow is
* correct.  An earlier cut clipped it to the runner's own 19 rows above the
* ground line and 25 below, and that CUT THE SHADOW OFF: a fighter's shadow is
* taller than the band, so it was chopped flat against the carpet instead of
* spreading.  Measuring a band is only right when there is something to fall
* off.
*
	rets

**************************************************************************
*											     *
*  mk1t_shang - SHANG TSUNG SEATED ON THE THRONE			     *
*											     *
*  MK1's own, read with MAME's disassembler and then measured in real MK1  *
*  runs (tools/run_mk1_throne_{anim,park,win}_probe.ps1).		     *
*											     *
*  WATCHING:  HE IS NOT ANIMATING - HE IS LOOKING AT THE CAMERA.  There is *
*  no lane and no timer.  Every mk1t_sh_rate ticks MK1 reads plane 1's	     *
*  camera x and picks one of seven poses by how far that camera is from    *
*  mk1t_sh_mid, mk1t_sh_step pixels to a step, clamped at mk1t_sh_maxb.    *
*  At or left of mk1t_sh_flat it takes bucket 3 whatever the sum says -    *
*  MK1's own JRLS branch.  So he turns his head to follow the fight, holds  *
*  it while the fight holds still, and snaps when the camera crosses a	     *
*  step.  A fixed animation lane would look right in any screenshot and be  *
*  wrong; the probe log's irregular holds (170, 184, 80, 344 ticks) read    *
*  exactly like a random-delay idle, which is why this was measured.	     *
*											     *
*  CLAPPING:  when a round is won he applauds.  MK1 keeps a ten-entry	     *
*  round-end hook table at FFCACF50, indexed by curback exactly as the	     *
*  stage table is; every entry is a bare RETS except the two THRONE ROOM    *
*  records', which kill the watching process and start the clap lane at     *
*  FFD6EC20 - clap4, clap3, clap2, clap3, looping - at MOVK 5h a frame.     *
*  Measured in a real MK1 win: it begins mk1t_sh_cwait ticks after the	     *
*  round is decided, holds every frame mk1t_sh_crate ticks, runs about	     *
*  mk1t_sh_cframes frames and then stops where it is, and the watching	     *
*  resumes for the next round.  ONLY A PLAIN WIN: a draw (winner_status    *
*  stays 0) and a round that goes to FINISH HIM (3) get no applause.	     *
*											     *
*  ONE POSE IS FOUR SLOTS PLUS THE LAP.  Every pose MK1 draws is three or   *
*  four pieces in front of the same seated robe, so the stage builds	     *
*  mk1t_sh_slots upper-body objects once and swaps each one's art with	     *
*  ani_flag; a pose with only three repeats its last piece, which draws it  *
*  twice in the same place for one blit and needs no blank record and no    *
*  inviso flag - there is no safe way to set one on a single-part object.   *
*  EVERY SLOT IS RE-PLACED on a pose change: the seven watching poses share *
*  one anipoint per slot, but the clap's pieces do not.		     *
*											     *
*  They ride mk1p_sky_lst (THE PIT's block, borrowed the way THE WARRIOR    *
*  SHRINE borrows it) paired in dlists_mk1thrn with worldtlx4 - PLANE 4,    *
*  which carries no module of its own but whose worldtlx MK1 still scrolls. *
*  Which plane was MEASURED, not assumed: his head template-matches at	     *
*  score 1.00 in six stationary MK1 frames and plane 4 is the only camera   *
*  that puts him at world mk1t_sh_x in all six.			     *
*											     *
**************************************************************************
	.bss	mk1t_sh_obj,32*mk1t_sh_slots,1	; the upper-body objects, front to back
	.bss	mk1t_sh_shown,32,1		; the pose record list on screen now

mk1t_sh_snd	.set	068h		; triple_sndtab2: throne room applause

mk1t_shang
	movi	mk1t_sh_slots+1,a0
	calla	objs_available
	jrnc	mk1t_sh_die		; not enough left - an empty throne beats
					; half a man

	clr	a0
	move	a0,@mk1t_sh_shown,l
	movi	mk1t_sh_obj,a1
	movi	mk1t_sh_slots,a2
mk1t_sh_zero
	move	a0,*a1+,l
	dsj	a2,mk1t_sh_zero

*
* The lap first, at the back, and it is never touched again.  Then the four
* upper-body slots, z rising toward the front: insobj_v keeps a list sorted on
* ozpos and the walker draws it in order.
*
	movi	mk1t_sh_lapr,a10
	move	*a10,a5,l
	clr	a2
	callr	mk1t_sh_piece

	movi	mk1t_sh_obj,a10
	movk	1,a11			; z 1..mk1t_sh_slots
mk1t_sh_build
	move	*a10,a5,l		; seed only - the first pose sets the art
	movi	mk1t_sh_lapr,a5
	move	*a5,a5,l
	move	a11,a2
	callr	mk1t_sh_piece
	move	a8,*a10+,l
	addk	1,a11
	cmpi	mk1t_sh_slots+1,a11
	jrlt	mk1t_sh_build

mk1t_sh_tick
	callr	mk1t_sh_watch		; a1 = the pose this camera asks for
	callr	mk1t_sh_show
	sleep	mk1t_sh_rate
	move	@winner_status,a0,w	; 1/2 = a player won, 3 = FINISH HIM
	jrz	mk1t_sh_tick		; nobody yet (or a DRAW, which leaves it 0)
	cmpi	2,a0
	jrhi	mk1t_sh_noclap		; FINISH HIM (or a soul sequence) - no clap

*
* ONLY A PLAIN WIN IS APPLAUDED: not a draw, and not a round that goes to
* FINISH HIM.  results_of_round writes 1/2 and finish_him_sequence overwrites
* it with 3 in the same slice, but the test is made again after the wait in
* case anything ever sleeps between the two.  Once 3 has been seen he never
* claps this round - play4 writes 1/2 back AFTER the finisher.
*
* A round has been decided.  MK1 waits, then applauds - and it applauds ONCE:
* the lane loops for ever in the data and MK1's round teardown is what ends it,
* so the frame count is taken from the measurement instead.  Afterwards his
* arms go back on the chair and he watches the camera again (MK1 leaves him on
* the last clap frame; that read as frozen), and the stage's calla builds him
* again for the next round.
*
	sleep	mk1t_sh_cwait		; MK1 waits before the first clap
	move	@winner_status,a0,w
	subk	1,a0
	cmpi	1,a0
	jrhi	mk1t_sh_noclap		; no longer a plain 1/2 win - no clap
	movi	mk1t_sh_snd,a0		; the crowd applauds with him - MK1's own
	calla	triple_sound2_ch3	; clap, once (stlaugh_patch.txt note (56)),
					; on the channel a busy round steals last
	movi	mk1t_sh_cframes,a11
	movi	mk1t_sh_clap,a10
mk1t_sh_clapf
	move	a10,a1
	callr	mk1t_sh_show
	sleep	mk1t_sh_crate
	addi	32*mk1t_sh_slots,a10	; -> the lane's next step
	movi	mk1t_sh_clap+(32*mk1t_sh_slots*mk1t_sh_cn),a0
	cmp	a0,a10
	jrlo	mk1t_sh_clapw
	movi	mk1t_sh_clap,a10	; MK1's lane loops back to its own start
mk1t_sh_clapw
	dsj	a11,mk1t_sh_clapf

*
* MK1 leaves him frozen on the last clap frame, hands together, until the
* round tears down.  Here he puts his arms back on the chair and goes on
* watching the camera instead - and never claps again this round.
*
	jruc	mk1t_sh_noclap

*
* A round that goes to FINISH HIM - or one whose clap is over: he goes on
* watching the camera, as he does
* through the fight, and does not applaud - not even when the finisher is over
* and the winner is declared.
*
mk1t_sh_noclap
	callr	mk1t_sh_watch
	callr	mk1t_sh_show
	sleep	mk1t_sh_rate
	jruc	mk1t_sh_noclap

mk1t_sh_die
	die

**************************************************************************
*											     *
*  mk1t_chair - THE THRONE, EMPTY, because Shang Tsung is in the fight.     *
*											     *
*  The throne is plane 5's background and he only ever covered the middle  *
*  of it, so this is a PATCH, not a chair: the pixels of MKBGANI.IMG's	     *
*  thrnchair that lie under one of his pieces and differ from what is	     *
*  drawn behind him, in mk1t_chair_n strips (no free run holds it whole).   *
*  Plane 5 scrolls at plane 4's rate, so the strips ride his list and are   *
*  laid by his own mk1t_sh_piece: each strip's anipoint is cut so that his  *
*  anchor minus it is the strip's top-left.  Built once, never touched -    *
*  the process only builds them.  tools/make_thrnchair.py has the rest.     *
*											     *
**************************************************************************
mk1t_chair
	movi	mk1t_chair_n+1,a0
	calla	objs_available
	jrnc	mk1t_sh_die		; not enough left - MK1's throne, as is,
					; beats half a patch
	movi	mk1t_chair_recs,a10
	movk	1,a11			; z 1..mk1t_chair_n
mk1t_ch_next
	move	*a10+,a5,l
	jrz	mk1t_sh_die		; 0 ends the list - built, done
	move	a11,a2
	callr	mk1t_sh_piece		; keeps a10/a11
	addk	1,a11
	jruc	mk1t_ch_next

*
* mk1t_sh_watch - a1 = the pose record list plane 1's camera asks for.
* MK1: bucket = |mk1t_sh_mid - camera| / mk1t_sh_step, clamped to mk1t_sh_maxb;
* camera <= mk1t_sh_flat takes bucket 3 outright.  The divide is repeated
* subtraction - it runs at most mk1t_sh_maxb times, and `modu` appears nowhere
* in this tree.
*
mk1t_sh_watch
	mmtm	sp,a0,a2
	move	@worldtlx+16,a0,w	; plane 1's camera x, the integer half
	sext	a0,w
	cmpi	mk1t_sh_flat,a0
	jrle	mk1t_sh_neutral
	movi	mk1t_sh_mid,a1
	sub	a0,a1
	abs	a1
	clr	a2
mk1t_sh_div
	cmpi	mk1t_sh_step,a1
	jrlt	mk1t_sh_got
	subi	mk1t_sh_step,a1
	addk	1,a2
	cmpi	mk1t_sh_maxb,a2
	jrlt	mk1t_sh_div
	jruc	mk1t_sh_got
mk1t_sh_neutral
	movk	3,a2			; MK1's JRLS branch lands on FFD6ED40,
					; which is the bucket table's entry 3
mk1t_sh_got
	movi	32*mk1t_sh_slots,a1	; one pose is that many bits of table
	mpyu	a1,a2			; -> a3 (mpyu leaves the low half in a3)
	movi	mk1t_sh_track,a1
	add	a3,a1
	mmfm	sp,a0,a2
	rets

*
* mk1t_sh_show - put the pose whose record list is at a1 on the four slots.
* Does nothing if it is already up, so a still camera costs one compare.
*
mk1t_sh_show
	mmtm	sp,a0,a1,a2,a3,a4,a5,a8,a9,a10,a11
	move	@mk1t_sh_shown,a0,l
	cmp	a0,a1
	jreq	mk1t_sh_shown_ok
	move	a1,@mk1t_sh_shown,l
	move	a1,a9			; a9 -> the pose's records
	movi	mk1t_sh_obj,a10
	movi	mk1t_sh_slots,a11
mk1t_sh_slot
	move	*a10+,a8,l		; the slot's object
	jrz	mk1t_sh_next
	move	*a9,a1,l		; its record for this pose
	mmtm	sp,a9,a10,a11
	calla	ani_flag		; swap the art, palette and flip kept
	mmfm	sp,a9,a10,a11
	move	*a8(oimg),a5,l		; re-place: the clap's pieces do NOT
	move	*a5(ianioff),a3,l	;   share one anipoint per slot
	movi	mk1t_sh_x,a0
	movi	mk1t_sh_y,a1
	move	a3,a4
	sll	16,a4
	sra	16,a4			; a4 = anix, sign extended
	sra	16,a3			; a3 = aniy
	sub	a4,a0
	sub	a3,a1
	move	a0,*a8(oxpos),w
	move	a1,*a8(oypos),w
mk1t_sh_next
	addi	32,a9
	dsj	a11,mk1t_sh_slot
mk1t_sh_shown_ok
	mmfm	sp,a0,a1,a2,a3,a4,a5,a8,a9,a10,a11
	rets

*
* mk1t_sh_piece - build one object.  a5 = its record, a2 = its z.  The anchor
* is mk1t_sh_x / mk1t_sh_y for every piece and each subtracts its OWN anipoint,
* which is how MK1 lays them out.  Returns a8.
*
mk1t_sh_piece
	mmtm	sp,a0,a1,a2,a3,a4,a5,a6,a7,a9,a10,a11
	mmtm	sp,a2
	calla	gso_dmawnz
	mmfm	sp,a2
	move	*a8(oimg),a5,l		; re-read: nothing promises gso kept a5
	move	*a5(ianioff),a3,l	; a3 = y:x anipoint
	movi	mk1t_sh_x,a0
	movi	mk1t_sh_y,a1
	move	a3,a4
	sll	16,a4
	sra	16,a4			; a4 = anix, sign extended
	sra	16,a3			; a3 = aniy
	sub	a4,a0
	sub	a3,a1
	move	a0,*a8(oxpos),w
	move	a1,*a8(oypos),w
	move	a2,*a8(ozpos),w
	clr	a0
	move	a0,*a8(oxvel),l		; dclipl adds these every frame for every
	move	a0,*a8(oyvel),l		; object - he must not drift
	movi	mk1p_sky_lst,b4		; insobj_v only READS b4
	move	a8,a0
	calla	insobj_v
	mmfm	sp,a0,a1,a2,a3,a4,a5,a6,a7,a9,a10,a11
	rets
