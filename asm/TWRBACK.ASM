*************************************************************************
*                                                                       *
*  tower_backdrop_reflections - the wall, the arch and the sky          *
*                                                                       *
*  Everything that stands on the marble already reflects (guards,       *
*  pillars).  This is the one thing left: the BACKDROP - the wall with  *
*  its great arch, and through the arch the clouds cloud_proc drifts    *
*  and the floating monk - mirrored into the back of the floor, squashed*
*  down to the carpet, at 76% - Midway's own SHADE brightness.  No      *
*  object here is the stage's own art drawn again with m_flipv and a     *
*  reduced oscale.                                                      *
*                                                                       *
*  Three lists, one scroll rate.  tower_scroll gives planes 5, 6, 7 and *
*  8 all 014000h and they share an origin (the probe logs x5 = x6 = x7 =*
*  x8), so the monk, the wall and both cloud rows reflect on private     *
*  lists all drawn at worldtlx6.  Order in dlists_tower is the real      *
*  order mirrored onto the floor: sky, then wall over it (so the sky     *
*  only shows through the arch and the windows, exactly as it does      *
*  above), then the monk, who is drawn in front of the wall above.      *
*                                                                       *
*  THE WALL is static, so all of its placement is done at BUILD time by *
*  tools/tower3_backdrop_reflect.py into twr_bkwall_tbl (TWRBKREF.ASM): *
*  one record per PLANE5BLKS block with its own ystep.  That is the     *
*  whole trick against seams - the DMA sizes each blit from its own     *
*  source height and CEILS a reduction (measured,                       *
*  tools/tower_scale_rounding_probe.lua), so blocks stacked 4-5 high    *
*  at one shared 1/6 step open 1-row marble cracks.  Per-block steps    *
*  make each block land on exactly the rows between its neighbours; the *
*  generator verifies that column by column.  The block's SAG, size and *
*  control word are still read out of R2HDRS at runtime, as the pillars *
*  do, so a re-cut moves the art without anyone retyping it.            *
*                                                                       *
*  All 73 are built once and never culled: this is a private list, so  *
*  bgnd_ud1 never walks it, and the display loop skips an off-screen    *
*  object before it costs a DMA.  268 of 358 objects are free on this   *
*  stage (measured), so the ~83 here fit with room.                      *
*                                                                       *
*  THE SKY MOVES, so backdrop_follow pairs one reflection with every    *
*  object on baklst8, baklst7 and baklst5 once they exist, and every    *
*  tick copies each source's sag, size, clip offset (the clouds are     *
*  clipped to the arch's window by clip_a_row), flags and x, and works  *
*  out the mirrored y through twr_dmap/twr_drawn - nothing divides.     *
*  Pairing is by position in the list: nothing here ever relinks those  *
*  lists after they are built, and the reflections are inserted with    *
*  ozval = creation order so their own list keeps the same sequence.    *
*                                                                       *
*  THE CARPET RUNNER.  The hardware cannot skip pixels, so the wall's    *
*  reflection lands on the red runner that leads up to the arch - and   *
*  the runner is locked under the arch, because floor_code scrolls on   *
*  scrollx6, the wall's own rate.  twr_runner_code redraws exactly the  *
*  runner's span on each line of the band, over the reflection, with    *
*  floor_code's own per-line skew.  See it for the maths.               *
*                                                                       *
*************************************************************************

; twr_skybg_lst, twr_bsky_lst, twr_bwall_lst, twr_bmonk_lst: the heads live
; in RAM.ASM's list block, so grab_screen's GAME OVER freeze clears them
; with every other list.  Declared here they outlived it, still chained
; through freed objects, and got drawn over the game-over screen.
	.global	twr_bsky_lst,twr_bwall_lst,twr_bmonk_lst,twr_skybg_lst
	.global	twr_cld7_lst,twr_cld8_lst	; cloud_proc's rows (RAM.ASM) - baklst7/8 are guard planes now
	.bss	twr_skybg_obj,32,1	; the sky quad, for backdrop_follow to pin.
					;   Not a list head, so it needs no place in
					;   RAM.ASM's block: nothing but the follower
					;   reads it, and the follower dies with the stage.

tower_backdrop_reflections
	mmtm	sp,a10,a11
;
;  Do not draw the marble this covers.  The band is floor texture rows
;  0..TWR_BKR-1 (screen 181..234), and every column of it is repainted
;  opaquely every frame - wall reflection blocks where the wall is solid,
;  the sky backing where it is not.  floor_code was drawing all 54 rows
;  underneath for nothing: 54 of the object queue's 500 cells and about
;  21,600 pixels a frame, on the stage that had the least of both to spare.
;
;  It is set HERE, not in calla_tower, for two reasons: TWR_BKR is an
;  assembly-time constant of this object, and this is the routine whose
;  coverage makes the skip safe.  If the reflection ever stops covering the
;  full band, this has to go with it or the bare autoerase colour shows
;  through the floor.  setup_floor_info clears it for every stage first.
;
;  A pure saving with no visual change - and that is testable: the frame
;  should come out pixel-identical.
;
	movi	TWR_BKR,a10
	move	a10,@skew_skip,w

;
;  THE SKY BACKING IS BACK ON (2026-09-17).  It was switched off when
;  skew_skip stopped floor_code drawing under the band, because the holes in
;  the reflected wall then showed the hardware autoerase colour - which on
;  this stage IS the sky, tower_mod's first word, 1D2CH - so the mirrored
;  windows looked right for free and it bought back 1.1-1.7 ms.
;
;  What that missed: the autoerase sky is the UNDIMMED one.  Every hole in
;  the reflection came out at full brightness against a dimmed mirror - not
;  just the arch window, but the single transparent pixels along the arch's
;  curve, which read as bright specks scattered over the floor.  Measured on
;  one frame: ~1,700 autoerase pixels inside the band, in runs of 1 to 40.
;  With the backing the same pixels are the DIMMED sky - which is how it
;  shipped before, and why nobody saw specks then.
;
;  It also carries the flattened palette now (REFL_FLAT in the generator), so
;  the reflected sky is the calmest thing in the band rather than the
;  brightest.  Cost is back: two on-screen 256x54 tiles, ~27,600 pixels,
;  ~1.1 ms of the 18.28 ms frame, which the two-blit shadow path pays for.
;
	callr	make_sky_backing	; the sky first - it sits behind the wall
	movi	twr_bkwall_tbl,a11
	movi	TWR_BKN,a10
tbr_lp	callr	make_wall_reflection
	addi	TWR_BKREC,a11
	dsj	a10,tbr_lp
	mmfm	sp,a10,a11
	rets				; backdrop_follow is created at the top of
					;   calla_tower - see the note there

**************************************************************************
*                                                                        *
*  make_sky_backing - the sky, behind the reflected wall                 *
*                                                                        *
*  THE TOWER's wall is not a solid slab.  Nearly a fifth of PLANE5 is    *
*  index 0, and every one of those pixels is somewhere the autoerase     *
*  colour shows through: the big central arch, the row of small window   *
*  panels along the top, and the tall slits either side of it.  The      *
*  reflection is built out of the wall's own blocks, so all of that came *
*  out as bare flagstone - the mirrored windows had the FLOOR behind     *
*  them, and the reflected clouds drifted across stone.                  *
*                                                                        *
*  This is one rectangle the size of the whole reflected band, on a list *
*  of its own so dlists_tower can put it behind the reflected clouds as  *
*  well as the wall.  Covering the whole band is safe, and the reason is *
*  worth stating: every pixel of the module is either transparent -      *
*  where the sky belongs - or opaque, and every opaque pixel's           *
*  reflection is drawn ON TOP of this.  The generator's check_tiling     *
*  proves the per-block reflections tile every column exactly, so no     *
*  opaque source row loses its reflected row.  It can only ever be seen  *
*  where the wall itself lets the sky through.                           *
*                                                                        *
*  NO ART AND NO PALETTE OF ITS OWN.  The DMA's write-mode nibble can    *
*  replace both zero and non-zero data with the constant colour          *
*  (dmacal), and that constant is an index into the object's OWN colour  *
*  map - see the note over the hit pop in MKDISP.ASM.  So the source can *
*  be anything at all: it reads the floor's own texture, which is        *
*  already set up in @skew_sag, and wears the dimmed CLOUD palette,      *
*  which already carries the dimmed sky (the clouds are drawn against    *
*  the sky, so the autoerase colour is one of their pens).               *
*                                                                        *
*  IT IS TILED, and that is not tidiness.  The band is the wall's full   *
*  1120px width, and ONE object that wide draws nothing whatsoever: the  *
*  DMA's destination x-size field is narrower than the 16 bits the       *
*  object carries, so 1120 arrives as 1120 & 511 = 96, and 96 pixels at  *
*  the band's left edge are off the left of the screen at every camera   *
*  position this stage allows.  It looks exactly like the object never   *
*  being queued - it was alive on its list, size 1120x54, with not one   *
*  pixel of it on screen.  256 is well inside the field.                 *
*                                                                        *
*  It never moves: it is fixed in the wall's plane, and dlists_tower     *
*  draws the list at worldtlx6 like the rest of the reflection, so the   *
*  camera carries it along with the wall.  Nothing has to follow it.     *
*                                                                        *
**************************************************************************
make_sky_backing
	mmtm	sp,a0,a1,a4,a8
	clr	a0
	move	a0,@twr_skybg_obj,l	; no quad until one is built
	calla	getobj
	jreq	msb_out		; pool exhausted - decoration, just skip
	move	a0,a8

	move	@skew_sag,a0,l	; any source at all - every pixel of it is
	move	a0,*a8(osag),l	;   replaced by the constant.  416x54 at
				;   6bpp is 134,784 bits into the floor's
				;   540,000, so the read stays inside the art
	movi	(TWR_SKYH*010000h)+TWR_SKYW,a0
	move	a0,*a8(osize),l	; [ysize:xsize]
	movi	TWR_SKYCTL,a0
	move	a0,*a8(oflags),w
	movi	TWR_SKYPEN,a0
	move	a0,*a8(oconst),w	; the pen, in both bytes of the word

	clr	a0
	move	a0,*a8(oflags2),l
	move	a0,*a8(oimg),l
	move	a0,*a8(ofset),w
	move	a0,*a8(oxvel),l
	move	a0,*a8(oyvel),l
	move	a0,*a8(ozval),l
	movi	001000100h,a0	; 1:1
	move	a0,*a8(oscale),l

	movi	NEWCLD_R,a0
	calla	getfpal
	jreq	msb_np
	move	a0,*a8(opal),w
msb_np	move	@worldtlx6+16,a4,w	; the camera's left edge, plane 6
	subk	TWR_SKYM,a4		;   less the margin
	zext	a4,w
	addi	TWR_SKYY*010000h,a4	; a4 = [y:x]
	calla	set_xy_coordinates	; a8, a4
	move	a8,a0
	movi	twr_skybg_lst,b4
	calla	insobj_v
	move	a8,@twr_skybg_obj,l	; backdrop_follow keeps it on the camera
msb_out	mmfm	sp,a0,a1,a4,a8
	rets

*
*  a11 = one twr_bkwall_tbl record (TWRBKREF.ASM):
*     +0   .long  dimmed palette
*     +32  .long  oscale [ystep:0100h] - this block's own step
*     +64  .long  ozval  - z in the high byte, the real draw order below it
*     +96  .word  R2HDRS index
*     +112 .word  oflags bits: transparency (2/3) | h-flip | inverted v-flip
*     +128 .word  plane x
*     +144 .word  the y to hand the engine (clip6's flip anchor already in)
*
make_wall_reflection
	mmtm	sp,a0,a1,a2,a3,a4,a5,a6,a7,a8,a9,a10,a11
	calla	getobj
	jreq	mwr_out			; pool exhausted - decoration, just skip
	move	a0,a8

	move	*a11(96),a1,w		; R2HDRS index -> * 80 bits, by shifts
	zext	a1,w
	sll	4,a1			; *16
	move	a1,a2
	sll	2,a2			; *64
	add	a2,a1			; *80
	addi	R2HDRS,a1
	move	*a1,a9,l		; [ysize:xsize] is already osize's layout
	move	a9,*a8(osize),l
	move	*a1(32),a0,l
	move	a0,*a8(osag),l		; raw: bkgsagof never adjusts a block's sag
	move	*a1(64),a0,w		; the block's own control word
	ori	dmago,a0
	move	*a11(112),a2,w
	or	a2,a0
	move	a0,*a8(oflags),w

	clr	a0
	move	a0,*a8(oflags2),l
	move	a0,*a8(oimg),l
	move	a0,*a8(ofset),w
	move	a0,*a8(oxvel),l
	move	a0,*a8(oyvel),l
	move	*a11(64),a0,l
	move	a0,*a8(ozval),l
	move	*a11(32),a0,l
	move	a0,*a8(oscale),l

	move	*a11,a0,l
	calla	getfpal
	jreq	mwr_np
	move	a0,*a8(opal),w
mwr_np
	move	*a11(144),a4,w		; engine y
	sll	16,a4
	move	*a11(128),a0,w		; plane x
	zext	a0,w
	movx	a0,a4			; a4 = [y:x]
	calla	set_xy_coordinates	; a8, a4
	move	a8,a0
	movi	twr_bwall_lst,b4
	calla	insobj_v
mwr_out	mmfm	sp,a0,a1,a2,a3,a4,a5,a6,a7,a8,a9,a10,a11
	rets


*
*  backdrop_follow - one pid_bani, for the life of the stage.
*
*  Only a7-a12 survive a sleep, so nothing is carried across one: every
*  tick starts again from the list heads.
*
backdrop_follow
bf_wait	sleep	1
	move	@twr_cld8_lst,a0,l		; cloud_proc builds both rows in its first
	jreq	bf_wait			;   pass, monk_proc both pieces in its first
	move	@twr_cld7_lst,a0,l
	jreq	bf_wait
	move	@baklst5,a0,l
	jreq	bf_wait
	sleep	1			; one more, so both monk pieces are down

	clr	a10			; ozval = creation order
	movi	NEWCLD_R,a3
	movi	twr_bsky_lst,a11
	move	@twr_cld8_lst,a2,l		; row 8 first - dlists_tower draws it first
bf_m8	callr	bf_make
	inc	a10
	move	*a2,a2,l
	jrne	bf_m8
	move	@twr_cld7_lst,a2,l
bf_m7	callr	bf_make
	inc	a10
	move	*a2,a2,l
	jrne	bf_m7
	movi	MONK_R,a3
	movi	twr_bmonk_lst,a11
	move	@baklst5,a2,l
bf_m5	callr	bf_make
	inc	a10
	move	*a2,a2,l
	jrne	bf_m5

bf_tick	sleep	1
*
*  The sky quad is ONE screen-wide object, not tiles across the whole wall:
*  static tiles put 2-3 of them on screen and the DMA billed all 512-768
*  px of their width.  Keeping it on the camera is this tick's first job.
*  TWR_SKYM px of margin each side absorb the tick this runs behind the
*  scroller - plane 6 moves at 0.625x, so ~6 px a tick at the ceiling.
*
	move	@twr_skybg_obj,a8,l
	jreq	bf_nosky
	move	@worldtlx6,a0,l	; 16.16, the integer in the high word
	subi	TWR_SKYM*010000h,a0
	move	a0,*a8(oxval),l	; oxval, not oxpos - oxpos is derived
bf_nosky
	move	@twr_bsky_lst,a11,l
	move	@twr_cld8_lst,a9,l
	callr	bf_run
	move	@twr_cld7_lst,a9,l		; a11 carries on down the sky list
	callr	bf_run
	move	@twr_bmonk_lst,a11,l
	move	@baklst5,a9,l
	callr	bf_run
	jruc	bf_tick

*  walk sources (a9) and reflections (a11) together until either runs out
bf_run	move	a9,a9
	jreq	bfr_x
	move	a11,a11
	jreq	bfr_x
	callr	bf_sync
	move	*a9,a9,l
	move	*a11,a11,l
	jruc	bf_run
bfr_x	rets

*
*  a9 = source, a11 = its reflection.  Clobbers a0-a2.
*
*  Mirrored y, the same half-open rule the generator uses for the wall, with
*  the flip anchor put back:
*     D_lo = TWR_BKBASE - y0 - h          depth of the source's bottom row
*     top  = TWR_BKBASE + dmap(D_lo)      floor(D*TWR_BKR/TWR_BKDMAX)
*     y    = top - h + drawn(h)           clip6 adds ysize-1; the DMA ceils
*  Both are tables in TWRBKREF.ASM (twr_dmap, twr_drawn): nothing divides.
*
bf_sync
	move	*a9(osag),*a11(osag),l
	move	*a9(osize),*a11(osize),l
	move	*a9(ofset),*a11(ofset),w	; the clouds' arch-window clip
	move	*a9(oflags),a0,w
	xori	m_flipv,a0
	move	a0,*a11(oflags),w
	move	*a9(oxval),*a11(oxval),l

	move	*a9(osizey),a1,w
	zext	a1,w			; h
	move	*a9(oypos),a2,w
	sext	a2,w			; y0
	cmpi	01000h,a2		; clip_a_row parks a cloud that has left the
	jrlt	bfs_live		;   arch window by adding 4000h to its y
	move	*a9(oyval),*a11(oyval),l	; (left_edge_clip, cld7). Park the
	rets				;   reflection the same way: pinning it to the
bfs_live				;   line drew a cloud the game had hidden
	movi	TWR_BKBASE,a0
	sub	a2,a0
	sub	a1,a0			; a0 = D_lo
	jrnn	bfs_d
	clr	a0			; dips below the line: pin it to the line
bfs_d	cmpi	TWR_MAPN-1,a0
	jrls	bfs_d2
	movi	TWR_MAPN-1,a0
bfs_d2	sll	4,a0
	addi	twr_dmap,a0
	move	*a0,a0,w		; the reflected row for depth D_lo
	addi	TWR_BKBASE,a0		; top
	sub	a1,a0			; - h
	cmpi	TWR_MAPN-1,a1		; h never gets near this, but it IS a table
	jrls	bfs_h			;   index
	movi	TWR_MAPN-1,a1
bfs_h	sll	4,a1
	addi	twr_drawn,a1
	move	*a1,a1,w		; rows the DMA draws of h at TWR_BKSTEP (it ceils)
	add	a1,a0			; the y to hand the engine
	sll	16,a0
	move	a0,*a11(oyval),l
	rets

*
*  a2 = source, a3 = dimmed palette, a10 = ozval, a11 = the list to go on.
*
bf_make
	mmtm	sp,a0,a1,a2,a3,a4,a5,a6,a7,a8,a9,a10,a11
	calla	getobj
	jreq	bfm_out
	move	a0,a8
	clr	a0
	move	a0,*a8(oflags2),l
	move	a0,*a8(oimg),l
	move	a0,*a8(oxvel),l
	move	a0,*a8(oyvel),l
	move	a10,*a8(ozval),l
	movi	TWR_BKSTEP,a0
	move	a0,*a8(oscale),l
	move	a3,a0
	calla	getfpal
	jreq	bfm_np
	move	a0,*a8(opal),w
bfm_np	move	a11,a4			; the list, before a11 becomes the object
	move	a2,a9
	move	a8,a11
	callr	bf_sync			; lay this tick's fields down first -
	move	a4,b4			;   insobj_v sorts on ozval, then oyval
	move	a8,a0
	calla	insobj_v
bfm_out	mmfm	sp,a0,a1,a2,a3,a4,a5,a6,a7,a8,a9,a10,a11
	rets


*************************************************************************
*                                                                       *
*  twr_runner_code - put the carpet runner back over the reflection     *
*                                                                       *
*  Called from dlists_tower as `.long -1,twr_runner_code`, the way      *
*  floor_code is, with floor_code's register contract: a1 is the live   *
*  DMA queue (cells are pushed onto it, never touched otherwise), a3 the*
*  list walker and a14 scrntl (both saved), a5 the page, b13 the count. *
*                                                                       *
*  One DMA per floor line from TWR_RUNL0 to TWR_RUNL1 - just the rows   *
*  the reflection band covers - each exactly twr_runner_tbl's span of   *
*  that texture row, from the floor's own texture, in the floor's own   *
*  const:pal and control.  The maths is floor_code's:                   *
*                                                                       *
*    screen y of texture row L = skew_y + (ceiling_y - worldtly) + L    *
*    skew on line L            = skew_oc + L * skew_dx   (16.16)        *
*    screen x of column c      = c - TWR_FLOORW + int(skew)             *
*    source of column c, row L = skew_sag - TWR_FLOORW*6                *
*                                + L*TWR_FLOORX*6 + c*6    (6bpp)       *
*                                                                       *
*  skew_oc and skew_dx are read AFTER floor_code has updated them this  *
*  frame, which is why this entry sits later in the list.  A span that  *
*  leaves the screen is clipped here, in software, the way the floor    *
*  never needs to be: every floor line is exactly the screen's width.   *
*                                                                       *
*************************************************************************
twr_runner_code
	move	@f_skew,a2,w
	jreq	trc_ret
	mmtm	sp,a3,a4,a14		; a4 too: the display walker's world top-left y:x for
					;   every list after this one (MKDISP disp3 only swaps the
					;   x).  Not saved, it left THE TOWER's front half - pillars,
					;   guards, monk, shadows, fighters - drawn at a junk y of 0
					;   instead of worldtly: 14px high, and deaf to the shake

	move	@worldtly+16,a0,w
	sext	a0,w
	move	@ceiling_y,a4,w
	sext	a4,w
	sub	a0,a4			; lines the camera has climbed
	move	@skew_y,a0,w
