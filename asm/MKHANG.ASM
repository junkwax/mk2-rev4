	move	a9,*a13(p_store1),w	; stable slot id for long drop/simmer path

	; --- body or already-dropped acid skeleton ---
	pullp	a9
	pushp	a9
	callr	hp_dropped_slot
	move	*a1,a0,w
	jrz	hp_spawn_human_body
	callr	hp_drop_eligible_slot
	move	*a1,a0,w
	jrz	hp_spawn_human_body	; defensive: Eric is never acid-swapped
	callr	hp_index_a1
	sll	5,a1
	addi	hanger_skel_full,a1
	move	*a1,a5,l
	movi	hp_skel_mpart,a6
	movk	1,a0
	callr	hp_skel_visible_slot
	move	a0,*a1,w
	jruc	hp_get_mpart_body

hp_spawn_human_body
