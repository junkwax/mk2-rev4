* a8  = body sprite (EDHANG1, etc.)                                     *
* a10 = longchain sprite                                                 *
* a11 = TINHOOK sprite                                                   *
* TINCHAIN4 connector -> hp_conn_ptr[index]  (a12 is the PROCESS STACK)  *
* Body ptr also saved to hp_body_ptr[a9] for recovery in drop sequence. *
*                                                                        *
**************************************************************************
hanger_proc
*
* Spawn body, longchain (a10), TINHOOK (a11), TINCHAIN4 (hp_conn_ptr).
* Body ptr saved to hp_body_ptr[index] for recovery in drop sequence.
*
