*
* hp_cut_shape_to_surface - show exactly the part of a8 that is above the acid.
*
* BOTH DIRECTIONS USE THIS.  Going down the body is eaten from the bottom as it
* sinks; coming up the skeleton is revealed from the top as it is pulled out.
* That is the same picture - "draw the rows above the waterline" - so it is the
* same code, and the reveal is as smooth as the sink instead of arriving in six
* lumps off a hand-authored table.
*
* In:  a8 = multipart object, a9 = its top Y.  Out: a1 = visible band count.
* Clobbers a0, a1, a2, a4, a5.  a9 preserved.
*
hp_cut_shape_to_surface
	mmtm	sp,a9
	move	*a8(oshape),a0,l	; restore full strip table before recutting
	calla	ani2
	mmfm	sp,a9

*
* MEASURED OFF THE PIECES, not off a band height.  This used to divide the
* rows above the surface by strip_step (20) and trust every band to be that
* tall, which is true of Ed and of nobody else: Tony is THREE 40px bands, so
* the count came out at six, the seek ran off the end of his list and the
* clip wrote a height into whatever followed it in the shape RAM.  A piece
* already carries its own dy and its own height, so the list is walked: each
* piece's top is oypos - dy, and it draws the rows of itself that are still
* above the waterline.
*
*
* EVERY PIECE ON ITS OWN.  Ed and Tony are cut into bands stacked top to
* bottom, and this used to stop the list at the first band the surface was
* crossing - nothing under it could be dry.  John is cut the other way: A is
* his left side, full height, and B his right side from row 17 down.  Both
* are crossing the surface at once, and stopping at A dropped his whole right
* side the tick his feet went in.  So each piece is cut by itself, any piece
* wholly under is taken out of the list (the rest close up behind it), and
* the list ends after the last piece still showing.  Stacked bands come out
* exactly as before.
*
	mmtm	sp,a6,a7
	move	*a8(oimg),a2,l		; reading the shape RAM ani2 just rebuilt
	move	a2,a6			; ...and writing the pieces that show
	clr	a3			; pieces still showing
	clr	a7			; breach marked this pass (once, or 1 -> 2)
	movi	acid_lower_mask_y,a4	; the surface

hp_lss_lp
	move	*a2,a0,l		; sag 0 ends the list
	jrz	hp_lss_end
	move	a4,a5
	sub	a9,a5			; rows of HIM above the surface
	move	*a2(mp_aniy),a0,w	; this piece sits oypos - dy down the body...
	add	a0,a5			; ...so this many of its own rows are above
	jrle	hp_lss_next		; wholly under: not copied, so it is gone
	move	*a2(mp_sizey),a0,w	; its full height, as ani2 just rebuilt it
*
* NEVER write a height LARGER than the art: the DMA would read past the frame
* and spray whatever follows it in the image ROM across the screen.  Ed's
* band F is 12 rows where the others are 20, so the compare is against the
* piece, never against a nominal band.
*
	cmp	a0,a5
	jrge	hp_lss_keep
	move	a5,*a2(mp_sizey),w	; the surface is cutting through this one
	move	a7,a7
	jrnz	hp_lss_keep
	movk	1,a7
	callr	hp_lss_mark_breach	; clobbers a0/a1 only
hp_lss_keep
	cmp	a2,a6
	jreq	hp_lss_kept		; nothing dropped yet: already in place
	move	*a2,a0,l		; close up behind a dropped piece
	move	a0,*a6,l
	move	*a2(32),a0,l
	move	a0,*a6(32),l
	move	*a2(64),a0,l
	move	a0,*a6(64),l
	move	*a2(96),a0,w
	move	a0,*a6(96),w
hp_lss_kept
	addi	mpart_entry_bits,a6
	inc	a3
hp_lss_next
