	callr	hp_fx_center_a11
	addi	bubble_x_nudge,a11	; the ring stays under the bubbles
	create	pid_green_splash,ripple_proc
hp_lob_done
	callr	hp_hook_hold_slot
	move	*a1,a11,l		; restore caller a11
	mmfm	sp,a9
	rets


