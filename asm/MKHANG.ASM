*
* OUT OF STEP.  Every bubble used to hold every frame for the same ticks - the
* six EDACID lanes all slept ed_fx_frame_ticks (5) and were all created on the
* same tick by hp_start_acid_boil, and every lowering bubble ran framew at 4 -
* so the whole pool popped in lockstep, one boil wearing six hats.
*
* Now each hold comes off a short table walked by ONE shared counter.  The six
* lanes call it in turn, so on any frame each lane draws a different entry, and
* the entry a lane gets next time depends on what everyone else did - they
* drift apart from their very first sleep and never line back up.  The tables
* average the old values (5 and 4), so the lanes keep their authored tempo and
* the rows that encode holds still hold about as long.
*
* Deliberately NOT randu: that draws from @rand, the game's own RNG, and every
* extra call would shift the AI's rolls for the rest of the round.
*
* Out: a0 = ticks.  Clobbers a0 only.
*
*
* hp_lane_splish - a0 = the EDACID lane frame about to be drawn.  BUBL4 is a
* bubble popping, pooldrip1 is a drip's ring as it lands.  Clobbers a0.
*
hp_lane_splish
	mmtm	sp,a1
	movi	BUBL4,a1
	cmp	a1,a0
	jreq	hls_play
	movi	pooldrip1,a1
	cmp	a1,a0
	jrne	hls_out
hls_play
	movi	snd_acid_pop,a0
	callr	hp_acid_pop
hls_out
	mmfm	sp,a1
	rets

*
* hp_acid_pop - a0 = a triple_sndtab index (snd_acid_pop).  Played unless
* another pop went out in the last acid_pop_gap ticks, or the round is decided.
* Clobbers a0 (triple_sound saves a0-a3; a1/a2 are saved here).
*
hp_acid_pop
	mmtm	sp,a1,a2
	move	@tick,a1,w
	move	@hp_splish_tick,a2,w
	sub	a2,a1
	jrn	hsk_play		; @tick restarted with the round
	cmpi	acid_pop_gap,a1
	jrlt	hsk_out
hsk_play
	move	@winner_status,a2,w
	jrnz	hsk_out			; decided: leave it to the announcer
	move	@tick,a1,w
	move	a1,@hp_splish_tick,w
	calla	triple_sound
hsk_out
	mmfm	sp,a1,a2
	rets

*
* hp_acid_sound - a0 = a triple_sndtab index.  triple_sound, unless the round
* is decided (see THE POOL'S OWN SOUNDS).  Saves everything but a0.
*
hp_acid_sound
	mmtm	sp,a1
	move	@winner_status,a1,w
	jrnz	has_out
	calla	triple_sound
has_out
	mmfm	sp,a1
	rets

