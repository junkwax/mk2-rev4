**************************************************************************
*                                                                        *
* create_hangers - called from calla_dedpool in BGND.ASM                 *
*                                                                        *
* Initializes hanger_coords RAM table from ROM defaults, then spawns     *
* NHANGERS fixed hanger processes. Optional player-following chains are  *
* gated off for the current test pass.                                   *
*                                                                        *
**************************************************************************
create_hangers
	movi	deadpool_hanger_runtime_enable,a0
	jrnz	ch_enabled
	rets

ch_enabled
	mmtm	sp,a0,a1,a2,a9,a10

	; copy default x/y into RAM coords table
	movi	hanger_initab,a1	; ROM src (64-bit entries)
	movi	hanger_coords,a2	; RAM dst (32-bit entries)
	movk	NHANGERS,a10
ch_copy
	move	*a1(32),a0,w		; worldx from ROM
	move	a0,*a2,w
	move	*a1(48),a0,w		; worldy from ROM
	move	a0,*a2(16),w
	addi	64,a1
	addi	32,a2
	dsjs	a10,ch_copy

	.if	acid_bubble_preview_only
	create	pid_green_splash,acid_bubble_preview_proc
	clr	a0
	movi	hp_dropped,a1
	move	a0,*a1,w
	movi	hp_drop_busy,a1
	move	a0,*a1,w
	movi	hp_autodrop_ctr,a1
	movi	ed_boon_preview_drop_wait,a0
	move	a0,*a1,w
	mmfm	sp,a0,a1,a2,a9,a10
	rets
	.endif

	; Start every eligible hanger except Ed already dropped (skeleton-visible)
	; so their hanging human body/chain/hook sprites never appear, only the
	; acid skeletons in their fixed corner spots; Eric (drop-ineligible) is
	; unaffected and stays the permanent hanging background body. Ed (index
	; 0) stays live so his EDPOOL.ASM-authored hang/drop/rise sequence runs
	; for real instead of being bypassed -- see hp_uc_hook_deep.
	movi	hp_dropped_init,a1
	movk	1,a0
	move	a0,*a1,w
*
* ONCE PER MATCH, not once per round.  This ran every round and put every body
* back on its hook, so a body that went in during round 1 was hanging whole
* again in round 2.  round_init has already counted the round by the time the
* stage is built (play_1_round: round_init, then do_a11_background), so
* round_num is 1 on the first round of a match - the same test round_init
* uses for drone_model_newmatch.
*
	move	@round_num,a0,w
	cmpi	1,a0
	jrgt	ch_keep_state		; round 2+: whoever went in stays in
	callr	hp_pick_lineup		; and a new match picks a new three
	movi	hp_dropped,a1
	movi	hp_live_now,a2
	movk	NHANGERS,a10
ch_reset_lp
	move	*a2+,a0,w		; live: on its hook (0).  Not live: 1, so
	xori	1,a0			;   no hanging body of theirs can appear
	move	a0,*a1+,w
	dsjs	a10,ch_reset_lp
	movi	first_drop_ticks,a0
	move	a0,@hp_next_drop_ticks,w	; and the countdown starts over
*
* Stagger the idle swings so the nine of them never start together: each
* body's first one is its own roll.
*
	mmtm	sp,a1,a2,a3
	movi	hp_idle_wait,a1
	movi	hp_idle_left,a2
	movk	NHANGERS,a3
ch_idle_lp
	movi	idle_first_span,a0
	calla	randu			; 1..span
	addi	idle_first_min,a0
	move	a0,*a1+,w
	clr	a0
	move	a0,*a2+,w
	dsj	a3,ch_idle_lp
	mmfm	sp,a1,a2,a3
	jruc	ch_state_set
ch_keep_state
*
* A round that ended in the middle of a drop never reached hp_rise_done, so
* it never set the pause.  Set it now, or the next round opens with a second
* body going straight in.
*
	move	@hp_drop_busy,a0,w
	jrz	ch_state_set
	movi	drop_pause_ticks,a0
	move	a0,@hp_next_drop_ticks,w
ch_state_set
	callr	hp_round_cap_roll	; how many may go in THIS round
	movi	hp_view_ticks,a1	; every round, a corner body is watched
	movk	NHANGERS,a10		;   for his ten seconds from zero
	clr	a0
ch_view_clr
	move	a0,*a1+,w
	dsjs	a10,ch_view_clr
	movi	-1,a0
	move	a0,@hp_drop_count_tick,w	; count the first tick of the round

	; no drop sequence is active when a Dead Pool round scene is created
	movi	hp_drop_busy,a1
	clr	a0
	move	a0,*a1,w

	; EDPOOL center-reference body/chain.  PARKED: this draws a second
	; a_edhang1_full on top of the one hanger_proc already builds - two Ed
	; Boons, one of them running its own drop/hold loop.  The real hanger
	; lifecycle below is the one that generalises to the other eight bodies,
	; so the tuning reference stays off.
;	clr	a1
;	not	a1
;	create	pid_edpool_preview,ed_preview_proc

*
* Spawn the three this match is hanging (hp_live_now).  The other six are not
* spawned at all, so no body, chain, hook or skeleton of theirs exists - the
* pool is three bodies wide apart, not a wall of nine.
*
	clr	a9
ch_spawn_lp
	move	a9,a1
	sll	4,a1
	addi	hp_live_now,a1
	move	*a1,a0,w
	jrz	ch_spawn_next
	mmtm	sp,a9			; create hands the child our a9 and may
	create	pid_bani,hanger_proc	;   not hand it back
	mmfm	sp,a9
