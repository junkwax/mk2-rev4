	add	a2,a0
	rets

hp_update_chain
	callr	hp_conn_ptr_slot
	move	*a1,a5,l		; a5 = TINCHAIN4 connector (NEVER a12)
	; Lock acid-state X to the original drop anchor, then use skeleton-
	; specific chain/hook offsets so DEDHANG rises on the same centerline.
*
* THE CHAIN HANGS OFF WHOEVER IS ON THE HOOK, at his own x - body or bones,
* dropping, rising or at rest.  The skeleton used to lock its chain to the drop
* point (hp_splash_x), which is where every path that places him already puts
