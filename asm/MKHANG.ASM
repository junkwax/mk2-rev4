*
* SPREAD THEM.  Every drip used to land on the centre line, which reads as one
* leak rather than a body sheeting.  Walk an eight-entry offset table with the
* lift counter: the offsets are unequal and unordered on purpose, so the eye
* cannot pick the cycle out of a four-second rise.  +-30 covers his 50px width
