**************************************************************************
*                                                                        *
* hanger_splash_proc - Dead Pool hanger-local acid splash                *
*                                                                        *
* The shared BGND green_splash_proc waits forever after deleting its     *
* object. Hangers can trigger many splashes in one match, so clean up    *
* the object safely and release the process slot immediately.            *
*                                                                        *
**************************************************************************
hanger_splash_proc
