	jauc	sucide


**************************************************************************
*                                                                        *
* hp_safe_delobjp - delete an objlst object only if it is still linked    *
*                                                                        *
* Scene cleanup can remove background FX before their child process wakes *
* up. Raw delobjp hard-locks when the object is no longer in objlst.     *
*                                                                        *
**************************************************************************
hp_safe_delobjp
	move	a0,a0
	jreq	hsd_done
	mmtm	sp,a0,a1
	movi	objlst,a1,l
hsd_loop
	move	*a1,a1,l
	jreq	hsd_restore
	cmp	a1,a0
	jrne	hsd_loop
	calla	delobjp
hsd_restore
	mmfm	sp,a0,a1
hsd_done
	rets


