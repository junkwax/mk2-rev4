	cmpi	NHANGERS,a9
	jrlt	ch_spawn_lp

	mmfm	sp,a0,a1,a2,a9,a10
	rets


**************************************************************************
*                                                                        *
* hp_pick_lineup - WHICH THREE BODIES HANG THIS MATCH                    *
*                                                                        *
* Called from create_hangers on the FIRST round of a match only, so the  *
* three it picks are the three rounds 2 and 3 rebuild.  See "THREE       *
* BODIES A MATCH" by NHANGERS for what it is doing and why.              *
*                                                                        *
* Writes hp_live_now.  Clobbers nothing the caller can see.              *
*                                                                        *
**************************************************************************
hp_pick_lineup
	mmtm	sp,a0,a1,a2,a3,a4,a5,a6,a8,a9,a10,a11
	clr	a0
	move	a0,@hp_lead_mask,w	; no lead unless the rotation picks one
*
* The starting point is every body whose art is actually packed.  With the
* rotation off that is the answer, and the stage is what it always was.
*
	movi	hp_live_now,a1
	movi	hanger_acid_live,a2
	movk	NHANGERS,a3
hpl_all
	move	*a2+,a0,w
	move	a0,*a1+,w
	dsj	a3,hpl_all

	.if	hanger_rotate
*
* A rig that wants one particular body every match says so here, and the
* rotation state is not touched - so a run of trials watches the same body and
* the next real match carries on where the rotation left off.
*
	move	@hp_lineup_force,a0,w
	jrz	hpl_rotate
	callr	hp_lineup_from_mask
	jruc	hpl_out

hpl_rotate
	movi	hp_live_now,a1		; nobody, until a zone deals somebody
	movk	NHANGERS,a3
	clr	a0
hpl_none
	move	a0,*a1+,w
	dsj	a3,hpl_none

	clr	a11			; zone 0 = left corner, 1 = the opening
hpl_zone				;   view, 2 = right corner
	move	a11,a0
	callr	hp_zone_members		; a2 = who hangs in this zone at all
	jrz	hpl_zone_next		; an empty corner just stays empty
	cmpi	1,a11
	jrne	hpl_bagged
	move	a2,a10			; the opening view: everybody in it hangs
	callr	hp_pick_stir		; ...and one of them goes in first
	move	a0,a1
	move	a2,a0
	callr	hp_pick_bit
	move	a0,@hp_lead_mask,w
	jruc	hpl_put
hpl_bagged

	move	a11,a8
	sll	4,a8
	move	a8,a9
	addi	hp_zone_bag,a8		; &bag[zone]
	addi	hp_zone_last,a9		; &last[zone]

	move	*a9,a10,w		; who this zone hung last match
	move	*a8,a3,w		; who it has not dealt yet this cycle
	and	a2,a3			; ...still in this zone
	move	a3,a0
	andn	a10,a0			; ...and not the one just seen
	jrnz	hpl_have
*
* The bag is empty (or the layout moved everybody out of it): refill it with
* the WHOLE zone and pick out of that.  The refill is whole on purpose - hold
* the last body out of the BAG and a zone of three deals only two before
* refilling again, which showed one of them four times in eight matches.  He
* is held out of this one PICK instead, so he cannot hang twice running and
* the zone still deals everybody once a cycle.
*
	move	a2,a3
	move	a3,a0
	andn	a10,a0
	jrnz	hpl_have
	move	a3,a0			; a zone of one: he hangs again, there
hpl_have				;   is nobody else to hang
	move	a3,*a8,w		; the bag this pick comes out of
	move	a0,a5			; ...and the candidates out of it
*
* Deal one.  NOT randu, and NOT @tick either: see hp_pick_stir.
*
	callr	hp_pick_stir
	move	a0,a1
	move	a5,a0
	callr	hp_pick_bit		; a0 = exactly one body's bit
	move	a0,a10
	move	*a8,a1,w
	andn	a10,a1
	move	a1,*a8,w		; out of the bag for this cycle
	move	a10,*a9,w		; and he is what this zone hung last
*
* Put him on his hook: hp_live_now[his index] = 1 (every bit set in a10).
*
hpl_put
	movi	hp_live_now,a1
	movk	NHANGERS,a2
	movk	1,a3
hpl_set
	move	a10,a4
	and	a3,a4
	jrz	hpl_set_next
	movk	1,a4
	move	a4,*a1,w
hpl_set_next
	sll	1,a3
	addi	16,a1
	dsj	a2,hpl_set

hpl_zone_next
	inc	a11
	cmpi	NZONES,a11
	jrlt	hpl_zone
hpl_out
	.endif
	mmfm	sp,a0,a1,a2,a3,a4,a5,a6,a8,a9,a10,a11
	rets

*
* hp_pick_stir - the number the pickers choose with.
*
* NOT randu, for this file's own reason (see hp_fx_hold_a0): @rand is the
* GAME's stream, so every extra call shifts the AI's rolls for the rest of the
* round.  And NOT @tick either, which is what this used at first and which
* turned out to be a CONSTANT here - `tick` is in round_init_words, so
* round_init zeroes it and create_hangers runs a few ticks later, every round.
* The probe showed it: the picks were a perfectly regular round-robin, because
* the chooser handed back the same number every time and the bag was doing all
* the work.
*
* So: a private 16-bit xorshift in .bss, which lives across matches and is
* advanced once per pick.  Its seed is the VALUE of @rand - READ, never
* advanced, which costs the stream nothing - so a new match number starts it
* somewhere else.  The BAG is still what guarantees the three are different;
* this only decides the order inside a cycle.
*
* Out: a0.  Clobbers a0,a1.
*
hp_pick_stir
	move	@hp_pick_rand,a0,w
	jrnz	hps_step
	move	@rand,a0,w		; a seed, without consuming a roll
	jrnz	hps_step
	movi	0a5a5h,a0		; ...and never zero: xorshift sticks there
hps_step
	move	a0,a1
	sll	7,a1
	xor	a1,a0
	andi	0ffffh,a0
	move	a0,a1
	srl	9,a1
	xor	a1,a0
	move	a0,a1
	sll	8,a1
	xor	a1,a0
	andi	0ffffh,a0
	jrnz	hps_keep
	movi	0a5a5h,a0
hps_keep
	move	a0,@hp_pick_rand,w
	rets

*
* hp_round_cap_roll - how many bodies may go into the acid THIS ROUND, rolled
* once per round by create_hangers.  See "How many fall in a round".
* Clobbers a0,a1.
*
hp_round_cap_roll
	clr	a0
	move	a0,@hp_round_drops,w
	callr	hp_pick_stir
	andi	0ffh,a0
	movk	drops_per_round_span,a1
hrc_mod
	cmp	a1,a0
	jrlt	hrc_set
	sub	a1,a0
	jruc	hrc_mod
hrc_set
	addi	drops_per_round_min,a0
	move	a0,@hp_round_cap,w
	rets

*
* hp_lineup_from_mask - a0 = a bitmask of bodies.  Writes hp_live_now from it,
* keeping only the ones whose art is packed, so a forced lineup cannot hang a
* body that has no bands cut.  Clobbers a0-a5.
*
hp_lineup_from_mask
	movi	hp_live_now,a1
	movi	hanger_acid_live,a2
	movk	NHANGERS,a3
hlfm_loop
	move	a0,a4
	andi	1,a4
	srl	1,a0
	move	*a2+,a5,w		; no art packed for him?
	jrnz	hlfm_keep
	clr	a4			;   then he is not hanging whatever the
hlfm_keep				;   mask says
	move	a4,*a1+,w
	dsj	a3,hlfm_loop
	rets

*
* hp_zone_members - a0 = zone.  Out: a2 = a bitmask of the bodies that hang in
* it and have their art packed, flags set on it (Z = the zone is empty).
* Reads hanger_coords, which create_hangers has already filled from the
* layout, so a body moved in the layout editor changes zones with no table to
* keep in step.  Clobbers a0-a6.
*
hp_zone_members
	move	a0,a5			; the zone we are collecting
	clr	a2
	movi	hanger_coords,a1
	movi	hanger_acid_live,a3
	movk	1,a6			; bit for the body we are looking at
	movk	NHANGERS,a4
hzm_loop
	move	*a3+,a0,w		; art packed?
	jrz	hzm_next
	move	*a1,a0,w		; his world x - hanger_coords +0
	callr	hp_zone_of_x
	cmp	a5,a0
	jrne	hzm_next
	or	a6,a2
hzm_next
	sll	1,a6
	addi	32,a1			; next 32-bit coords entry
	dsj	a4,hzm_loop
	move	a2,a2			; flags for the caller
	rets

*
* hp_zone_of_x - a0 = a body's world x (his LEFT edge, as hanger_initab gives
* it).  Out: a0 = 0 left corner, 1 the view the round opens on, 2 right
* corner.  Clobbers a0 only - hp_zone_members holds everything else live
* across it.
*
hp_zone_of_x
	cmpi	hz_mid_lo,a0
	jrlt	hzx_left
	cmpi	hz_mid_hi,a0
	jrgt	hzx_right
	movk	1,a0
	rets
hzx_left
	clr	a0
	rets
hzx_right
	movk	2,a0
	rets

*
* hp_pick_bit - a0 = a bitmask with at least one bit set, a1 = any number to
* choose with.  Out: a0 = exactly one of a0's bits.  Clobbers a0-a4.
*
* The mask never has more than NHANGERS bits, so the count is a walk and the
* modulo is a subtract loop - modu is not used anywhere in this tree.
*
hp_pick_bit
	move	a0,a3
	clr	a2			; how many bodies are in the bag
hpb_count
	move	a3,a3
	jrz	hpb_counted
	move	a3,a4
	andi	1,a4
	jrz	hpb_count_next
	inc	a2
hpb_count_next
	srl	1,a3
	jruc	hpb_count
hpb_counted
	andi	0fh,a1			; a1 = a1 mod a2, and a2 >= 1 because the
hpb_mod					;   caller was given a non-empty bag
	cmp	a2,a1
	jrlt	hpb_walk
	sub	a2,a1
	jruc	hpb_mod
hpb_walk
	movk	1,a3			; step over the set bits a1 times
hpb_walk_loop
	move	a0,a4
	and	a3,a4
	jrz	hpb_walk_next
	move	a1,a1
	jrz	hpb_walk_done
	dec	a1
hpb_walk_next
	sll	1,a3
	jruc	hpb_walk_loop
hpb_walk_done
	move	a3,a0
	rets


**************************************************************************
