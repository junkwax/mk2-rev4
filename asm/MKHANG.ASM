*
* THE DROP SCHEDULE.  Every body hanging this match (hp_live_now - three of
* the nine, see hp_pick_lineup) goes in once per MATCH,
* and a body only lets go WHILE HE IS ON SCREEN (hp_drop_in_view: his whole
* body inside the camera) - nobody goes into the acid where no one can see
* it.  Between drops there is a pause of at least drop_pause_ticks (15s),
* counted from the moment the previous body is back up on his hook, and only
* while a fight is live.  NOBODY GOES IN FOR THE FIRST first_drop_ticks (15s)
* OF A MATCH - the round opens on a clean pool and the fight gets going before
* the stage starts doing things.  That is 15 seconds of FIGHTING: the
* countdown is armed when the stage is built but only counted while a round is
* live (hp_drop_count), so the intro, a pause and the round banners do not
* spend it.
*
* NOT IN ORDER.  Whoever is on screen when the pause is up goes next.  A
* fixed order (Ed, Tony, John) stalled the whole pool whenever the next in
* line was off screen - the camera follows the fighters, and at rest it only
* shows world 373..773, so Tony at 892 could hold everyone up for a round.
* Two in view at once: the first process to run takes hp_drop_busy, and the
* other waits out the next pause.
*
* ONE COUNTDOWN, hp_next_drop_ticks, counted down ONCE A TICK whichever
* bodies' processes are asking: hp_drop_count stamps @tick, so the second
* process to ask in the same tick does not count it again.
*
* ONCE IN, STAYS IN.  hp_dropped and the countdown are reset only on the first
* round of a match (round_init has already counted it: round_num 1); rounds 2
* and 3 respawn a dropped body as his skeleton on the hook, and the countdown
* carries over.
*
*
* THE LEAD.  One of the opening-view bodies, picked at random each match
* (hp_lead_mask), goes in FIRST, first_drop_ticks into the fight - 9.5s, the
* user's call 2026-10-05 ("within 10 seconds of the match starting").  The
* corner bodies do not start their ten seconds until he is in, and the other
* front bodies still wait for the corners.
*
