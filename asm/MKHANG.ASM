**************************************************************************
*                                                                        *
* hp_update_chain - keep chain/hook connected through the acid pull      *
*                                                                        *
* Normal hanging bodies show the long chain, short connector, and hook.  *
* Once a body reaches the acid cut line, longchain stays planted on that *
* line while the connector/hook stay hidden until they can clear the lip.*
*                                                                        *
* Input: a8=body, a10=chain, a11=hook; connector read from hp_conn_ptr   *
* Clobbers a5 (the connector) - a12 is the process stack, never touch it *
* Clobbers: a0, a1, a2, a3, a4                                          *
*                                                                        *
**************************************************************************
*
* hp_sway_a0 - THE SWING on the way down.  As he is lowered he sways a little
* side to side, and the chain and hook go with him (hp_update_chain hangs them
* off his x).  sway_tab is one cycle, a step a fall move - 16 moves at
* drop_ticks 4 is ~1.2 seconds - and once the acid has hold of his feet
* (hp_breached) the swing halves: the liquid damps it.  hp_body_submerge puts
* him back on his column, so he goes under dead centre and the splash, the
* bubbles and the bones all stay on it.  Down only: the bones come up straight.
*
* In: a0 = his column.  Out: a0 = column + swing.  Clobbers a1, a2.
*
*
* hp_idle_sway_a0 - A BODY ON A HOOK IS NEVER QUITE STILL.  Every
* idle_sway_min + randu(idle_sway_span) ticks (10..25s) a hanger leans ONE
* pixel through idle_sway_tab - at his own speed (hanger_idle_hold) and his
* own way first (hanger_idle_dir) - then hangs straight until his next one.
* Each body rolls his own wait, in create_hangers and after every lean, so
* no two move alike or together.
*
* In: a0 = his column.  Out: a0 = column + this tick's lean.  Clobbers a1, a2.
*
hp_idle_sway_a0
	mmtm	sp,a3
	move	a0,a3			; keep the column
	callr	hp_idle_left_slot
	move	*a1,a0,w
	jrgt	his_swinging
*
* Hanging straight: count down to the next one.
*
	callr	hp_idle_wait_slot
	move	*a1,a0,w
	dec	a0
	move	a0,*a1,w
	jrgt	his_still
	callr	hp_idle_hold_slot	; his turn: start one, his own length -
	move	*a1,a1,w		;   16 steps of 1 << hold ticks
	movk	16,a0
	sll	a1,a0
	callr	hp_idle_left_slot
	move	a0,*a1,w
his_still
	move	a3,a0
	mmfm	sp,a3
	rets

his_swinging
	dec	a0			; one tick of it gone
	callr	hp_idle_left_slot
	move	a0,*a1,w
	jrnz	his_lean
*
* That was the last tick - hang straight again and roll the next wait.
*
	movi	idle_sway_span,a0
	calla	randu
	addi	idle_sway_min,a0
	callr	hp_idle_wait_slot
	move	a0,*a1,w
	move	a3,a0
	mmfm	sp,a3
	rets

his_lean
*
* Which step of the lean: ticks done so far / 16, so each entry holds 16 ticks
* and the whole thing takes ~4.7 seconds.  It was sway_tab at one entry a
* tick - the drop's swing, at half size - and that read as a wobble.
*
	mmtm	sp,a4
	callr	hp_idle_hold_slot
	move	*a1,a4,w		; his step length, as a shift
	movk	16,a1
	sll	a4,a1			; his whole lean, in ticks
	sub	a0,a1			; ticks of it done
	neg	a4			; ...in steps.  SRL BY A REGISTER SHIFTS BY THE
	srl	a4,a1			;   NEGATED count: plain `srl a4,a1` with a4 = 4
					;   shifted 28, every step read as 0 and
					;   nobody ever leaned
	andi	0fh,a1
	sll	4,a1
	addi	idle_sway_tab,a1
	move	*a1,a2,w
	callr	hp_idle_dir_slot
	move	*a1,a1,w
	jrnn	his_dir_ok
	neg	a2			; he leans the other way first
his_dir_ok
	move	a3,a0
	add	a2,a0
	mmfm	sp,a4
	mmfm	sp,a3
	rets

hp_idle_hold_slot
	callr	hp_index_a1
	sll	4,a1
	addi	hanger_idle_hold,a1
	rets

hp_idle_dir_slot
	callr	hp_index_a1
	sll	4,a1
	addi	hanger_idle_dir,a1
	rets

hp_idle_wait_slot
	callr	hp_index_a1
	sll	4,a1
	addi	hp_idle_wait,a1
	rets

hp_idle_left_slot
	callr	hp_index_a1
	sll	4,a1
	addi	hp_idle_left,a1
	rets

hp_sway_a0
	move	@hp_sway_step,a1,w
	addk	1,a1
	move	a1,@hp_sway_step,w
	andi	0fh,a1
	sll	4,a1
	addi	sway_tab,a1
	move	*a1,a2,w		; this step's swing, +-3
	move	a0,a1			; (keep the column)
	callr	hp_breached_slot
	move	*a1,a1,w
	jrz	hp_sway_full
	sra	1,a2			; in the acid: half the swing
hp_sway_full
